import { MAX_TRIP_STOPS, type TripStop } from "@/lib/booking-types";
import type { GeoPlace } from "@/lib/pricing-types";

/**
 * محطاتُ الرحلة الوسطى — **مُساعِداتُ العرض** فوق عقد `lib/booking-types.ts`.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 والنوعُ والسقفُ **يُستوردان ولا يُعادان تعريفاً**
 * ══════════════════════════════════════════════════════════════════════════
 * `TripStop` و`MAX_TRIP_STOPS` يعيشان في `lib/booking-types.ts` — عقدُ الحجز
 * الأعلى، ويقرؤه معنا مسارا `/api/quote` و`/api/booking` ومحرّكُ المسافة. وهذه
 * الوحدة **تُعيد تصديرهما ولا تنسخهما**: نسخةٌ ثانية للسقف كانت ستعني أن يعرض
 * الويدجت زرّ «أضف محطة» بعدَدٍ يرفضه الخادم (‏النمط ٨ في `handover/LESSONS.md`:
 * مصدران لرقمٍ واحد ينحرفان حتماً). وقد كُتبت هذه الوحدة أوّلَ مرةٍ بنسخةٍ
 * محلّية بسقف ٣ بينما العقد ٥ — وهو الانحراف بعينه، فأُزيل.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔒 وحدةٌ محيَّدة — بلا `"use client"` وبلا `server-only`
 * ══════════════════════════════════════════════════════════════════════════
 * يقرؤها الطرفان من نسخةٍ واحدة: ويدجت الحجز ومسارُ الدفع (عميل) وشاشاتُ اللوحة
 * والبورتال وصفحةُ المتابعة (خادم). ووضعُ `"use client"` في أعلاها يُحيل كلَّ
 * ثابتٍ فيها إلى **مرجع عميل** عند أول قارئٍ خادمي — والعطل صامت: `clsx` يُسقط
 * القيمة بلا شكوى، ولا بناءٌ يحمرّ (القسم ٥ في `handover/LESSONS.md`).
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 والقاعدة المالية التي تفسّر كلَّ نصٍّ في هذه الشاشات
 * ══════════════════════════════════════════════════════════════════════════
 * المتعهد سعّر **مساراً مباشراً** من منطلقٍ إلى وجهة. ورحلةٌ بمحطةٍ وسطى أطولُ
 * زمناً ومسافةً ومستحقُّه لا يتغيّر — فيقود أطولَ بثمنِ رحلةٍ أقصر. ولذلك:
 * **رحلةٌ ذاتُ محطاتٍ وسطى لا تُسعَّر من قائمة أسعار متعهدٍ إطلاقاً**، بل
 * بالتعريفة على المسافة الحقيقية متعددة الأرجل (‏`TripSnapshot.stops` في العقد).
 *
 * ⚠ **والواجهة تقول ذلك للعميل صراحةً قبل الدفع لا عنده**: جملةٌ واحدة صادقة
 * («قد يكون الإجمالي أعلى») خيرٌ من مفاجأةٍ في الخطوة الأخيرة. والإنفاذُ نفسه
 * في القاعدة لا هنا (**D-05**) — هذه الوحدة تعرض ولا تُسعّر.
 */

export { MAX_TRIP_STOPS };
export type { TripStop };

/**
 * 🔴 **سقفان لا سقفٌ واحد — والفرقُ بينهما هو الفرقُ بين رفضٍ ورفضٍ مؤجَّل.**
 *
 * | الرقم | مَن يفرضه | ماذا يعني تجاوزُه |
 * |---|---|---|
 * | `MAX_TRIP_STOPS` (‏٥) | ثابتٌ في `lib/booking-types.ts` | حدُّ كلفةٍ مطلق: مُحلِّلا `/api/quote` و`/api/booking` يرفضان، ومحرّكُ المسافة لا يقيس خارجياً |
 * | `max_trip_stops()` (‏افتراضُه **٣**) | عمودٌ في `trip_settings` يضبطه المالك، ويفرضه المُشغّل `bookings_guard_trip_stops` (‏هجرة `0140`) | الحجزُ يُرفض — **بعد** أن يرى العميل السعر |
 *
 * وهذا الثابت **نسخةُ افتراضِ العمود** يستعملها الويدجت حين يتعذّر بلوغُ القراءة
 * الخادمية (‏`getStopsCap` في `stops-cap.ts`, وهي `server-only` فلا يستوردها
 * متصفح). وموضعُه هنا لا هناك لأن هذه الوحدة **محيَّدة**: يقرؤها الطرفان من
 * نسخةٍ واحدة، ووضعُ الرقم في ملفٍّ `server-only` كان يمنع العميل من قراءته
 * أصلاً، ووضعُه في ملفٍّ `"use client"` كان يجعله **مرجعَ عميل** عند القارئ
 * الخادمي (القسم ٥ في `handover/LESSONS.md`).
 *
 * ⚠ تغيّرَ افتراضُ العمود في هجرةٍ لاحقة؟ فهذا السطر يتبعه — ولا ثالثَ لهما.
 */
export const DEFAULT_STOPS_CAP = 3;

/** نقطةٌ من منتقي الأماكن ⇐ محطة. الوسم وحده يُنقل، والإحداثيات كما هي. */
export function toTripStop(place: GeoPlace): TripStop {
  return { label: place.label, lat: place.lat, lng: place.lng };
}

/** رقمٌ محدود فعلاً — `NaN` و`Infinity` و`"12"` كلها ليست إحداثياً */
function finiteNumber(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function textOf(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

/**
 * قراءةُ المحطات من **لقطة رحلةٍ مجهولة الشكل** — `bookings.trip` كما تصل من
 * `get_booking_by_token`، أو من عمود `jsonb` في اللوحة، أو من صفّ البورتال.
 *
 * 🔴 **والغياب رحلةٌ بنقطتين، لا خطأ.** ثمانية عشر حجزاً قائماً بلا هذا الحقل،
 * وكودٌ منشورٌ لا يعرفه — فهذا القارئ يجيب `[]` عن الغياب وعن `null` وعن الشكل
 * الفاسد معاً، ولا يرمي ولا يُسقط صفحةً.
 *
 * وتُقبل الأسماء بالشكلين (camelCase من الواجهة، snake_case لو كتبها SQL
 * مباشرةً) — نفس ما يفعله `readText(trip, "originLabel", "origin_label")` في
 * صفحة المتابعة، ولنفس السبب: اللقطة `jsonb` لا جدول، وشكلُها عهدٌ لا عمود.
 */
export function readTripStops(trip: unknown): TripStop[] {
  if (!trip || typeof trip !== "object" || Array.isArray(trip)) return [];
  const record = trip as Record<string, unknown>;
  const raw = record.stops ?? record.tripStops ?? record.trip_stops;
  if (!Array.isArray(raw)) return [];

  const out: TripStop[] = [];
  for (const item of raw) {
    if (!item || typeof item !== "object" || Array.isArray(item)) continue;
    const entry = item as Record<string, unknown>;
    const lat = finiteNumber(entry.lat);
    const lng = finiteNumber(entry.lng);
    // 🔒 **D-09 حرفياً**: محطةٌ بلا إحداثيات لم تدخل حساب المسافة، فعرضُها
    //    نقطةً على المسار ادّعاءٌ بأن الرحلة تمرّ بما لم يُحسب لأجله شيء.
    //    والمسارات ترفضها عند الإدخال أصلاً — وهذا حارسُ القراءة لا بديلٌ عنه.
    if (lat === null || lng === null) continue;
    const label = textOf(entry.label) || textOf(entry.stopLabel) || textOf(entry.stop_label);
    out.push({ label, lat, lng });
    // السقف من العقد نفسه — لقطةٌ فيها أكثر تعني بيانةً لا نثق بها، فلا تُعرض
    // بطولٍ لا حدَّ له على شاشةٍ تشرح قراراً
    if (out.length >= MAX_TRIP_STOPS) break;
  }
  return out;
}

/**
 * نقاطُ المسار بالترتيب الذي يُقاد به: المنطلق ثم المحطات ثم الوجهة.
 *
 * موضعُها هنا لا في كل شاشة: ستُّ شاشاتٍ تعرض المسار (اللوحة قائمةً وتفصيلاً ·
 * طابور التشغيل · البورتال · بطاقة العروض · متابعة العميل)، ونسخةٌ في كلٍّ منها
 * تعني ستةَ ترتيباتٍ تنحرف بأول تعديل (القاعدة الذهبية ١٢: لا يُستنسخ منطق —
 * يُفوَّض إليه).
 *
 * والوسمُ الفارغ يُستبدل بـ`fallback` ولا يُحذف: **المحطةُ موجودةٌ في المسار حتى
 * لو غاب اسمها**، وإسقاطُها يجعل الشاشة تعرض طريقاً أقصر مما سيُقاد.
 */
export function routePointLabels(
  originLabel: string,
  stops: readonly TripStop[],
  destLabel: string,
  fallback = "—"
): string[] {
  const clean = (value: string) => (value.trim().length > 0 ? value.trim() : fallback);
  return [clean(originLabel), ...stops.map((stop) => clean(stop.label)), clean(destLabel)];
}

/**
 * بصمةُ المحطات — تدخل مفاتيحَ «هل تغيّرت مُدخلات السعر؟».
 *
 * 🔴 **والترتيب جزءٌ من البصمة لا زينة**: نفسُ المحطتين بترتيبٍ مقلوب مسارٌ آخر
 * بمسافةٍ أخرى — فتبديلُهما يجب أن يُسقط السعر المعروض كما يُسقطه حذفُ محطة.
 */
export function stopsFingerprint(stops: readonly TripStop[]): string {
  return stops.map((stop) => `${stop.lat},${stop.lng}`).join(">");
}
