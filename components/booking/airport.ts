/**
 * هل هذه رحلة مطار؟ — **الإشارة الوحيدة الموجودة في البيانات: وسمُ المكان.**
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ما بُحث عنه أولاً، ولماذا لم يوجد
 * ══════════════════════════════════════════════════════════════════════════
 *
 * قِيس على القاعدة الحيّة (2026-08-16) قبل كتابة سطر: **لا جدول `services`
 * ولا `airports` ولا أي رابطٍ بين الحجز ونوع الخدمة** — الخدمات في هذا
 * المنتج **محتوى تسويقي** (‏`pages`/`sections`)، و`bookings` لا تحمل
 * `service_slug` أصلاً. فقائمةُ رموزٍ ثابتة لم تكن خياراً مرفوضاً بل خياراً
 * **غير قائم**: لا رمز يُقارَن به.
 *
 * والإشارة الأقوى نظرياً — تصنيف Nominatim (‏`category=aeroway`) — **ليست
 * ملتقَطة**: `lib/geo/geocode.ts` ينادي `format=jsonv2` ويحتفظ بالوسم
 * والإحداثيات و`osm_type/osm_id` فقط، والكاش الدائم (`geocode_cache`) مليء
 * بصفوفٍ بُنيت على ذلك الشكل. فالتقاطها اليوم يعني تعديل طبقة الجيوكودنج
 * **وإبطال الكاش كله** كي لا يبقى مطارٌ محفوظٌ بلا تصنيف — عملٌ أوسع من هذا
 * البند بكثير، وهو مكتوب في تقرير التسليم بوصفه **ما لم يُفعل عن قصد**.
 *
 * فبقي الوسم: `مطار القاهرة، القاهرة` كما يُخزَّن في `trip.originLabel` /
 * `trip.destLabel` لكل حجزٍ قائم منذ اليوم الأول.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔒 والحدود على النمط ليست تجميلاً — الدرس ١٣ في القواعد الذهبية
 * ══════════════════════════════════════════════════════════════════════════
 *
 * بحثٌ نصّي بلا تطويق يمسك ما لم يُقصد: «المطارية» و«مطارق». والعربية لا
 * تعرف `\b` في محرك JS بمعنىً مفيد (كل حرف عربي `\w` عند بعض المحركات ولا
 * شيء عند غيرها)، فالتطويق هنا **صريح**: ما قبل الكلمة ليس حرفاً، وما بعدها
 * ليس حرفاً — مع السماح ببادئة `ال` وبالتاء المربوطة في «مطارات».
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  وأثره **إظهارُ حقلٍ لا غير** — لا سعر ولا قبول
 * ══════════════════════════════════════════════════════════════════════════
 *
 * الخطأ في الاتجاهين رخيص ومقصود: مطارٌ لم يُعرَف ⇒ لا يظهر الحقل والعميل
 * يكتب رقمه في الملاحظات كما اليوم (بلا انحدار)؛ ومكانٌ اسمه فيه «مطار» وليس
 * مطاراً ⇒ يظهر حقلٌ **اختياري** يتجاهله. ولذلك يعيش هذا الحكم في الواجهة
 * ولا يُنقل إلى SQL: لا مالَ يتوقّف عليه ولا حجزَ يُرفض به، وقاعدة D-05 تخصّ
 * الحساب لا إظهار حقل.
 */

/**
 * كلمات المطار في اللغتين اللتين يُكتب بهما الوسم فعلاً.
 *
 * ولماذا لا تُقرأ من الإعدادات (D-04)؟ لأن D-04 يخصّ **نصوص العلامة** — اسمها
 * وألوانها وأرقامها — وهذه مفرداتُ لغةٍ لا مفرداتُ علامة، شأنها شأن «مصر»
 * و«Egypt» في `lib/geo/geocode.ts:54` حرفياً. ونسخةُ whitelabel في سوقٍ آخر
 * تضيف كلمتها هنا كما تضيف لغتها إلى `messages/`.
 */
const AIRPORT_PATTERNS: readonly RegExp[] = [
  // العربية: «مطار» و«المطار» و«مطارات» — مطوّقة بما ليس حرفاً عربياً أو لاتينياً
  /(?:^|[^\p{L}])(?:ال)?مطار(?:ات)?(?:$|[^\p{L}])/u,
  // الإنجليزية: الوسم يعود لاتينياً حين يكتب الزائر بالإنجليزية
  /(?:^|[^\p{L}])airports?(?:$|[^\p{L}])/iu,
  // اختصارٌ شائع في الأوسام اللاتينية لمطارات مصر (Intl Airport ⇐ يمسكه ما فوق)
  /(?:^|[^\p{L}])a[eé]roports?(?:$|[^\p{L}])/iu,
];

/** هل يبدو هذا الوسم وسمَ مطار؟ */
export function isAirportLabel(label: string | null | undefined): boolean {
  const text = (label ?? "").trim();
  if (text === "") return false;
  return AIRPORT_PATTERNS.some((pattern) => pattern.test(text));
}

/**
 * رحلة مطار = **أحد طرفيها** مطار — الوصول إليه أو المغادرة منه سواء.
 *
 * ورقم الرحلة مفيدٌ في الحالتين ولسببين مختلفين: في الاستقبال يعرف السائق
 * متى تهبط الطائرة فعلاً، وفي التوصيل يعرف الموعد الذي لا يجوز أن يتأخر عنه.
 */
export function isAirportTrip(
  originLabel: string | null | undefined,
  destinationLabel: string | null | undefined
): boolean {
  return isAirportLabel(originLabel) || isAirportLabel(destinationLabel);
}
