/**
 * تذكّر حساب التحويل الأخير — ن‑٩ (ب-٣): «العائد لا يُعيد القرار».
 *
 * ── لماذا كوكي، ولماذا هذا القدر منها بالضبط ───────────────────────────────
 *
 * القرار الذي يُتذكَّر هو **أي حسابٍ حوّل إليه هذا المتصفح آخر مرة**. وقيمته
 * `uuid` حسابٍ **من حساباتنا نحن** — لا رقم محفظة، ولا مبلغ، ولا شيء يخصّ
 * العميل. فالمخزَّن ليس بياناً شخصياً بل **تفضيل واجهة**، ولذلك يُقرأ على
 * الخادم فيصل الاختيار مع أول HTML بلا وميضٍ ولا جافاسكربت.
 *
 * ⚠ **ولا يُربط بالحجز إطلاقاً**: مفتاحٌ واحد لكل المتصفح، بلا توكن ولا مرجع.
 *   كوكي باسمٍ فيه توكن الحجز كانت ستُسرِّب مفتاح الصفحة إلى كل طلبٍ لاحق —
 *   وهو بعينه ما تحذّر منه `lib/export-types.ts` §٥ («الرابط نفسه هو بيانات
 *   الاعتماد»).
 *
 * 🔒 **والمعرّف لا يُصدَّق أبداً.** ما يُقرأ من الكوكي يُطابَق بالقائمة التي
 *    ترجعها `available_payment_accounts` وحدها؛ فقيمةٌ ملفَّقة — أو حسابٌ أطفأه
 *    بدر بعد آخر زيارة — **تسقط بلا أثر** ويعود الاختيار إلى الأول. أي أن هذه
 *    الكوكي لا تستطيع أن تُظهر حساباً لا تعرضه القاعدة (‏ن‑٩ أ: التعريف الواحد).
 */

/**
 * اسم مجموعة الراديو في منتقي التحويل — **معرَّفٌ في مكان واحد لأن ثلاثة يقرؤونه**:
 * المنتقي يسمّي به مدخلاته، و`RememberTransferAccount` يرشّح به الأحداث،
 * و`ReceiptUpload` يتابع به الاختيار. ونصٌّ مكرَّر في ثلاثة ملفات ينحرف بصمت
 * فيتوقف التتبّع بلا خطأ يظهر.
 */
export const TRANSFER_GROUP = "transfer-account";

/** اسم الكوكي — يقرؤه الخادم ويكتبه `RememberTransferAccount` في المتصفح */
export const TRANSFER_ACCOUNT_COOKIE = "tours_transfer_account";

/** ستة أشهر: أطول من أي دورة حجزٍ، وأقصر من «إلى الأبد» */
export const TRANSFER_ACCOUNT_COOKIE_MAX_AGE = 180 * 24 * 60 * 60;

/** شكل `uuid` — يُفحص قبل أي استعمال، فالكوكي نصٌّ يكتبه من يشاء */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isAccountId(value: string | null | undefined): value is string {
  return typeof value === "string" && UUID.test(value);
}

/**
 * أي خيارٍ يبدأ مختاراً؟ **المتذكَّر إن كان ما زال معروضاً، وإلا فالأول.**
 *
 * والأول هو الأرخص بعد الهجرة `0070` (‏ن‑٩ ب-٤)، فالافتراضي في غياب التفضيل
 * هو الأوفر — لا ما صادف أن كان أعلى القائمة.
 *
 * @param ids معرّفات الحسابات **كما وصلت من القاعدة**، بترتيبها
 * @param remembered قيمة الكوكي كما قُرئت، بلا تنظيف مسبق
 */
export function preferredAccountId(
  ids: readonly string[],
  remembered: string | null | undefined
): string | null {
  if (ids.length === 0) return null;
  if (isAccountId(remembered) && ids.includes(remembered)) return remembered;
  return ids[0];
}
