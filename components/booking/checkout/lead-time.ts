import "server-only";

import { createServiceSupabase } from "@/lib/supabase/admin";

/**
 * أدنى مهلة قبل الانطلاق — **قراءةُ ما تقرّره القاعدة، لا حسابٌ يوازيه.**
 *
 * ── لماذا هذا الملف أصلاً ─────────────────────────────────────────────────
 * حجزٌ موعده بعد عشر دقائق لا يمكن تنفيذه: البثّ يعمل بموجاتٍ مؤقّتة
 * (‏`window_minutes` × `max_rounds`) قبل أن يتحرّك أحد، والمتعهد يحتاج زمن
 * وصولٍ فوق ذلك. فالحارس في `create_booking` (هجرة `0067`) يرفضه — والواجهة
 * يجب أن **تمنع اختياره** لا أن تقبله ثم تعتذر بعد أن مُلئ النموذج كاملاً.
 *
 * ── ⚠ ولماذا لا تُحسب المعادلة هنا ───────────────────────────────────────
 * لأنها نفس الفخّ الذي وقعت فيه مهلة الدفع قبل `0052`: رقمٌ في الإعدادات
 * تعيد الواجهة تركيبه بيدها فينحرف عن الحارس أول يوم يتغيّر أحدهما (النمط ٨
 * في `handover/LESSONS.md` — مصدران لرقم واحد). فالمُنادى هنا
 * **`booking_min_pickup_at()`** — الدالة **نفسها** التي يناديها `create_booking`
 * في شرطه حرفياً. ما تسمح به الشاشة هو ما تقبله القاعدة، بالتعريف.
 *
 * ── ولماذا بمفتاح الخدمة لا بنداءٍ من المتصفح ────────────────────────────
 * `booking_min_pickup_at()` **غير ممنوحة لـ`anon` ولا `authenticated`** عمداً
 * (‏`0067` §٣ · D-53): هي تكشف رقم سياستنا التشغيلية بلا سياق، وكل متعهد
 * مستخدم `authenticated`. فالقراءة هنا بعميل الخدمة، وهي **قراءة لحظةٍ لا
 * كتابة**، ويصل إلى المتصفح ما يحتاجه العميل ليختار موعداً وحسب.
 *
 * ⚠ وهي تختلف في ذلك عن `booking_hold_until` (‏`0052`) الممنوحة لـ`anon`
 * بقصد: تلك تأخذ طابعَي حجزٍ بعينه وترجع وعداً يخصّه، وصفحة `/booking/[token]`
 * عامةٌ بلا جلسة فلا سبيل غيرها. وهذه لا سبيل لها إلا هذا الإجراء الخادمي.
 *
 * ── والفشل يقع صامتاً وفي الاتجاه المتساهل ───────────────────────────────
 * بلا `SUPABASE_SERVICE_ROLE_KEY`، أو بهجرةٍ غير مطبَّقة، أو بأي خطأ: يعود
 * `enabled: false` فلا تُشدَّد أرضية المنتقي. و**التساهل هو الاتجاه الصحيح
 * هنا** بالضبط لأن الحارس الحقيقي في القاعدة: أسوأ ما يقع أن يختار العميل
 * موعداً يرتدّ برسالة صريحة (‏`lead-time`)؛ أما التشديد على تخمين فيمنع
 * حجوزاً سليمة بلا أن يعرف أحد لماذا.
 */

export type LeadTime = {
  /** المهلة مضبوطة فعلاً (> صفر) — وهو شرط عرض أي أرضية أو جملة */
  enabled: boolean;
  /**
   * ISO — **أقرب لحظة انطلاق تقبلها القاعدة**، محسوبةً من `now()` على الخادم.
   *
   * 🔒 «تقبلها» لا «ترفض ما قبلها بلحظة»: الحارس يقارن بـ`<` فالمساوي مقبول،
   * فما يُعرض هنا بوصفه «أقرب موعد متاح» هو موعدٌ **يمرّ** فعلاً لو اختير في
   * الحال. ولذلك يجب على القارئ أن يقرّب لأعلى إلى أول خانةٍ يستطيع المنتقي
   * إظهارها (دقيقة كاملة)، وإلا عرض لحظةً بثوانٍ لا يمكن اختيارها أصلاً.
   */
  minPickupAt: string | null;
  /**
   * المهلة بالدقائق — **للجملة الموجَّهة للعميل وحدها** («نحتاج مهلة ساعتين
   * على الأقل»)، لا لحسابِ تاريخٍ في المتصفح. والرقم ليس سرّاً: هو بعينه ما
   * تقوله رسالة الرفض لأي عميل يحاول موعداً أقرب.
   */
  leadMinutes: number;
};

const NO_LEAD: LeadTime = { enabled: false, minPickupAt: null, leadMinutes: 0 };

/**
 * أقرب موعد انطلاق مقبول الآن — أو `NO_LEAD` حين لا قيد أو تعذّرت القراءة.
 *
 * ⚠ **لا مُدخل لها بقصد.** كل ما تحتاجه القاعدةُ لتقرّر هو ساعتُها وإعداداتها،
 * وكلاهما عندها. فلا شيء من المتصفح يدخل في هذا الجواب — ولا شيء يُصدَّق.
 */
export async function readLeadTime(): Promise<LeadTime> {
  const service = createServiceSupabase();
  if (!service) return NO_LEAD;

  try {
    const [minRes, cfgRes] = await Promise.all([
      service.rpc("booking_min_pickup_at"),
      // الرقم للعرض وحده — والعمود يُقرأ من الجدول لا من `trip_config()` التي
      // ليست ممنوحة لأي دور مستخدم (نفس تعليل `lib/trip-settings.ts`).
      service.from("trip_settings").select("min_lead_minutes").limit(1).maybeSingle(),
    ]);

    if (minRes.error) return NO_LEAD;

    const iso = typeof minRes.data === "string" ? minRes.data : null;
    // `null` من الدالة يعني «لا قيد» صراحةً — لا «الآن»، ولا خطأً يُبتلع
    if (iso === null || !Number.isFinite(Date.parse(iso))) return NO_LEAD;

    const raw = cfgRes.error ? null : (cfgRes.data as { min_lead_minutes?: unknown } | null);
    const minutes = Number(raw?.min_lead_minutes ?? 0);

    return {
      enabled: true,
      minPickupAt: iso,
      leadMinutes: Number.isFinite(minutes) && minutes > 0 ? Math.round(minutes) : 0,
    };
  } catch {
    return NO_LEAD;
  }
}
