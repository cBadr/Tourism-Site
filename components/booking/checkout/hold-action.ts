"use server";

import { readPaymentHold, type PaymentHold } from "./hold";

/**
 * معاينة مهلة الدفع لخطوة «الدفع» في الحاسبة — **دالة خادمية لا مسار جديد.**
 *
 * ── لماذا لا خاصية (prop) تُمرَّر من صفحة خادمية ──────────────────────────
 * نموذج الحجز يعيش داخل ويدجت العميل (‏`search-widget` ← `offers` ← `checkout`)
 * وهو جزيرةُ عميلٍ تُركَّب في أكثر من صفحة خادمية — وهو بعينه السبب المكتوب في
 * ترويسة `/api/booking/settings` لوجود ذلك المسار بدل تمرير الإعدادات عبر كل
 * شجرة استدعاء. فالحاجة قديمة والجواب هنا أضيق: دالة خادمية واحدة بدل مسارٍ
 * عام جديد (**ولا مسار يُنشأ تحت `app/` في هذه الموجة أصلاً**).
 *
 * ── وماذا يخرج منها ──────────────────────────────────────────────────────
 * **التاريخ المشتقّ ورايةُ التفعيل — ولا دقيقةَ مهلةٍ واحدة.** وهذا هو الحدّ
 * الذي رسمته `0052` نفسها: `booking_hold_until` ممنوحة لـ`anon`، و`trip_config()`
 * ليست ممنوحة لأحد. فما يخرج من هنا يستطيع أي زائر أن يناله بنداءٍ مباشر على
 * PostgREST، وما لا يخرج يبقى غير منالٍ. (والدالة الخادمية نقطةُ HTTP عامة
 * بطبعها — فالسؤال الصحيح ليس «من يناديها» بل «ماذا يكسب مناديها»، والجواب:
 * لا شيء لم يكن يملكه.)
 *
 * ── ولا مدخل يُصدَّق ──────────────────────────────────────────────────────
 * `created_at` **لا يصل من المتصفح**: تُقرأ الساعة هنا. والمُدخل الوحيد موعد
 * انطلاقٍ يُتحقّق من كونه طابعاً زمنياً قبل أن يمرّ (‏`isoOrNull` في `hold.ts`).
 */
export async function previewPaymentHold(pickupAtIso: string | null): Promise<PaymentHold> {
  return readPaymentHold(new Date().toISOString(), pickupAtIso);
}
