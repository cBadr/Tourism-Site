import "server-only";

import { formatNormalizedPhone } from "@/lib/phone";
import { createServiceSupabase } from "@/lib/supabase/admin";

/**
 * الهاتف **كما فهمه النظام** — يُعاد إلى العميل قبل التأكيد.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  لماذا هذا الملف: التطبيع يمنع رقماً **فاسداً**، ولا يمنع رقماً **خاطئاً**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * العميل يحجز ضيفاً — بلا حساب وبلا بريدٍ إلزامي — **فالهاتف هو القناة
 * الوحيدة**. وخانةٌ واحدة مقلوبة تُنتج رقماً سليم الشكل تماماً: `normalize_phone`
 * تقبله وتخزّنه في `phone_norm`، والنموذج يقبله، ولا شيء في المنظومة كلها
 * يعلم أن أحداً لن يردّ. والنتيجة عميلٌ لا يُبلَّغ ⇒ **رحلة فاشلة**، ولها في
 * هذا المنتج أثرٌ مالي حقيقي (`docs/phase-briefs/FAILED-TRIPS-AND-PARTNER-ALERTS.md`).
 *
 * فالعلاج ليس تحقّقاً أشدّ — الشكل صحيح فعلاً — بل **أن يقرأ العميل رقمه
 * بعينٍ جديدة ويقرّ به**.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔒 ولا نسخة ثانية من التطبيع — القاعدة الذهبية ١٢
 * ══════════════════════════════════════════════════════════════════════════
 *
 * المرجع الوحيد `public.normalize_phone` (‏`0026`): هي التي يُبنى عليها عمود
 * `bookings.phone_norm` المولَّد، وعليه وحده تقع كل مطابقة عميل (الولاء ·
 * سقف الكوبون لكل عميل · «تابع حجزك»). فلو كتبنا في المتصفح تطبيعاً «مكافئاً»
 * لصار للهوية مصدران ينحرفان أول يوم يتشدّد أحدهما (النمط ٨ في `LESSONS.md`)،
 * ولعرضنا على العميل رقماً غير الذي ستخزّنه القاعدة — أي **أن تصير شاشة
 * التأكيد نفسها كذبة**.
 *
 * ── والمتصفح لا يستطيع مناداتها ─────────────────────────────────────────
 * `normalize_phone` **غير ممنوحة لـ`anon`** بقرارٍ محروسٍ بفحصٍ في `0026`
 * نفسها وبتأكيدٍ في `phone_tests.sql` — يُسقطان الهجرة والاختبار معاً إن
 * انفتحت. فلا يُنقض ذلك التفافاً.
 *
 * ولذلك المسار: **إجراء خادمي** (`lead-time-action.ts`) ينادي هذه الدالة
 * بعميل الخدمة. وحدُ الأمان مقروء: `normalize_phone` دالةٌ نصّية صرفة
 * `immutable` — لا تلمس صفاً ولا تقرأ إعداداً — فالمنادي يستعيد **نصّه هو**
 * بعد تنسيقه، ولا يكسب معلومةً لم يكن يملكها.
 *
 * ⚠ والتنسيق للعرض في `lib/phone.ts` (`formatNormalizedPhone`) لا هنا: ذاك
 * ملف حدود الهاتف الخارجة، وفيه `waNumber` و`e164Number` و`telLink` — ووضعُ
 * منسّقٍ رابع بجوارها يمنع أن يبني ملفٌ آخر شكلاً خامساً بيده، وهو العيب
 * الذي وُجد ذلك الملف أصلاً لإغلاقه.
 */

export type PhoneEcho = {
  /**
   * الشكل المعياري كما ستخزّنه القاعدة (`normalize_phone`) — مفتاح المطابقة.
   * يُستعمل **للمقارنة لا للعرض**: ما يقرّه العميل يجب أن يُسقَط لحظة تغيّره.
   */
  normalized: string | null;
  /**
   * النص المعروض — `+20 10 1000 0506`. `null` يعني «لا شيء يُعرض»: نصٌّ بلا
   * أرقام، أو أقصر من أن يكون رقماً، أو تعذّرت القراءة. والمنادي يخفي بطاقة
   * التأكيد كلها عندها — **لا يعرض رقماً مبتوراً يقرّ به العميل**.
   */
  display: string | null;
};

const NO_ECHO: PhoneEcho = { normalized: null, display: null };

/** سقفٌ على المُدخل: النموذج يقصّ عند ٢٠ محرفاً، وهذا حدُّ ما يعبر إلى القاعدة */
const MAX_INPUT_LENGTH = 40;

/**
 * الشكل المعياري لهاتفٍ كتبه العميل، ونصُّه المعروض.
 *
 * لا ترمي أبداً: كل تعذّرٍ يعود `NO_ECHO` فتصمت بطاقة التأكيد. و**الصمت هو
 * الاتجاه الآمن** هنا: رقمٌ مخترَع يقرّ به العميل أسوأ من غياب البطاقة، ولا
 * يمنع الصمتُ الحجزَ لأن الإقرار لا يُطلب إلا حين يوجد ما يُقرّ به.
 */
export async function readPhoneEcho(phone: string): Promise<PhoneEcho> {
  const raw = (phone ?? "").trim().slice(0, MAX_INPUT_LENGTH);
  if (raw === "") return NO_ECHO;

  const service = createServiceSupabase();
  if (!service) return NO_ECHO;

  try {
    const { data, error } = await service.rpc("normalize_phone", { p_phone: raw });
    if (error) return NO_ECHO;

    const normalized = typeof data === "string" && data.trim() !== "" ? data.trim() : null;
    if (normalized === null) return NO_ECHO;

    const display = formatNormalizedPhone(normalized);
    return display === null ? NO_ECHO : { normalized, display };
  } catch {
    return NO_ECHO;
  }
}
