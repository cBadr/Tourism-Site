import "server-only";

import { cache } from "react";

import { MAX_TRIP_STOPS } from "@/lib/booking-types";
import { createServiceSupabase } from "@/lib/supabase/admin";
import { DEFAULT_STOPS_CAP } from "./stops";

/**
 * سقفُ محطات الرحلة **كما يفرضه المالك في القاعدة** — لا كما يظنّه المتصفح.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 لماذا وُلد هذا الملف: رقمان لسقفٍ واحد
 * ══════════════════════════════════════════════════════════════════════════
 * الهجرة `0140` جعلت السقف **إعدادَ مالك**: عمود `trip_settings.max_trip_stops`
 * (‏افتراضُه **٣**) يقرؤه `max_trip_stops()` ويفرضه المُشغّل
 * `bookings_guard_trip_stops` على كل حجز. أما `MAX_TRIP_STOPS` في
 * `lib/booking-types.ts` فهو **سقفُ الكلفة المطلق (٥)**: ما لا يُقاس خارجياً
 * ولا يُقبل في مُحلِّل الطلب بحال.
 *
 * فبلا هذه القراءة يعرض الويدجت خمسة، والقاعدةُ ترفض فوق ثلاثة — أي أن العميل
 * **يبني رحلةً بأربع محطات، ويرى سعرها، ثم يُرفَض عند الحجز**. وهو حرفياً
 * النمط ٢ في `handover/LESSONS.md`: الواجهة تَعِد بما لا تنفّذه القاعدة، وفي
 * أسوأ ترتيبٍ ممكن — الرفض بعد أن مُلئ النموذج كاملاً.
 *
 * ⚠ **وهو سقفُ إدخالٍ لا قاعدةُ أهلية** (نفس `maxPassengers` و`maxLuggage`
 * حرفياً، D-12): ما يُقبل ويُرفض تقرّره القاعدة وحدها. غايةُ ما يمنعه أن تعرض
 * الشاشة على العميل زرّاً **يضمن الرفض** قبل أن يضغطه.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ولماذا بمفتاح الخدمة، ولماذا `prop` لا نداءٌ من المتصفح
 * ══════════════════════════════════════════════════════════════════════════
 * `max_trip_stops()` **غير ممنوحة لـ`anon` ولا `authenticated`** (‏`0140`):
 * وكلُّ متعهدٍ مستخدمٌ `authenticated` (**D-20**). فالقراءة هنا بعميل الخدمة،
 * وهي **قراءةُ رقمٍ لا كتابة**، ويصل الويدجتَ `prop` من غلافيه الخادميَّين —
 * وهما كلُّ من يُركّبه. ولا يُنشأ مسارٌ عام لأجل رقم، وهو نفس ما فُعل حين
 * حُذف `GET /api/quote` لصالح `getFleetCaps`.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ومناديها ثلاثةٌ لا واحد — الشاشةُ والمساران
 * ══════════════════════════════════════════════════════════════════════════
 * يقرؤها اليوم: الغلافان الخادميّان للويدجت (`app/(site)/book/page.tsx` و
 * `components/booking/booking-widget.tsx`) لتقرير كم زرَّ «أضف محطة» يُعرض،
 * **و`POST /api/quote` و`POST /api/booking`** لرفض ما يتجاوز السقف قبل أي نداءٍ
 * خارجيّ. وكان المساران يعرفان ٥ (سقفَ الكلفة المطلق) بينما القاعدة تفرض ٣،
 * فتُسعَّر رحلةٌ بأربع محطاتٍ **ثم تُرفض عند الحجز**.
 *
 * ⚠ **والمساران يناديانها بشرطٍ واحد: `stops.length > 0`.** رحلةُ النقطتين —
 * وهي الغالبةُ الساحقة على مسارٍ ساخن — لا تدفع رحلةَ شبكةٍ واحدة ثمناً لرقمٍ
 * لا يعنيها. و`cache` تجعلها قراءةً واحدة لكل طلبٍ مهما تعدّد مناديها.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 والفشل يقع في الاتجاه **المتحفّظ** — عكس أختيه
 * ══════════════════════════════════════════════════════════════════════════
 * سقفا الركاب والحقائب يسقطان عند الفشل إلى الثابت **الأوسع** لأن التشديد
 * هناك يمنع حجوزاً سليمة. وهنا العكس: القاعدةُ الافتراضية **٣**، فسقوطٌ إلى ٥
 * يعني وعداً بما تَرفضه. والارتداد `DEFAULT_STOPS_CAP` = **افتراضُ العمود
 * نفسه**، أي ما ستفرضه القاعدة فعلاً على قاعدةٍ لم تُضبط بعد.
 *
 * والثمنُ في الاتجاه الآخر مدفوعٌ سلفاً: من بلغ السقف يجد تحت الزرّ رابطَ
 * «اطلب عرض سعر» — مخرجٌ بشريّ لا طريقٌ مسدود.
 */

/**
 * السقف السارية قراءتُه الآن، مقصوصاً على `MAX_TRIP_STOPS`.
 *
 * `cache` يجعلها قراءةً واحدة لكل طلبٍ مهما تعدّد مناديها — نفس ما تفعله
 * `getFleetCaps` و`getPublicExtras` في الغلاف الخادمي نفسه.
 */
export const getStopsCap = cache(async (): Promise<number> => {
  const clamp = (value: number) => Math.max(0, Math.min(Math.trunc(value), MAX_TRIP_STOPS));
  try {
    const supabase = createServiceSupabase();
    if (!supabase) return DEFAULT_STOPS_CAP;
    const { data, error } = await supabase.rpc("max_trip_stops");
    // هجرةٌ غير مطبَّقة، أو بيئةٌ بلا مفتاح خدمة، أو منحةٌ ناقصة ⇒ الافتراض
    if (error || typeof data !== "number" || !Number.isFinite(data)) return DEFAULT_STOPS_CAP;
    return clamp(data);
  } catch {
    return DEFAULT_STOPS_CAP;
  }
});
