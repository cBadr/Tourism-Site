"use client";

import { useTimeZone } from "next-intl";

import { setSiteTimeZone } from "@/lib/site-timezone";

/**
 * يعكس منطقة الموقع من next-intl إلى `lib/site-timezone.ts` — **مرآةٌ لا مصدر**.
 *
 * ── لماذا يلزم أصلاً ────────────────────────────────────────────────────────
 * الدوال التي تفسّر مُدخل العميل وتُنسّق المعروض له **دوالٌ صرفة** لا مكوّنات:
 * `toIsoFromCairoInputs` و`todayInputValue` و`formatDateLabel` وأخواتها. وهي
 * تُنادى من معالِج حدث أو من دالة عرض، فلا تستطيع `useTimeZone()` ولا `await`.
 * فتقرأ الوحدة المشتركة، وهذا المكوّن هو من يملؤها في المتصفح.
 *
 * ── ولماذا **أثناء التصيير** لا في `useEffect` ──────────────────────────────
 * 🔴 React يصيّر الشجرة كاملةً ثم يشغّل التأثيرات. فضبطٌ في `useEffect` يقع
 * **بعد** أول تصيير لكل الأبناء — أي بعد أن يكون منتقي التاريخ قد حسب أرضيته
 * بالمنطقة الافتراضية. والإسناد هنا مجرّد كتابة قيمة في وحدة (idempotent)،
 * فتكراره في التصيير المزدوج بوضع Strict بلا أثر.
 *
 * ولذلك موضعه **أول ابنٍ داخل `NextIntlClientProvider`** في `app/layout.tsx`:
 * الإخوة يُصيَّرون بالترتيب، فتستقر القيمة قبل أن يُصيَّر أي شيء يقرؤها.
 *
 * ── والمصدر واحد لا اثنان ───────────────────────────────────────────────────
 * `useTimeZone()` يعيد ما وضعه `i18n/request.ts` في إعداد next-intl، وهو نفسه
 * ما قرأه من `public.site_time_zone()`. فليس هذا مساراً ثانياً للقيمة بل
 * انعكاسٌ للمسار الوحيد — ومسارا قيمةٍ واحدة هما صنف العيب المتكرر في هذا
 * المستودع (ترويسة `checkout/datetime.ts`).
 *
 * يُصيَّر على الخادم أيضاً (مكوّن عميل يُصيَّر مسبقاً) فيؤكّد ما ضبطه
 * `getSiteTimeZone()` هناك — ولا يخالفه لأن المصدر واحد.
 */
export function SiteTimeZoneSync() {
  // `undefined` ممكنٌ نوعياً (مزوّد بلا إعداد) — و`setSiteTimeZone` تسقط
  // إلى الافتراضي عندها بدل أن ترمي داخل التصيير.
  setSiteTimeZone(useTimeZone());
  return null;
}
