"use client";

import { useCallback, useRef, type ReactNode } from "react";
import { cn } from "@/lib/utils";
import { useScrollPast } from "./use-scroll-past";
import styles from "./motion.module.css";

/**
 * الشريط اللاصق السفلي — ينزلق صاعداً بعد تجاوز البطل.
 *
 * حدّ التصميم: `ارتفاع البطل − ١٤٠` — أي أنه يظهر قبل أن يختفي البطل تماماً،
 * فلا تمرّ على القارئ لحظةٌ واحدة بلا زرّ حجز على الشاشة.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 و`afterId` يغلب الحدّ أعلاه — لأن الحدّ نفسه كان الخطأ
 * ══════════════════════════════════════════════════════════════════════════
 *
 * شكوى المالك من الجوال (2026-08-17): الشريط يصل و**زرّ «احسب السعر» ما زال
 * على الشاشة** — إجراءان رئيسيان يتنافسان في إطارٍ واحد.
 *
 * والسبب بنيويّ لا رقميّ: على الجوال يعيش ويدجت الحجز **أسفل البطل مباشرةً
 * ومتداخلاً معه** (‏`-mt-12` في `components/sections/hero.tsx`)، فحدُّ «ارتفاع
 * البطل − ١٤٠» يقع **داخل الويدجت** لا بعده. أي أن الرقم ١٤٠ لم يكن صغيراً،
 * بل كان **مقيساً من العنصر الخطأ**.
 *
 * فحين يصل `afterId` يصير الحدّ **قاع ذلك العنصر في الوثيقة**: الشريط يظهر
 * حين يغادر العنصر إطارَ العرض من أعلاه — أي حين لا يبقى منه بكسلٌ واحد،
 * وبالتالي **لا يبقى منه زرُّ إرسال**. وهو نفس مبدأ القرار المكتوب في
 * `cta-bar.tsx` §(٢): «لا شريط فوق شاشةٍ فيها زرّ إرسال».
 *
 * ⚠ والقياس يُعاد عند كل إطار تمرير (`getBoundingClientRect`) لا مرّةً واحدة:
 *   الويدجت يتمدّد بعرض بطاقات الأسعار ثم بمسار إتمام الحجز، فارتفاعٌ محفوظ
 *   من لحظة التحميل كان سيعيد العطل بمجرد أن يضغط الزائر «احسب السعر».
 *
 * 🔒 وغياب العنصر يُسقط القاعدة إلى حدّ البطل كما كان حرفياً — فالصفحات التي
 * لا ويدجت فيها (خدمات · مسارات · صفحات الباني) لا يتغيّر سلوكها بحرف.
 *
 * 🔴 **وبلا جافاسكربت يبقى الشريط ظاهراً** (الإخفاء مشروط في CSS بـ
 * `scripting: enabled`). زرُّ حجزٍ ظاهرٌ دائماً أسوأ احتمالاته أنه زائد،
 * وزرٌّ مخفيّ للأبد خسارةُ تحويلٍ صامتة.
 */
export function SlideUpBar({
  children,
  className,
  /** ارتفاع البطل بالبكسل، أو `undefined` فيُقرأ من العنصر ذي هذا المعرّف. */
  heroId = "hero",
  offset = 140,
  /**
   * معرّف العنصر الذي **لا يظهر الشريط قبل أن يغادر الشاشة كاملاً**. حين يوجد
   * على الصفحة يغلب `heroId` و`offset` معاً؛ وحين لا يوجد يعود الحدّ إلى البطل.
   */
  afterId,
}: {
  children: ReactNode;
  className?: string;
  heroId?: string;
  offset?: number;
  afterId?: string;
}) {
  // نقرأ الارتفاع عند كل نداء لا مرّة واحدة: ارتفاع البطل يتغيّر بالدوران،
  // وبتحميل الخطوط، وبالتفاف العنوان على شاشةٍ ضيقة.
  const cached = useRef(0);
  const threshold = useCallback(() => {
    if (afterId) {
      const after = document.getElementById(afterId);
      if (after) {
        // قاع العنصر في إحداثيات الوثيقة: `scrollY > هذا` ⇔ غادر العنصر الشاشة
        return after.getBoundingClientRect().bottom + window.scrollY;
      }
    }
    const hero = document.getElementById(heroId);
    if (hero) cached.current = hero.offsetHeight;
    // بلا بطل على الصفحة: حدٌّ معقول بدل صفر (وإلا ظهر الشريط فوق البطل نفسه)
    return (cached.current || window.innerHeight * 0.8) - offset;
  }, [afterId, heroId, offset]);

  const on = useScrollPast(threshold);

  return (
    <div
      className={cn(styles.slideUpBar, className)}
      {...(on ? { "data-on": "" } : null)}
    >
      {children}
    </div>
  );
}
