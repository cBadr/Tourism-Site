"use client";

import { useEffect } from "react";

/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  أعمدة التذييل على الجوال: **واحدٌ مفتوح لا أكثر**                       ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * ── 🔴 القاعدة التي لا تُنقض: الخادم يُصيّر **كل** الأعمدة مفتوحة ───────────
 *
 * `<details>` يُفتح ويُغلق بالسمة `open` وحدها، **ولا يملك CSS فتحه**: قاعدة
 * المتصفح تخفي المحتوى عبر `::details-content` (وهو حديثٌ ومختلف بين
 * المتصفحات). فالخياران: أن تُكتب الأعمدة **مغلقةً** ويُفتحها CSS على المكتب
 * (لا يمكن مُحكماً)، أو أن تُكتب **مفتوحةً** ويطويها الجافاسكربت.
 *
 * 🔒 **والثاني وحده يفشل فشلاً آمناً.** بلا جافاسكربت — أو قبل الترطيب، أو
 * لزاحفٍ لا ينفّذه — تبقى **الروابط الواحد والثلاثون** مفتوحةً ومقروءة. والأول
 * كان يعني تذييلاً لا يظهر منه إلا أربعة عناوين، و**ثلاثون رابطاً داخلياً
 * محجوبة عن جوجل** في موقعٍ السيو هو منتجه — بلا خطأ ولا سجلّ يمسكه أحد.
 *
 * ⚠ **والأكورديون أحادي الفتح لا ينقض ذلك بل يشدّده:** لو صُيِّر عمودٌ واحد
 *   مفتوحاً من الخادم لضاع ثلاثون رابطاً بدل خمسة عشر. فالطيّ إلى واحد يقع
 *   **بعد** الترطيب لا في الـHTML.
 *
 * ── ما تغيّر بأمر بدر بعد استعماله (2026-08-17) ────────────────────────────
 *
 * > «١- قائمة حجزك و حسابك لا تقبل الطي، أريدها أن تكون قابلة للطي.
 * >  ٢- أريد أن يتم طي كافة القوائم عند فتح واحدة، ولتكن حجزك وحسابك مفتوحة
 * >  بشكل افتراضي على أن يتم طيها في حال قام المستخدم بفتح قائمة أخرى.»
 *
 * فسقط `data-ftr-keep` (التثبيت) وحلّ محلّه `data-ftr-default` (البداية).
 * وحجّة التثبيت كانت أن «تابع حجزك» شكوى بدر الأولى فلا يُخبَّأ — **وفتحُه
 * افتراضياً يفي بها حرفاً**: الرابط مرئيٌّ لحظة الوصول في الحالتين، والفرق
 * الوحيد أن الزائر صار يملك طيّه.
 *
 * ── ثلاثة قرارات في السلوك، وكلٌّ منها كان يمكن أن يقع على الوجه الآخر ─────
 *
 * **(١) للزائر أن يغلق الكل.** طيُّ العمود المفتوح لا يفتح غيره، فتبقى الأعمدة
 *      الأربعة عناوينَ وحدها. ومن يريد التذييل بعيداً عن طريقه يناله — وهو
 *      أقصى ما يمكن أن يبلغه القسم ارتفاعاً أدنى. ولا يُفقد شيء: العناوين
 *      الأربعة كلها ظاهرة، والفتح نقرةٌ واحدة.
 *
 * **(٢) بلا حفظٍ بين الصفحات.** لا `localStorage` ولا كوكي: كل صفحة تبدأ من
 *      «حجزك وحسابك» مفتوحاً. وحفظُ الاختيار كان يعني أن زائراً طوى العمود
 *      مرةً لا يرى «تابع حجزك» في أي صفحةٍ بعدها — أي إحياءُ الشكوى الأولى
 *      من بابٍ خلفي.
 *
 * **(٣) المكتب خارج هذا كله.** فوق `md` تُفتح الأعمدة الأربعة ولا يعمل الطيّ
 *      ولا الأحادية: هناك عناوينُ ساكنة بلا أسهم، والمساحة أفقية لا رأسية.
 *
 * ── ولا رايةَ «أنا أزامن الآن» ─────────────────────────────────────────────
 *
 * حدث `toggle` على `<details>` **يُطلَق في مهمةٍ مؤجَّلة** لا فور تغيير السمة
 * (نصّ المواصفة: «queue a details toggle event task»). فرايةٌ تُرفع وتُخفض حول
 * سطر `panel.open = …` تكون قد سقطت قبل أن يصل الحدث — أي حارسٌ لا يحرس.
 *
 * فالمعالج **متقارب بذاته** بدل ذلك: كل حالةٍ يبلغها يعيد إنتاج نفسها بلا
 * تغيير، فتقف السلسلة عند أول دورة. (فتحُ ب ⇒ يُغلق أ ⇒ حدثُ أ لا يجد ما
 * يفعله ⇒ سكون.)
 *
 * ولا يقرأ هذا المكوّن جلسةً ولا بياناتٍ: يضبط سمةً على DOM ويصيّر `null` —
 * فالتذييل يبقى مكوّن خادم كما هو (نفس مبرر جزيرة الترويسة).
 */
export function FooterAccordionSync() {
  useEffect(() => {
    if (!window.matchMedia) return;
    /** نفس نقطة `md` في Tailwind — فوقها الأعمدة عناوين ساكنة لا أزرار */
    const wide = window.matchMedia("(min-width: 768px)");

    const panels = Array.from(
      document.querySelectorAll<HTMLDetailsElement>("details[data-ftr-acc]")
    );
    if (panels.length === 0) return;

    /**
     * العمود المفتوح على الجوال. يبدأ من المعلَّم بـ`data-ftr-default`، ثم
     * يتبع آخر ما فتحه الزائر، و`null` تعني «الكل مطويّ» وهي حالةٌ مشروعة.
     *
     * ومحلُّه متغيّرٌ في نطاق الأثر لا `useState`: تبديلُه لا يعيد تصيير شيئاً
     * (نحن نكتب على DOM مباشرةً)، وحالةُ React كانت ستشتري دورة تصييرٍ كاملة
     * مقابل سمةٍ واحدة — وهو نفس مبرر `flow-road.tsx` عند `is-live`.
     */
    let current: HTMLDetailsElement | null =
      panels.find((panel) => panel.hasAttribute("data-ftr-default")) ?? null;

    /**
     * 🔒 إغلاقٌ لا يترك التركيز داخل لوحةٍ تُخفى.
     *
     * الحالةُ التي يعالجها: زائرٌ بلوحة مفاتيح داخل روابط «خدماتنا»، ثم يفتح
     * «مسارات شائعة» بنقرةٍ باللمس أو الفأرة (وسفاري لا ينقل التركيز إلى
     * `<summary>` عند النقر). فيُغلق العمود الأول **والتركيز في جوفه** — يصير
     * على عنصرٍ `content-visibility: hidden` فيقذفه المتصفح إلى `<body>`،
     * ويستأنف الزائر تنقّله من أول الصفحة.
     *
     * فيُنقل التركيز إلى عنوان العمود المغلَق: أقربُ موضعٍ ذي معنى، ومنه
     * يستأنف التنقّل حيث كان، وضغطةٌ واحدة تعيد فتح ما كان مفتوحاً.
     */
    const close = (panel: HTMLDetailsElement) => {
      if (!panel.open) return;
      const active = document.activeElement;
      if (active instanceof HTMLElement && panel.contains(active)) {
        panel.querySelector("summary")?.focus();
      }
      panel.open = false;
    };

    /** الحالة الصحيحة للعرض الحالي — تُطبَّق عند الترطيب وعند تبدّل العرض */
    const apply = () => {
      if (wide.matches) {
        panels.forEach((panel) => {
          panel.open = true;
        });
        return;
      }
      panels.forEach((panel) => {
        if (panel === current) panel.open = true;
        else close(panel);
      });
    };

    const onToggle = (event: Event) => {
      const panel = event.currentTarget as HTMLDetailsElement;

      /*
        المكتب: العنوان ساكن، و`pointer-events-none` تمنع الفأرة وحدها — أما
        `Enter` على `<summary>` المركَّز عليه فيطويه فعلاً، ولا سهمَ هناك يعيد
        فتحه. فيُعاد. والفتحُ على مفتوحٍ لا يُطلق حدثاً، فتقف السلسلة.
      */
      if (wide.matches) {
        if (!panel.open) panel.open = true;
        return;
      }

      if (panel.open) {
        current = panel;
        panels.forEach((other) => {
          if (other !== panel) close(other);
        });
        return;
      }

      // طوى الزائر المفتوح ⇒ لا يبقى شيء مفتوحاً، ولا يُفتح بديلٌ عنه
      if (current === panel) current = null;
    };

    apply();
    wide.addEventListener("change", apply);
    panels.forEach((panel) => panel.addEventListener("toggle", onToggle));

    return () => {
      wide.removeEventListener("change", apply);
      panels.forEach((panel) => panel.removeEventListener("toggle", onToggle));
    };
  }, []);

  return null;
}
