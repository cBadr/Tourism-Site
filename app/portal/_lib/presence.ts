import "server-only";

import { cookies } from "next/headers";
import { after } from "next/server";
import { createServerClient } from "@supabase/ssr";

/**
 * نبضةُ حضور المتعهد — «متواجد يعني أونلاين» بنصّ المالك (2026-08-18).
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ما كان موجوداً قبل هذا الملف: **لا شيء**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * العمود الوحيد الذي يحمل «آخر ظهور» في القاعدة كلها كان
 * `partner_push_subscriptions.last_seen_at` — أي **جهاز** لا **شخص**. ومتعهدٌ
 * بلا اشتراك دفعٍ واحد (وهي حال القاعدة اليوم: صفر اشتراكات) لا أثر له إطلاقاً.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔴 لماذا `after()` ولماذا لقطةُ كوكيز
 * ══════════════════════════════════════════════════════════════════════════
 *
 * أمرُ المالك: **بلا كتابةٍ على مسار التصيير** — «كتابةٌ على كل تحميل صفحة كلفةٌ
 * لم يطلبها». و`after` من `next/server` هي أداةُ Next لهذا بعينه: تُنفَّذ **بعد
 * إرسال الاستجابة**، فلا تُبطئ حرفاً مما يراه المتعهد.
 *
 * ⚠ **لكن `cookies()` و`headers()` تُرمى داخل `after` في مكوّنٍ خادمي** (وثيقة
 *   `next/dist/docs/01-app/03-api-reference/04-functions/after.md` نصّاً:
 *   «Calling `cookies()` or `headers()` inside the `after` callback in a Server
 *   Component will throw a runtime error»). وعميلُ Supabase يقرأ الكوكيز عند
 *   **كل** نداء — فتمريرُ عميل الصفحة إلى `after` كان سيرمي.
 *
 * ⇒ فالحل: **تُقرأ الكوكيز أثناء التصيير** (حيث القراءة مسموحة) وتُمرَّر لقطةً
 *   ساكنة، ويُبنى داخل `after` عميلٌ يقرأ من اللقطة ولا يكتب كوكيزاً إطلاقاً.
 *   `setAll` فارغة عمداً: تجديدُ الجلسة شأنُ الوسيط (`proxy.ts`)، ونبضةُ حضورٍ
 *   لا يجوز أن تمسّ توكن أحد.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  والخانقان: أيُّهما الضمانة
 * ══════════════════════════════════════════════════════════════════════════
 *
 * | الطبقة | أين | ماذا تمنع | هل هي الضمانة؟ |
 * |---|---|---|---|
 * | `where` داخل `touch_partner_presence` | Postgres (0118) | **الكتابة** داخل الدقيقة | ✅ نعم — تصمد مهما تعدّدت العمليات |
 * | خريطة في ذاكرة العملية | هذا الملف | **رحلة الشبكة** أصلاً | ❌ لا — تضيع مع أول إعادة تشغيل |
 *
 * فالذاكرة توفير لا حاجز. ولو حُذفت لبقي السلوك صحيحاً وكلّف نداءً بعد كل
 * استجابة؛ ولو حُذف شرط `where` من الهجرة لصارت كتابةً على كل تحميل صفحة —
 * وهو ما يحرسه `presence_tests.sql` (ج-٢) بنداءٍ حيّ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ولماذا لا تُرمى من هنا استثناءات
 * ══════════════════════════════════════════════════════════════════════════
 *
 * نبضةُ الحضور **زينةٌ تشغيلية**: فشلُها يعني نقطةً رمادية في اللوحة، ولا يجوز
 * أن يعني صفحةً مكسورة في وجه المتعهد. فكل مسار هنا يبتلع خطأه بصمت.
 * ⚠ وثمنُ ذلك مُعلَن: **عطلٌ صامت**. والذي يكشفه أن العمود يبقى `null` لمتعهدٍ
 *   يعمل — وهو ظاهرٌ في اللوحة بوصفه «لم يدخل بوابته قط»، لا مخبوءٌ في سجل.
 */

/** نافذة الخانق في الذاكرة — نفس دقيقة الهجرة، ولا تتجاوزها */
const THROTTLE_MS = 60_000;

/**
 * آخر لحظة أُرسلت فيها نبضةٌ لكل متعهد **في هذه العملية**.
 *
 * ⚠ حجمها محدودٌ بعدد المتعهدين لا بعدد الطلبات (مفتاحٌ لكل متعهد)، فلا تنمو
 *   بلا حدّ. وشركاء المنصة عشراتٌ لا ملايين.
 */
const lastPing = new Map<string, number>();

/**
 * سجّل حضور المتعهد صاحب الجلسة الحالية — **بعد** إرسال الاستجابة.
 *
 * تُنادى من `readPortalGate()` وحدها، وهي مُذاكَرة بـ`cache()` لكل طلب — فالنبضة
 * واحدةٌ لكل طلب مهما تعدّد قارئو البوابة في شجرة التصيير، وتشمل **أفعال**
 * البورتال (قبول عرض، حفظ سعر) لا صفحاته وحدها.
 *
 * @param subcontractorId معرّف المتعهد كما حلّته البوابة. `null` ⇒ لا شيء.
 */
export async function recordPortalPresence(subcontractorId: string | null): Promise<void> {
  if (!subcontractorId) return;

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !anonKey) return;

  // خانقُ الذاكرة: يوفّر رحلة الشبكة، ولا يُغني عن خانق القاعدة
  const now = Date.now();
  const previous = lastPing.get(subcontractorId);
  if (previous !== undefined && now - previous < THROTTLE_MS) return;
  lastPing.set(subcontractorId, now);

  try {
    // القراءة هنا — أثناء التصيير — لأنها ممنوعة داخل `after`
    const jar = await cookies();
    const snapshot = jar.getAll().map(({ name, value }) => ({ name, value }));

    after(async () => {
      try {
        const supabase = createServerClient(url, anonKey, {
          cookies: {
            getAll: () => snapshot,
            // لا كتابة كوكيز من نبضة حضور: تجديد الجلسة شأن `proxy.ts`
            setAll: () => {},
          },
        });
        // بلا وسيط: الهوية من الجلسة، والخانق في القاعدة (0118)
        await supabase.rpc("touch_partner_presence");
      } catch {
        // زينةٌ تشغيلية لا تكسر صفحة — وأثرُ الفشل مرئيٌّ في اللوحة نفسها
      }
    });
  } catch {
    // خارج نطاق طلب، أو الكوكيز غير متاحة: تُترك النبضة ولا يُكسر شيء.
    // ونُسقط أثر الذاكرة كي تُعاد المحاولة في الطلب التالي بدل انتظار دقيقة.
    lastPing.delete(subcontractorId);
  }
}
