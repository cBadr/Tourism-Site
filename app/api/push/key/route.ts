import { vapidPublicKey } from "@/lib/push/vapid";

/**
 * GET /api/push/key — المفتاح العام لـVAPID.
 *
 * ── لماذا مسارٌ بدل متغيّر `NEXT_PUBLIC_` ──────────────────────────────────
 *
 * المتصفح يحتاج المفتاح العام ليشترك به (`applicationServerKey`). وبادئة
 * `NEXT_PUBLIC_` كانت ستحقنه في الحزمة وقت **البناء** — ومفتاحٌ يُضاف إلى
 * البيئة بعد النشر يظلّ غائباً حتى بناءٍ جديد. وهذا بالضبط شكلُ تشغيلِ هذا
 * المشروع: المالك يضيف مفاتيحه على الخادم متى جهّزها، والقناة تعمل في **الدورة
 * التالية** بلا نشر (نفس منطق `syncProviderReadiness`).
 *
 * وأسماء المتغيّرات تبقى بلا بادئة — أي بلا خطر أن يتسرّب `VAPID_PRIVATE_KEY`
 * إلى حزمة المتصفح بغلطةٍ مطبعية.
 *
 * ── 🔒 ولماذا هذا المسار **بلا حارس** ──────────────────────────────────────
 *
 * المفتاح العام عامٌّ بتعريفه: هو ما يُشحن إلى كل عميلٍ في أي تطبيق دفعٍ في
 * العالم، ولا يُشتقّ منه الخاص. وله منادٍ لا يملك جلسةً بالضرورة: عاملُ الخدمة
 * في `pushsubscriptionchange` — حدثٌ يقع والصفحة مغلقة.
 *
 * وما **لا** يخرج من هنا: أسماء المتغيّرات الناقصة ولا سببُ العطل. تلك تخصّ
 * المالك وتُقرأ من شاشته (`notification_providers`)، ولا شأن لزائرٍ بها.
 */

export const runtime = "nodejs";
/** مفتاحٌ يُضاف إلى البيئة يجب أن يظهر في الطلب التالي، لا بعد إبطال كاش */
export const dynamic = "force-dynamic";

export async function GET(): Promise<Response> {
  const publicKey = vapidPublicKey();
  return Response.json(
    { ready: publicKey !== null, publicKey },
    { headers: { "Cache-Control": "no-store" } }
  );
}
