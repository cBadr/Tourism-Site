import type { ReactNode } from "react";
import { colorSchemeFor, getThemeChoice } from "@/lib/theme";

/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  غلاف الموقع العام — القشرة الداكنة في مكانٍ واحد لكل صفحاته              ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * ── لماذا وُلد هذا الملف (م‑٨) ──────────────────────────────────────────────
 *
 * القرار ٢٦ («الموقع داكن بهوية التصميم») كان منفَّذاً على **الرئيسية وحدها**:
 * الصنف `.dark` مكتوباً في `app/page.tsx` نفسها، وهي تعترف بذلك في تعليقها
 * («هذه الصفحة وحدها… والاثنتا عشرة صفحة العامة الأخرى ما زالت فاتحة»). فكان
 * الموقع واجهتين لا واحدة: رئيسيةٌ داكنة يفتح منها الزائرُ `/book` فتنقلب
 * الأرضية تحت يده.
 *
 * ── وأين كانت «القشرة المشتركة»؟ لم تكن ────────────────────────────────────
 *
 * `handover/ARCHITECTURE.md` §٣ يسمّي ثلاث «مجموعات مسارات»، وله في الملفات
 * اثنتان فقط: `app/admin/layout.tsx` و`app/portal/layout.tsx`. أما الموقع
 * العام فكان **جذر التطبيق نفسه** — ثلاث عشرة صفحة متناثرة تحت `app/` مباشرةً،
 * وأقربُ غلافٍ يجمعها هو `app/layout.tsx` الذي يخدم الواجهات الثلاث معاً.
 *
 * ولذلك **لم يُنقل الصنف إلى `<body>`**: هناك يبتلع اللوحةَ والبورتال معه.
 * وحتى لو أُلبِسا صنفاً فاتحاً مضاداً، يبقى المتغيّر `dark:` مضبوطاً على
 * `&:is(.dark *, .surface-ink *)` في `globals.css` — فكل أداة `dark:*` في
 * ٤٠+ شاشة إدارية كانت ستشتعل داخل أرضيةٍ فاتحة. أي أن `<body>` يشتري سطراً
 * ويدفع نظاماً ثانياً.
 *
 * فالحلّ أن **تصير المجموعة الثالثة مجموعةً فعلاً**: `app/(site)/` — قوسان لا
 * يظهران في أي رابط (المجموعات شفافة في التوجيه، والعربية تبقى بلا بادئة كما
 * تنصّ القاعدة ١)، وتحتهما كل صفحة عامة، وفوقهما هذا الغلاف الواحد.
 *
 * ── ثلاث خصائص لهذا الشكل يجب ألا تُنقض ────────────────────────────────────
 *
 * ١) **صفحةٌ عامة جديدة تولد داكنة.** ما دامت داخل المجموعة فلا سطر يُكتب لها.
 *    وهذا هو الفرق العملي بين غلافٍ ووسمٍ يُنسخ ثلاث عشرة مرة.
 *
 * ٢) **`/admin` و`/portal` خارج المجموعة بنيوياً** — لا بصنفٍ مضاد ولا بفحص
 *    مسار في الجذر. فما لا يدخل لا يحتاج مخرجاً.
 *
 * ٣) 🔴 **ولا لونَ مكتوباً هنا.** م‑٩ ستضيف مبدّل فاتح/داكن، وشرطُ أن تكون
 *    «لوحةٌ ثانية ومفتاح» لا «فكُّ عتمةٍ محفورة» أن يبقى كلُّ لونٍ خارجاً من
 *    السبعة عشر رمزاً. والصنف `dark` نفسه ليس لوناً بل **مفتاح إسناد**: كتلة
 *    `.dark` في `globals.css` تعيد إسناد الرموز الدلالية إلى العائلة الداكنة،
 *    فيوم يأتي المبدّل يقلبه على هذا العنصر بعينه ولا يلمس شيئاً آخر.
 *
 * ── ✅ وقد جاء المبدّل (م‑٩)، والتعهّد الثالث صمد حرفياً ────────────────────
 *
 * لم يُفكَّ لونٌ محفور لأنه لم يكن ثمّة لونٌ محفور: كل ما لزم هو **صنفٌ يُقلب على
 * هذا العنصر بعينه**، تماماً كما تنبّأ السطر أعلاه. والذي أُضيف ثلاثة أشياء لا
 * رابع لها — `site-theme` (نطاق المبدّل)، و`data-theme` (الاختيار)، و`dark`
 * (مشروطاً بالاختيار الصريح وحده).
 *
 * ── 🔴 وأين يُحسم الوميض — والجواب: **قبل أن يُرسَل أول بايت** ──────────────
 *
 * الاختيار الصريح يصل مع الطلب كوكيّاً، فيخرج هذا الغلاف من الخادم مطلياً
 * صحيحاً. ولا سكربتَ حاجزاً في `<head>` ولا `localStorage` ولا `useEffect` —
 * وثلاثتها تعني أن HTML وصل بثيمٍ ثم انقلب، وهو **تعريف** الوميض لا علاجه.
 *
 * أما من لم يختر (وهو الأغلب) فقراره ليس عند الخادم أصلاً — الخادم لا يعلم
 * تفضيل جهازه ولا سبيل له إليه في الطلب الأول (‏`Sec-CH-Prefers-Color-Scheme`
 * لا تصل إلا من الطلب الثاني، وكروميوم وحده يرسلها). فيُترك قراره **لCSS**:
 * `color-scheme: light dark` مع `light-dark()` في `globals.css` §١ب. والمحرّك
 * يعرف تفضيل الجهاز قبل أول طلاء لأنه خاصية جهازٍ لا نتيجة شبكة.
 *
 * ⚠ **و`.dark` لا تُكتب إلا مع الاختيار الصريح.** الحالة `system` تنقلب داكنةً
 * عبر `color-scheme` وحدها، وصنفٌ ثابت هنا كان سيجمّدها على الداكن ويُلغي
 * الاتّباع. وثمن ذلك أن أدوات `dark:` في المستودع تحتاج فرعاً ثانياً في
 * `@custom-variant dark` — وهو مكتوبٌ ومُبرَّر في `globals.css`، ونسيانه يترك
 * صناديق التنبيه بنصٍّ داكن على أرضيةٍ داكنة عند من لم يختر شيئاً.
 *
 * ── ولماذا `flex flex-1 flex-col` لا `display: contents` ───────────────────
 *
 * منقولٌ حرفاً عن التحذير الذي كان في `app/page.tsx`: عنصر بـ`display:contents`
 * لا يرسم خلفية، فكانت أرضية `body` الرملية تظهر خلف كل شيء. والغلاف هنا يرسم
 * `bg-background` بنفسه ويمدّ نفسه في عمود `body` (‏`min-h-full flex flex-col`)
 * فيملأ الشاشة ولو قصرت الصفحة.
 *
 * ── وما **لا** يفعله هذا الغلاف عمداً ──────────────────────────────────────
 *
 * لا يركّب `SiteHeader` ولا `SiteFooter` ولا `WhatsAppFab`. الصفحات تركّبها
 * بنفسها اليوم لأن كلاً منها يقرأ `settings` و`locale` ويمرّرهما، وبعضها يحذف
 * الزرّ العائم (`/payment/return`) أو يتقدّم عليه بشريط سياق (`/account`).
 * وتوحيدُ ذلك حركةٌ ثانية مستقلة، ولو خُلطت بهذه لما عرف أحدٌ أيُّ تغيّرٍ بصريّ
 * جاء من أيّ قرار.
 */
export default async function SiteLayout({ children }: { children: ReactNode }) {
  const theme = await getThemeChoice();

  return (
    <>
      {/*
        🔴 **سطرٌ واحد لأدوات المتصفح التي لا يبلغها الغلاف** — وليس تكراراً له.

        `color-scheme` على هذا `<div>` يحكم ما بداخله: منتقي التاريخ، وقائمة
        `select`، وأرضية الإكمال التلقائي. أما **شريط تمرير الصفحة** فيرسمه
        المتصفح من `<html>` — وهو خارج الغلاف، ويخدم `/admin` و`/portal` معاً
        فلا يجوز أن يحمل الاختيار من الجذر.

        فيُحقن من هنا: هذا الملف لا يُصيَّر إلا داخل مجموعة `(site)`، فاللوحة
        والبورتال لا يريانه إطلاقاً. والوسم جزءٌ من HTML الخادمي فيصل في نفس
        الوثيقة — بلا وميض وبلا طلب.

        ⚠ والقيمة **ليست نصاً حراً**: `colorSchemeFor` تُخرج واحدةً من ثلاث
        سلاسل مكتوبة في `lib/theme.ts`، ومدخلها مرشَّحٌ بـ`normalizeThemeChoice`
        — فكوكيٌّ مصنوع بيد لا يكتب حرفاً داخل هذا الوسم.
      */}
      <style>{`:root{color-scheme:${colorSchemeFor(theme)}}`}</style>
      <div
        data-theme={theme}
        className={`site-theme flex flex-1 flex-col bg-background text-foreground${
          theme === "dark" ? " dark" : ""
        }`}
      >
        {children}
      </div>
    </>
  );
}
