/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  عقد عمولة بوابات الدفع — ن‑١ (الهجرة `0066`)                             ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * نصّ بدر: «مبلغٌ ثابت **أو** نسبة من تكلفة الرحلة، تُضاف إلى فاتورة العميل
 * النهائية، وتُضبط من صفحة حسابات الدفع والخزينة خياراً إضافياً لكل حساب».
 * مثالاه: فودافون كاش **+١ جنيه** · انستاباي **+٢٠ جنيهاً**.
 *
 * هنا **القرارات ومبرراتها وعاقبة نقضها** وحدها؛ التفصيل التنفيذي في الهجرة.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §١ — 🔴 القرار الحاكم: العمولة **خارج `bookings.total`**، لا طبقةً خامسة فيه
 * ══════════════════════════════════════════════════════════════════════════
 *
 * البديهي أن تُضاف العمولة في آخر معادلة التسعير، كما فعلت الخدمات في **D-54**:
 *
 *     total = (ride_total − coupon − points) + extras          ← القائم
 *     total = … + payment_fee                                  ← ✖ **مرفوض**
 *
 * ورفضُه ليس تفضيلاً في الشكل: **`bookings.total` ليس رقم فاتورة، بل مدخلٌ في
 * خمسة حسابات ليست للعميل.** قِيس على الكتالوج الحيّ لا على ذاكرة:
 *
 * | مَن يقرأ `total` | ماذا يحدث لو حمل العمولة |
 * |---|---|
 * | `dispatch_ceiling` | أساسه `total − extras`، فالعمولة **تدخله** ⇒ يتسع سقف الموجة ⇒ يفوز متعهدٌ أغلى ⇒ **العمولة غيّرت ما يستحقه المتعهد** وهي ليست من نصيبه |
 * | `bookings.amount_remaining` | `total − amount_due` ⇒ المتبقي **نقداً مع السائق** يرتفع بعمولةِ تحويلٍ إلكتروني لم يقع |
 * | مُشغّل كسب النقاط | أساسه `total − extrasTotal` ⇒ العميل **يكسب نقاطاً على رسم تحويل** |
 * | `apply_discount` ← أرضية الهامش | أساس الخصم يتضخّم بمالٍ ليس هامشاً ⇒ يُسمح بخصمٍ يأكل هامش الرحلة الحقيقي |
 * | `margin_amount` | يصير إيرادُ التحويل ربحاً في كل تقرير ربحية |
 *
 * 🔒 **فالعمولة طبقةٌ على الفاتورة لا على السعر**، ومكانها **بعد** الحجز كله:
 *
 *     bookings.total                       ← مجمَّد، لا يمسّه شيء مما هنا
 *       + payment_fee(الحساب المختار)      ← ★ طبقة الفاتورة
 *       = ما يحوّله العميل
 *
 * وهذه حمايةٌ **بنيوية لا انضباطية**، على سابقة **D-18** حرفياً: ما لا يوجد في
 * `bookings.total` **لا يمكن** أن يبلغ سقفَ البث ولا الهامش ولا النقاط — لا لأن
 * أحداً تذكّر أن يطرحه في أربعة مواضع (وهو ما احتاجته الخدمات في **D-55**)، بل
 * لأنه ليس هناك أصلاً. **العمولة لا تحتاج بند D-55 خاصاً بها، وهذا هو الفرق.**
 *
 * ⚠ **عاقبة النقض:** إضافة العمولة إلى `total` تحرّك الخمسة أعلاه دفعةً واحدة،
 * وأخطرها الأول: **مالٌ يدفعه العميل لفودافون كاش يصير سقفاً يشتري به متعهدٌ
 * رحلةً أغلى.** ولا اختبارٌ قائم يمسكه — كلها خضراء ما دام الحساب صحيحاً.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٢ — أساس النسبة، وعلى أي ساقٍ تقع العمولة
 * ══════════════════════════════════════════════════════════════════════════
 *
 * **الأساس `bookings.total`** — «تكلفة الرحلة» بلسان بدر، وهو الرقم المجمَّد بعد
 * الكوبون والنقاط وشاملاً الخدمات. أساسٌ مجمَّد ⇒ ناتجٌ مجمَّد بلا عمل إضافي.
 *
 * **والعمولة تقع مرة واحدة على الساق الإلكترونية**: تُضاف إلى `amount_due` (ما
 * يحوّله العميل الآن، كاملاً كان أو عربوناً) ولا تُضاف إلى `amount_remaining`
 * (النقد الذي يسلّمه للسائق — لا بوابة فيه ولا عمولة عليها). فالفاتورة:
 *
 *     المطلوب تحويله الآن = amount_due + fee
 *     إجمالي ما يدفعه     = total + fee
 *     المتبقي مع السائق   = amount_remaining        ← بلا مساس
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٣ — 🔒 التجميد: لقطةٌ في `bookings.trip`، يكتبها **مُشغّل على الجدول**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * العميل يختار الحساب **بعد** الحجز، فالعمولة ليست رقماً واحداً يُجمَّد بل
 * **جدولاً**. ولذلك تُجمَّد الجدولة كلها لحظة الحجز في مفتاح واحد:
 *
 *     trip -> 'paymentFees' = { "<accountId>": { kind, value, amount }, … }
 *
 * وثلاثة أسباب تجعل هذا هو الشكل الصحيح لا تفصيلاً في التخزين:
 *
 * 1. **هي آلية التجميد القائمة نفسها لا ثانيةٌ بجوارها** (**D-10**): `trip` هي
 *    اللقطة التي تحمل الخصم والخدمات وساعات الانتظار سلفاً.
 * 2. **وتخرج إلى العميل بلا سطح جديد ولا منحة جديدة**: `get_booking_by_token`
 *    ترجع `trip` كاملاً لـ `anon` منذ `0007`. جدولٌ مستقل كان سيستلزم دالة
 *    `security definer` ثالثة ومنحةً لـ `anon` — سطح هجوم مقابل صفر مكسب.
 * 3. **ولا تحمل حرفاً يعرّف**: المفتاح `uuid` والقيمة ثلاثة أرقام. لا مقبض ولا
 *    اسم حساب ولا رصيد — فالقاعدة (١) في `0060` تبقى صحيحة بحرفها.
 *
 * 🔒 **والكاتب مُشغّلٌ على `bookings` لا سطرٌ في `create_booking`** — وهذا قرارٌ
 * لا تفصيل:
 * - **لأن `create_booking` ليست الطريق الوحيد إلى الجدول.** الدرس محفورٌ في
 *   **D-45**: حارسٌ داخل الدالة يتخطّاه إدراجٌ مباشر عبر PostgREST، ونُقل إلى
 *   الجدول لهذا بعينه. لقطةٌ ناقصة تعني حجزاً بلا عمولات — أي **مجاناً**.
 * - **ولأن استنساخ جسمٍ بعشرين وسيطاً هو بعينه ما وُلد منه انحدار D-58.** لا
 *   يُلمس حرفٌ من `create_booking`، فالانحدار مستحيلٌ بنيوياً لا مستبعَدٌ
 *   بالانتباه (القاعدة ١٢ في `handover/INDEX.md`).
 *
 * ⚠ **وقاعدة الغياب مكتوبة لأنها تُسأل:** حسابٌ لا مفتاح له في اللقطة **بلا
 * عمولة**. فالحساب الذي أُنشئ أو رُفعت عمولته بعد الحجز **لا يمسّ حجزاً قائماً**
 * — وهو نصّ شرط بدر. واتجاه الخطأ الوحيد الممكن في مصلحة العميل، وهو الاتجاه
 * الذي تُقبل فيه الأخطاء في المال.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٤ — الحدّ في الجدول لا في الواجهة
 * ══════════════════════════════════════════════════════════════════════════
 *
 * قيد `payment_accounts_fee_chk` **واحدٌ يحكم العمودين معاً**:
 *
 *     (none    و القيمة = 0)
 *  أو (fixed   و 0 ≤ القيمة ≤ 100000)
 *  أو (percent و 0 ≤ القيمة ≤ 100)
 *
 * فنسبةٌ فوق المئة أو مبلغٌ سالب **مستحيلان على مستوى الصف**، لا مرفوضَين في
 * نموذج. والنوع المجهول يسقط من الفروع الثلاثة فيُرفض هو الآخر — قيدٌ واحد
 * برسالة واحدة بدل قيدين يتفارقان. والواجهة تتحقق قبله لتقول **رسالة مفهومة**،
 * لا لتحرس: من يكتب من محرر SQL يقع على القيد نفسه.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٥ — لا عمولة على وعاءٍ لا يُحوَّل إليه — **رفضاً لا قسراً**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * النقدية تُسلَّم يداً بيد، ووعاء تسوية البوابات مقبضه معرّفٌ داخلي (`0060`).
 * فعمولةٌ عليهما **لا تصل عميلاً أبداً** — إعدادٌ يبدو محفوظاً ولا يفعل شيئاً.
 *
 * والحارس `TR002` **يرفض ولا يقسر**، حرفياً على قرار `0060`: القسر الصامت هو
 * العيب الذي جاءت تلك الهجرة تصلحه (خانةٌ يقبلها المتصفح ويقلبها الخادم بصمت).
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٦ — قيمة الإيصال تصير **الإجمالي المحوَّل**، والحساب مُدخَل لا سعر
 * ══════════════════════════════════════════════════════════════════════════
 *
 * `attach_receipt` كانت تثبّت `payments.amount = bookings.amount_due`. ومع عمولة
 * يصير ذلك **رقماً لا يطابق صورة الإيصال في يد المشرف** — والمطابقة هي وظيفة
 * الصفّ كلها (**D-52**: «به وحده يُطابَق القيد مع كشف البنك بعد شهرين»). فمشرفٌ
 * يقارن ٢٬٧٤٠ في الصورة بـ٢٬٧٢٠ في السطر يرفض تحويلاً سليماً.
 *
 * 🔒 **فالمبلغ صار `amount_due + fee(الحساب)`، وما زال يُحسب في SQL من الحجز
 * ومن اللقطة المجمَّدة — لا من المتصفح.** المتصفح يرسل **أي حساب حوّلتَ إليه**،
 * وهو مُدخَلٌ كفئة السيارة لا سعرٌ (**D-09** بحرفه: «الواجهة ترسل المدخلات،
 * والقاعدة تعيد الحساب»). وأقصى ما يشتريه كذبٌ فيه هو **فرق العمولتين** — جنيهٌ
 * أو عشرون — والصورة أمام المشرف تحسمه؛ بينما قبولُ `amount` من المتصفح كان
 * يشتري ثمن الرحلة كله، ولذلك بقي مرفوضاً.
 *
 * ⚠ **عاقبة النقض:** إعادة تثبيت المبلغ على `amount_due` وحده تُنتج فرقاً دائماً
 * بين كل إيصال وصورته، فيتعلّم المشرف تجاهُل الفرق — وهو اليوم الذي يمرّ فيه
 * تحويلٌ ناقصٌ حقيقي (النمط: «الإنذار الذي يرنّ على ضجيج يصمت يوم الحريق»).
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٧ — ما لا يُبنى في هذه الدفعة، بسببٍ مكتوب (**D-39**)
 * ══════════════════════════════════════════════════════════════════════════
 *
 * - **لا عمولة على بوابات البطاقات** (`payment_providers`). البوابة ليست صفاً
 *   يختاره العميل من `payment_accounts` بل مزوّداً له جلسةٌ ومبلغٌ يُقفَل في
 *   `payment_intents` ويُتحقق من توقيعه (**D-28**)؛ فإضافة العمولة هناك تمسّ
 *   `create_payment_intent` و`settle_payment_intent` والتسوية والإحكام معاً.
 *   **المُحفِّز:** أول حساب بوابة حقيقي يفتحه بدر.
 * - **لا قيد مصروف مقابل** للعمولة في الدفتر. الصفّ يسجّل ما وصل، ومصروفُ
 *   المحفظة — إن اقتطعته منّا لا من المرسِل — بابُ مصروفاتٍ قائم في الخزينة.
 *   **المُحفِّز:** أول كشف محفظة يُظهر اقتطاعاً من جانبنا.
 * - **لا عمولة على العربون وحده دون الباقي**: الباقي نقدٌ مع السائق (§٢).
 */

/** كيف تُحسب عمولة الحساب — والقيمة تُقرأ بحسبه (**§٤**) */
export type PaymentFeeKind = "none" | "fixed" | "percent";

/**
 * إعداد العمولة على حساب دفع — عمودان على `payment_accounts` يديرهما بدر من
 * `/admin/payment-accounts`.
 */
export type PaymentAccountFee = {
  kind: PaymentFeeKind;
  /**
   * جنيهاً حين `fixed`، ونسبةً مئوية من `bookings.total` حين `percent`.
   * ⚠ ومداها مفروضٌ بقيد جدول لا بتحقق واجهة (**§٤**).
   */
  value: number;
};

/**
 * سطر واحد من اللقطة المجمَّدة في `trip -> 'paymentFees'`.
 *
 * 🔒 الثلاثة تُخزَّن معاً كما تُخزَّن `unitPrice` و`lineTotal` في
 * `booking_extras`: `amount` هو ما يُقرأ ويُجمع، و`kind`/`value` هما ما يجعل
 * الرقم **قابلاً للتفسير بعد سنة** حين تكون الإعدادات قد تغيّرت مرتين.
 */
export type FrozenPaymentFee = {
  kind: PaymentFeeKind;
  value: number;
  amount: number;
};

/**
 * حساب تحويل كما يصل صفحة الحجز من `available_payment_accounts(text, numeric)`.
 *
 * ⚠ الأرقام الثلاثة الأخيرة **محسوبة في Postgres** (**D-05**): الواجهة تنسّقها
 * ولا تجمع منها شيئاً. وأي جمعٍ هنا يفتح باب «رقمين لنفس المبلغ في شاشتين».
 */
export type PaymentAccountChoice = {
  id: string;
  kind: string;
  label: string;
  handle: string;
  holderName: string | null;
  /** عمولة هذا الحساب على هذا الحجز — مجمَّدة لحظة الحجز، وصفرٌ إن لا عمولة */
  fee: number;
  /** `amount_due + fee` — ما يحوّله العميل الآن إن اختار هذا الحساب */
  dueWithFee: number;
  /** `total + fee` — إجمالي الفاتورة بهذا الحساب */
  totalWithFee: number;
};

/**
 * أعمدة لا يجوز أن تبلغ متصفّح الزائر عبر طريق التوكن — تُقرأ في الفحص الذاتي
 * للهجرة كما قرأتها `0060`. توسيع نوع الإرجاع بالعمولة **لا يفتح** هذا الباب،
 * والقائمة مكتوبة هنا كي يُفحَص كل توسيعٍ قادم عليها لا على الذاكرة.
 */
export const PAYMENT_ACCOUNT_FORBIDDEN_COLUMNS = [
  "daily_headroom",
  "monthly_headroom",
  "opening_balance",
  "daily_cap",
  "monthly_cap",
  "sort",
  "active",
] as const;

/** حدود القيد في الجدول — مكرَّرة هنا للرسائل وحدها، والحاكم قيد `payment_accounts_fee_chk` */
