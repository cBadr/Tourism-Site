export const isStatSection = (value: unknown): value is StatSectionKey =>
  typeof value === "string" && STAT_SECTIONS.some((section) => section.key === value);

export function statSection(key: StatSectionKey): StatSection {
  const found = STAT_SECTIONS.find((section) => section.key === key);
  // لا يقع عملياً: النوع مغلق والمصفوفة تغطيه. الحارس يمنع انهيار الشاشة لو
  // حُذف بند من المصفوفة بلا تحديث النوع.
  if (!found) {
    return {
      key,
      label: key,
      path: STATS_BASE_PATH,
      tagline: "",
      help: "قسم غير معرَّف في سجل الأقسام.",
    };
  }
  return found;
}
