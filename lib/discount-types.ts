/**
 * تواقيع Postgres (هجرة 0024) — **هذا الملف هو المرجع الأوحد لأسمائها.**
 * أي دالة تُولد بعده تُضاف هنا في نفس الالتزام.
 *
 *   coupons                 — الكوبونات كما تديرها اللوحة
 *   coupon_redemptions      — كل استخدام: الكوبون والحجز والهاتف والقيمة (append-only)
 *   promo_banners           — بانرات العرض
 *
 *   apply_discount(p_code text, p_total numeric, p_class_slug text,
 *                  p_partner_cost numeric, p_phone text)
 *       returns  (applied boolean, amount numeric, total_after numeric,
 *                 clamped boolean, rejection text)
 *       — الدالة الوحيدة التي تحسب خصماً. تُستدعى **بعد** `quote_price` لا داخلها.
 *         تفرض أرضية الهامش بنفسها (القاعدة ٣) فلا يمكن لمستدعٍ أن يتخطاها.
 *
 *   redeem_coupon(p_code text, p_booking uuid, p_amount numeric, p_phone text)
 *       returns uuid
 *       — تُستدعى داخل معاملة `create_booking` وحدها. تزيد العدّاد وتكتب صف
 *         الاستخدام ذرّياً، فحجزان متزامنان لا يتجاوزان سقف الاستخدام.
 *
 *   v_stats_discounts       — إحصائيات القسم السابع
 *
 * وتُوسَّع في نفس الهجرة:
 *   - `quote_public()` بحقول الخصم في **نوع إرجاعها** صراحةً، وإلا لم تصل الواجهة (D-18).
 *   - `create_booking(...)` بمعامل رمز الكوبون، ولقطة تفصيل السعر بحقول الخصم.
 *   - `section_stats(p_section ...)` بقسم سابع `discounts` — وهي دالة مركزية
 *     ترفض اليوم أي قسم خارج الستة، فالتوسعة هجرة إلزامية لا شاشة جديدة.
 */

/**
 * ما لا تفعله هذه المرحلة — مؤجَّل بسبب مكتوب لا محذوف (D-39):
 *
 * - **حسابات العملاء والولاء** ⇒ المرحلة ١٢ب. السبب: حساب العميل يضيف صنفاً
 *   ثالثاً من `authenticated` لأول مرة في المشروع، وكل سياسة RLS وكل
 *   `grant ... to authenticated` في ٢٣ هجرة كُتبت على افتراض «كل authenticated
 *   متعهد أو موظف» (D-20). تبدأ ١٢ب بمراجعة كل منح قائم قبل إنشاء أول حساب.
 *
 * - **قائمة عروض الأسعار المهجورة** ⇒ مؤجَّلة. السبب: لا مصدر بيانات لها.
 *   `funnel_events` بلا PII **بنيوياً لا انضباطياً**، و`quote_requests` نموذج
 *   «اطلب عرض سعر» لا العروض الفورية. بناؤها يعني جدولاً يحمل اسم وهاتف من
 *   لم يحجز — وهو بالضبط ما تفاداه تصميم المرحلة ١٠ عمداً. قرار خصوصية يخصّ بدر.
 *
 * - **تخصيص الكوبون لمسار** ⇒ مؤجَّل حتى يُعرَّف «المسار» تسعيرياً.
 *
 * - **تراكم الخصومات**: كوبون واحد لكل حجز، ولا يتراكم مع غيره. حين تصل
 *   المرحلة ١٢ب بالنقاط يُحسم التراكم صراحةً بسقف إجمالي للخصم.
 */
