/**
 * عقد الخصومات والتحفيز (المرحلة ١٢أ) — المرجع الأوحد.
 *
 * من VISION.md سطر ٧٦، وهو **كل** ما تقوله الرؤية عن هذه الأنظمة:
 * «وأنظمة مكملة: نظام التحفيز — نظام الخصومات — نظام الولاء».
 * وموضعه داخل قسم «آلية التسعير» لا في قسم مستقل — أي أن الرؤية تصنّفها
 * **مكمِّلات للتسعير**. أما الكوبونات والنقاط وحسابات العملاء فتفصيلٌ من خارطة
 * الطريق لا من الرؤية؛ ولذلك قُسّمت المرحلة: ١٢أ الخصومات والتحفيز (هذا العقد)،
 * و١٢ب حسابات العملاء والولاء (مؤجَّلة بقرار بدر 2026-08-13).
 *
 * ── ست قواعد تحكم التصميم ──────────────────────────────────────────────────
 *
 * (١) **الخصم طبقة تالية لبناء السعر، لا خطوة داخله.**
 *     D-11 يقول «الذروة آخر خطوة دائماً»، ومنطق الخصم يقتضي أن يكون هو الأخير.
 *     لا صياغة تُرضي الاثنين، فيُحسم صراحةً: **D-11 يحكم بناء السعر داخل
 *     `quote_price`** (الأرضية ← معامل العودة ← الانتظار ← الذروة)، والخصم يقع
 *     **بعد** الناتج المبني في دالة مستقلة. هذا نقض جزئي مُعلَن لحرفية D-11،
 *     مكتوب هنا بلفظه كي لا يُمرَّر بصمت.
 *     والنتيجة العملية: خصم ١٠٪ يعني ١٠٪ من السعر الذي يراه العميل — لا ١٢٪
 *     كما كان سيصير لو خُصم قبل الذروة.
 *
 * (٢) **الخصم من هامش الموقع وحده، ولا يمسّ تكلفة المتعهد أبداً.**
 *     تكلفة المتعهد التزام تعاقدي لا علاقة له بحملة تسويقية للموقع.
 *
 * (٣) **الخصم ممنوع أن يُنزل الهامش تحت أرضيته المفروضة — بحاجز في SQL.**
 *     هذه القاعدة وحدها تحلّ ثلاثة تصادمات: تبقى `min_price` صمام أمان كما
 *     تسمّيها الخارطة، ويبقى سقف البث في 0014 صحيحاً وهو مشتقّ من الإجمالي
 *     **بعد** الخصم (أي من الاقتصاد الحقيقي)، ويستحيل الإسناد الآلي بخسارة —
 *     وهي عاقبة نقض D-16 المكتوبة. الحدّ يُفرض في الدالة لا في شاشة الكوبون
 *     (سابقة D-16: الأرضية في القاعدة لا في طبقة التطبيق).
 *
 * (٤) **الخصم المطبَّق يُجمَّد في لقطة الحجز** كما تُجمَّد بقية تفاصيل السعر.
 *     تعديل الكوبون أو حذفه بعد الحجز لا يغيّر حجزاً قائماً (سابقة D-10).
 *
 * (٥) **الخصم ليس حدثاً نقدياً فلا قيد له في الدفتر.** ما يدخل الخزينة هو
 *     المحصَّل فعلاً، و`bookings.total` هو الإجمالي **بعد** الخصم — فتقرير
 *     هامش الرحلة و`v_booking_profit` يصيران صحيحين تلقائياً بلا قيد جديد.
 *     («ويظهر أثرها في الكشوف» في الخارطة يتحقق بهذا، لا باختراع قيد
 *     «إيراد لم يُقبض» وهو مفهوم لا وجود له في هذا النظام.)
 *
 * (٦) **رمز الكوبون ليس سرّاً، لكنه ليس مباحاً للتخمين.** التحقق من الرمز
 *     مسار عام يقبل مدخلاً من المتصفح، فيلزمه حدّ معدّل صريح — وإلا جُرِّبت
 *     آلاف الرموز حتى يُصاب رمز صالح.
 */

/** نوع الخصم */
export type DiscountKind = "percent" | "amount";

/**
 * الكوبون كما تديره اللوحة.
 *
 * **النطاق: الفئة فقط.** خارطة الطريق تقول «تخصيص لفئة/مسار»، و«المسار» ليس
 * كياناً في التسعير: التغطية تُحسب بنطاقات كيلومترية حول نقطتين، وصفحات
 * `/routes/[slug]` كيان محتوى وسيو لا كيان تسعير. فتخصيص الكوبون لمسار
 * **مؤجَّل بسبب مكتوب** حتى يُعرَّف «المسار» تسعيرياً (D-39: التأجيل مسموح والحذف ممنوع).
 */
export type Coupon = {
  id: string;
  /** الرمز كما يكتبه العميل — يُقارَن بلا حساسية لحالة الأحرف ولا مسافات */
  code: string;
  kind: DiscountKind;
  /** نسبة مئوية أو مبلغ بعملة الموقع، بحسب `kind` */
  value: number;
  /** سقف قيمة الخصم بالجنيه حين يكون `kind = "percent"` — null بلا سقف */
  maxAmount: number | null;
  /** لا يعمل الكوبون إن كان إجمالي الرحلة أقل من هذا */
  minTripTotal: number | null;
  /** فئات بعينها — مصفوفة فارغة تعني كل الفئات */
  classSlugs: string[];
  startsAt: string | null;
  endsAt: string | null;
  /** سقف استخدام إجمالي — null بلا سقف */
  maxUses: number | null;
  /** سقف استخدام لكل عميل. **الهوية اليوم هي رقم الهاتف وحده** */
  maxUsesPerPhone: number | null;
  enabled: boolean;
  usedCount: number;
};

/**
 * سبب رفض الكوبون — الاتحاد مغلق، ولكل قيمة نص عربي واحد في الواجهة.
 *
 * **قاعدة عرض:** الرسالة الظاهرة للعميل لا تفرّق بين «غير موجود» و«معطَّل»،
 * فالتفريق يخبر من يخمّن الرموز أنه اقترب. التفصيل للوحة لا للزائر.
 */
export type DiscountRejection =
  | "not-found" // لا وجود له، أو معطَّل، أو خارج نافذة الصلاحية
  | "expired"
  | "not-started"
  | "exhausted" // بلغ سقف الاستخدام الإجمالي
  | "per-customer-limit"
  | "class-not-eligible"
  | "below-min-total"
  | "floor-guard" // الخصم يخترق أرضية الهامش ⇒ يُرفض أو يُقلَّص
  | "rate-limited";

/**
 * نتيجة تطبيق الخصم على سعر مبنيّ.
 *
 * **`amount` قد يكون أقل من القيمة الاسمية للكوبون** حين تتدخل أرضية الهامش:
 * كوبون ٣٠٪ على رحلة هامشها ٢٠٪ لا يُرفض بالضرورة، بل يُقلَّص إلى ما تحتمله
 * الأرضية ويُعلَم بـ `clamped`. الشفافية هنا مقصودة: المالك يجب أن يرى أن
 * حملته لم تُطبَّق كما أعلنها، لا أن يكتشف ذلك من فرق في الأرقام.
 */
export type DiscountOutcome = {
  applied: boolean;
  code: string | null;
  kind: DiscountKind | null;
  /** قيمة الخصم الفعلية بالجنيه بعد كل الحدود */
  amount: number;
  /** الإجمالي قبل الخصم — يُحفظ في اللقطة كي يبقى الأصل معروفاً */
  totalBefore: number;
  /** الإجمالي بعد الخصم — هو `bookings.total` */
  totalAfter: number;
  /** true إن قلّصته أرضية الهامش عن قيمته الاسمية */
  clamped: boolean;
  rejection: DiscountRejection | null;
};

/** إعدادات نظام الخصومات — من اللوحة (اعتبار ٢) */
export type DiscountSettings = {
  enabled: boolean;
  /** أقصى نسبة خصم يقبلها النظام مهما كان الكوبون — حارس فوق الحارس */
  maxPercent: number;
  /** أدنى هامش يجب أن يبقى بعد الخصم، نسبةً من تكلفة المتعهد */
  minMarginPercentAfterDiscount: number;
  /** أدنى هامش بالجنيه يجب أن يبقى بعد الخصم */
  minMarginAmountAfterDiscount: number;
  /** محاولات التحقق من الرمز المسموح بها لكل عنوان في الدقيقة */
  verifyRateLimitPerMinute: number;
};

