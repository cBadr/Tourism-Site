/**
 * «بلا استثناء» في نصّ الملاحظة تعني **كل خيار له أثر**، لا كل خانة يمكن رسمها.
 * وهذه استُبعدت بمبرر، لا سهواً:
 *
 * • **`<meta name="keywords">`** — جوجل توقّف عن قراءته سنة ٢٠٠٩ وأعلن ذلك
 *   صراحةً، وبينج مثله. حقلٌ يملؤه المالك بعناية ولا يفعل شيئاً **أسوأ من
 *   غيابه**: يستهلك وقته ويوهمه أنه ضبط شيئاً. (نفس منطق رفض المؤشر المخترع
 *   في الملاحظة ١٢.)
 *
 * • **`priority` و`changefreq` لكل صفحة في خريطة الموقع** — أعلنت جوجل أنها
 *   تتجاهلهما. القيم الحالية في `app/sitemap.ts` تبقى كما هي بلا شاشة تحرير.
 *
 * • **تحويلات بنمط/بادئة (wildcard)** — تكلفتها في الوسيط عالية، ولا حالة
 *   واحدة تحتاجها اليوم (‏`redirects` فارغ). مُحفِّزها: أول إعادة هيكلة مسارات.
 *
 * • **IndexNow / إخطار محركات البحث بعد النشر** — يحتاج نطاقاً حياً، والنشر
 *   مؤجَّل بقرار المالك. مُحفِّزه: يوم شراء الدومين.
 *
 * • **وسما تحقق GSC وبينج** — يبقيان في `/admin/integrations` ولا يُنقلان:
 *   القاعدة ١ في `lib/analytics-types.ts` تجمع كل معرّفات الخدمات في كائن
 *   واحد، وتقسيمه يصنع مصدرين. يُعرضان في مركز السيو **بالقراءة مع رابط**.
 */

