/**
 * الحقول المُضافة إلى `PageMeta` في `lib/content-types.ts`.
 *
 * **ولماذا لا عمود جديد في `pages`؟** لأن `meta` عمود `jsonb` أصلاً، وتوسيعه
 * لا يحتاج هجرة ولا يمسّ صفاً قائماً. والمفتاح الغائب في صفٍّ قديم يُقرأ
 * «غير مضبوط» فيسقط إلى الافتراضي الآمن.
 */
export type PageSeoExtras = {
  /**
   * منع فهرسة صفحة **منشورة**.
   *
   * وهي حاجة حقيقية لا ترف: اليوم الخياران «منشورة ومفهرسة» أو «مسودة مخفية عن
   * الزوار». والحالة الوسطى مطلوبة فعلاً — صفحة شكر، صفحة عرضٍ مؤقت، نسخةٌ
   * مكرّرة تُبقى للزوار وتُخفى عن البحث كي لا تنافس أصلها على الكلمة نفسها.
   */
  noindex: boolean | null;
  /** استثناء الصفحة من خريطة الموقع — منفصل عن `noindex` بقصد (انظر أدناه) */
  excludeFromSitemap: boolean | null;
  /** صورة مشاركة تخصّ هذه الصفحة — تسبق صورة الموقع */
  ogImageUrl: string | null;
  /**
   * 🔒 مسار قانوني مخصّص — **داخلي فقط ويبدأ بـ`/`**.
   *
   * ولماذا القيد؟ لأن canonical إلى نطاق خارجي يهدي وزن الصفحة لموقع آخر، وهو
   * أسرع طريقة لإخراج صفحة من النتائج بلا رسالة خطأ واحدة. والحاجة المشروعة
   * الوحيدة هنا داخلية: صفحتان بمحتوى متقارب تُوجَّه إحداهما إلى الأخرى.
   *
   * ⚠ ولا يمسّ بادئة اللغة إطلاقاً (D-24): يُكتب المسار العربي الأصيل
   * (‏`/services/airport-transfer`) وتُركَّب البادئة في `lib/seo.ts` كما لكل مسار.
   */
  canonicalPath: string | null;
};

