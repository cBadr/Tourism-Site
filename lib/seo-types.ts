/**
 * عقد مركز السيو المتكامل (الدفعة ٤ — الملاحظة ٤) — المرجع الأوحد.
 *
 * نصّ المالك في `docs/VISION.md` ملحق ٢ ملاحظة ٤:
 * «إعدادات السيو فقيرة — المطلوب صفحة كاملة مخصّصة للسيو تشمل كل خيارات السيو
 * والميتاداتا **بلا استثناء**.»
 *
 * ── الشكوى قابلة للتشخيص بدقة، والجرد أثبتها ──────────────────────────────
 *
 * `site_settings.seo` كان يحمل **حقلين لا ثالث لهما** (`titleTemplate` و
 * `defaultDescription`)، **وكلاهما يُحرَّر في `/admin/settings` لا في مركز
 * السيو** — أي أن الشاشة المسمّاة «مركز السيو» لا تملك إعداد سيو واحداً. وكل
 * ما عداه مثبَّت في الكود: `robots.txt` قاعدةٌ واحدة صمّاء، وصورة المشاركة ملف
 * ثابت، ونوع بطاقة إكس مكتوب حرفياً، ولا سبيل لمنع فهرسة صفحة منشورة.
 *
 * ── القرار الذي يجعل هذا العمل بلا هجرة ───────────────────────────────────
 *
 * `pages.meta` و`site_settings.value` **كلاهما `jsonb`** — فتوسيعهما تغييرُ
 * عقدٍ وواجهة لا تغييرُ مخطط. ولهذا نتيجتان تستحقان الذكر:
 *   • **صفر هجرة** في هذه الملاحظة، وصفر خطر على بيانات قائمة.
 *   • وكل تعديل سيو **يُسجَّل تلقائياً** في `audit_log`، لأن `pages` و
 *     `site_settings` من الجداول الأربعة والثلاثين المرصودة منذ الملاحظة ١٥.
 *
 * ⚠ **والمفتاح الغائب ليس خطأً**: صفٌّ قديم في `pages.meta` لا يحمل `noindex`
 * يُقرأ «غير مضبوط» فيسقط إلى الافتراضي الآمن (مفهرَسة). فلا ترحيل بيانات ولا
 * قيمة تُكتب في صفوف لم يلمسها المالك.
 *
 * ── ثلاثة حدود لا تُتجاوز في أي حقل هنا ───────────────────────────────────
 *
 * **(١) D-24 — الروابط العربية بلا بادئة.** لا حقل في هذا العقد يمسّ بناء
 * المسار: `canonicalPath` أدناه **مسار داخلي فقط** ولا يقبل نطاقاً خارجياً،
 * لأن canonical يشير إلى موقع آخر يعني إهداء وزن الصفحة لغيرك.
 *
 * **(٢) D-25 — لا تُعلَن لغة قبل أن يكون فيها محتوى منشور.** خريطة الموقع
 * وhreflang يقرآن `enabled_locales()` وحدها، ولا خيار في هذه الشاشة يتخطّاها.
 *
 * **(٣) D-04 — صفر نص علامة في الكود.** كل قيمة هنا من القاعدة، بما فيها صورة
 * المشاركة الافتراضية التي كانت ملفاً ثابتاً في المستودع.
 */

