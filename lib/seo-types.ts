/**
 * حقول `LocalBusiness` في البيانات المهيكلة.
 *
 * **ولماذا هي أعلى عائد سيو هنا تحديداً؟** لأن هذا نشاط نقل **محلي**: من يبحث
 * عن «ليموزين مطار القاهرة» يبحث بنيّة محلية، وجوجل يرتّب النتائج المحلية
 * بإشارات لا تخرج إلا من بطاقة نشاط مكتملة — العنوان والإحداثيات وساعات العمل
 * ونطاق السعر. والمخطط الحالي يُخرج **ستة حقول** ولا شيء من هذه.
 *
 * ⚠ **وكل حقل هنا اختياري بـ`null`، ولا يُخترع له افتراضي.** بطاقة نشاط تعلن
 * عنواناً غير صحيح أسوأ من بطاقة بلا عنوان: الأولى تُفقد الثقة عند أول زائر
 * يصل إلى مكان لا وجود له، والثانية تنقص إشارةً وحسب. (نفس منطق `tariffs`
 * و`extra_services` اللذين يخرجان بلا بذرة.)
 */
export type BusinessInfo = {
  /** الشارع والرقم */
  streetAddress: string | null;
  /** المدينة */
  addressLocality: string | null;
  /** المحافظة */
  addressRegion: string | null;
  postalCode: string | null;
  /** رمز الدولة بحرفين — `EG` */
  addressCountry: string | null;
  latitude: number | null;
  longitude: number | null;
  /**
   * ساعات العمل بصيغة schema.org — `"Mo-Su 00:00-23:59"`.
   * نصّ حرّ لأن الصيغة معيارية ومعروفة، وبناء محرِّر أسبوعي كامل لحقلٍ يُضبط
   * مرةً واحدة إفراطٌ في الأداة على حساب المهمة.
   */
  openingHours: string | null;
  /** نطاق السعر — `$$` أو `٥٠٠–٣٠٠٠ ج.م` */
  priceRange: string | null;
  /** المناطق المخدومة — تخرج `areaServed` (كان مثبَّتاً `"EG"` في الكود) */
  areaServed: string[];
};

