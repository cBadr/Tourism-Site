/** نوع بطاقة إكس — كان مكتوباً حرفياً في `lib/seo.ts` */
export type TwitterCardType = "summary" | "summary_large_image";

/**
 * قواعد `robots.txt`.
 *
 * كان الملف قاعدةً واحدة صمّاء: `allow: /` مع `disallow: /admin, /portal`.
 * وثلاثة أشياء لم تكن ممكنة وهي مطلوبة فعلاً:
 *   • **إطفاء الفهرسة كلياً** — موقع تجريبي أو نسخة قبل الإطلاق تُفهرَس اليوم
 *     بلا أي مفتاح لمنعها، وسحبُ صفحةٍ من النتائج بعد فهرستها أبطأ بكثير من
 *     منعها ابتداءً.
 *   • **منع مسار بعينه** بلا نشر كود.
 *   • **حجب زواحف الذكاء الاصطناعي** (GPTBot · CCBot · Google-Extended …) —
 *     قرارٌ يخصّ المالك وحده: محتواه الذي يبني به ترتيبه هو نفسه ما تتدرّب عليه.
 */
export type RobotsSettings = {
  /**
   * `false` ⇒ `Disallow: /` للجميع.
   * 🔒 **افتراضه `true`** (مفهرَس): الافتراضي هو ما سيعمل في الإنتاج، وموقعٌ
   * محجوب صامتاً عن جوجل عطبٌ لا يلاحظه أحد لأسابيع (النمط ٧ في `LESSONS.md`).
   */
  indexable: boolean;
  /** مسارات إضافية ممنوعة — تُضاف إلى `/admin` و`/portal` ولا تحلّ محلّهما */
  disallow: string[];
  /** حجب زواحف نماذج الذكاء الاصطناعي */
  blockAiCrawlers: boolean;
};

export type SeoSettings = {
  /** قالب العنوان العام — `%s` موضع عنوان الصفحة */
  titleTemplate: string;
  /** الوصف الافتراضي — يُستعمل احتياطياً لكل صفحة بلا وصف */
  defaultDescription: string;
  /**
   * صورة المشاركة الافتراضية (‏١٢٠٠×٦٣٠).
   * `null` ⇒ السقوط إلى شعار العلامة، ثم إلى الملف المرفق في المستودع.
   * وترتيب السقوط هذا مقصود: المالك يضبط صورةً مصمَّمة للمشاركة، وشعارُه بديلٌ
   * أفضل من لا شيء، والملف المرفق آخر شبكة أمان.
   */
  ogImageUrl: string | null;
  /** حساب إكس للموقع بلا `@` — يخرج `twitter:site` */
  twitterSite: string | null;
  twitterCard: TwitterCardType;
  robots: RobotsSettings;
};

