/**
 * عقد دفع الويب — القناة ج٢ في
 * `docs/phase-briefs/FAILED-TRIPS-AND-PARTNER-ALERTS.md`.
 *
 * يُقرأ قبل لمس أي شيء في `lib/push/` أو `public/sw.js` أو `app/api/push/`.
 *
 * ── لماذا وُجد هذا الملف ────────────────────────────────────────────────────
 *
 * القاعدة تعرف القناة منذ `0054`: جدول الاشتراكات موجود، والتفضيلات موجودة،
 * وحساب الإتاحة يعدّ `webpush` قناةً **بالغة**. وطبقة التسليم تعرفها كذلك —
 * وترجع عنها `no-credentials` صراحةً ولا تزعم إرسالاً. الناقص شيئان لا ثالث
 * لهما: **توقيع VAPID وتشفير الحمولة** (هذا الملف وجيرانه)، و**عاملُ خدمة**
 * يعرض البطاقة على الجهاز (`public/sw.js`).
 *
 * ── ثلاثة قيود تحمل كل ما تحتها ─────────────────────────────────────────────
 *
 * 1. 🔒 **الحمولة تُشفَّر لكن لا تُؤتمَن.** ما نرسله يمرّ بخادم Apple/Google/
 *    Mozilla مخزَّناً حتى يوصله، ويُفكّ على الجهاز وحده. ومع ذلك تبقى القاعدة
 *    الحاكمة **D-19** كما هي: بطاقةُ عرضِ رحلةٍ تُبنى من الحمولة **العامة**
 *    (`dispatch_trip_payload(_, true)`) — بلا اسم عميل ولا هاتفه ولا إجمالي.
 *    والمتعهد يفتح البورتال ليرى ما يخصّه. وهذا ليس تحوّطاً زائداً: بطاقةُ
 *    الإشعار تظهر على شاشة مقفلة يراها من يقف بجوار الهاتف.
 *
 * 2. 🔒 **`endpoint` معرّفٌ ومفتاحٌ معاً** (تعليق الجدول في `0054` بنصّه): من
 *    يملكه يرسل إلى الجهاز. فلا يخرج من الخادم إلى أي واجهة — ولذلك لا يوجد
 *    في `PushDeviceView` ولا في أي نوع إرجاع يقرؤه المتصفح.
 *
 * 3. **الحدّ ٤٠٩٦ بايت للجسم كله** (الترويسة + النص المشفَّر). ليس رقماً
 *    تحوّطياً بل ما تقبله خدمات الدفع فعلاً؛ وتجاوزه يعني `413` على كل جهاز
 *    دفعةً واحدة. ولذلك الحمولة **تُقصّ قبل التشفير** لا بعده (`payload.ts`).
 */

