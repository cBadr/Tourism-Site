/**
 * ملخّص محاولة تسليمٍ واحدة إلى **كل** أجهزة متعهد.
 *
 * ⚠ و«نجح» تعني جهازاً واحداً على الأقل: متعهدٌ له هاتفٌ وحاسوب، والحاسوب
 * مطفأ — الرسالة وصلت. أما صفرُ نجاحٍ فتعذّرُ بلوغٍ يستحق التصعيد إلى التشغيل
 * (`partner-unreachable`)، ولا يُبتلع.
 */
export type PushDeliveryReport = {
  /** عدد الأجهزة المسجَّلة وقت المحاولة */
  targets: number;
  sent: number;
  failed: number;
  /** اشتراكات حُذفت لأنها ماتت (٤٠٤/٤١٠) — تُطرح من `targets` في المرة القادمة */
  pruned: number;
  /** سببٌ واحد مختصر حين لم ينجح شيء — رمزٌ أو نصُّ خطأ، للسجل لا للواجهة */
  reason: string | null;
};
