// ---------------------------------------------------------------------------

/**
 * 🔒 **هذا النوع وعامل الخدمة يتغيّران معاً أو لا يتغيّران.** عامل الخدمة يعيش
 * في متصفح المتعهد وقد يبقى نسخةً قديمة أسابيع (لا يُحدَّث إلا حين يفتح
 * البورتال)، فحقلٌ يُعاد تسميته هنا يُنتج بطاقةً فارغة على أجهزةٍ لا نراها.
 *
 * ولذلك: **الحقول تُضاف ولا تُزاح** (نفس نمط D-54)، و`v` يرتفع حين يستحيل ذلك.
 * والعامل يتسامح مع الغياب ويعرض بديلاً بدل أن ينهار — لأن بطاقةً ناقصة سطراً
 * خيرٌ من إشعارٍ لا يظهر (وأسوأ من ذلك: متصفحاتٌ تعرض «This site has been
 * updated in the background» حين يفشل عرض البطاقة، فيرى المتعهد ضجيجاً بلا معنى).
 */
export type PushPayload = {
  /** إصدار العقد — العامل يقرؤه ليعرف كيف يقرأ الباقي */
  v: 1;
  /** رمز الحدث (`trip_offered` …) — رمزٌ لا جملة، والعامل يستعمله وسماً */
  event: string;
  /** العنوان كما يظهر في البطاقة */
  title: string;
  /** السطر تحته — مبنيٌّ من الحمولة **العامة** وحدها (القيد ١) */
  body: string;
  /** وجهة النقر — مسارٌ نسبي داخل البورتال، لا عنوان مطلق */
  url: string;
  /**
   * وسم البطاقة. بطاقتان بالوسم نفسه ⇒ الثانية **تحلّ محل** الأولى ولا تتراكم.
   * ولذلك يكون معرّف الإشعار لا اسم الحدث: عرضان لرحلتين مختلفتين بطاقتان.
   */
  tag: string;
  /** مرجع الحجز إن وُجد — يُعرض في البطاقة ويسهّل المطابقة */
  ref?: string;
};

/**
 * أقصى نصٍّ صريح قبل التشفير.
 *
 * الحساب لا التقدير: جسم `aes128gcm` = ترويسة (١٦ ملح + ٤ حجم السجل + ١ طول
 * المعرّف + ٦٥ مفتاح عام = ٨٦) + نصٌّ صريح + ١ فاصل الحشو + ١٦ وسم المصادقة.
 * فالسقف المطلق ٤٠٩٦ − ٨٦ − ١٧ = ٣٩٩٣، ونأخذ ٣٦٠٠ هامشاً لأن الخطأ هنا لا
 * يظهر في التطوير: حمولةٌ قصيرة تنجح، ورحلةٌ بملاحظات طويلة تفشل بـ٤١٣ وحدها.
 */
export const MAX_PUSH_PLAINTEXT = 3600;

