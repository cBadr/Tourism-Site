/**
 * نتيجة الإرسال إلى جهازٍ واحد.
 *
 * **الشكل مطابقٌ لـ`SendOutcome`** في `lib/notifications/types.ts` عمداً
 * (`ok` · `skipped` · `error`) كي تمرّ إلى `toOutcome` بلا مترجم، ويزيد عليه
 * حقلاً واحداً:
 *
 * 🔒 **`gone`** — الاشتراك **لن ينجح أبداً** بعد الآن: ألغى المستخدم التصريح،
 * أو مُسح الموقع من الجهاز، أو أبطلت خدمة الدفع العنوان (٤٠٤/٤١٠). والفرق بينه
 * وبين `error` هو الفرق بين «احذف الصفّ» و«أعد المحاولة» — وبلا الأول يبقى
 * جهازٌ ميت يعدّ المتعهد «بالغاً» في `partner_channels`، فيتخطّاه البثّ… لا،
 * بل **يشمله** البثّ ولا يصله شيء. وهو بالضبط العيب الذي وُجدت هذه الموجة له.
 */
export type PushSendOutcome =
  | { ok: true }
  | { ok: false; skipped: string; gone?: boolean }
  | { ok: false; error: string; gone?: boolean };

/** هل تقول هذه النتيجة «احذف هذا الاشتراك»؟ */
export function isGone(outcome: PushSendOutcome): boolean {
  return outcome.ok === false && outcome.gone === true;
}

