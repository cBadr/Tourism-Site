/**
 * ما يحتاجه المُرسِل عن جهازٍ واحد. الحقول الثلاثة كلها base64url كما تخرج من
 * `PushSubscription.toJSON()` في المتصفح وكما تُخزَّن في القاعدة حرفياً.
 */
export type PushTarget = {
  /** عنوان خدمة الدفع — سرٌّ تشغيلي لا يُعاد إلى واجهة (القيد ٢ أعلاه) */
  endpoint: string;
  /** المفتاح العام للجهاز — ٦٥ بايت غير مضغوطة بعد فكّ base64url */
  p256dh: string;
  /** سرّ المصادقة — ١٦ بايت بعد فكّ base64url */
  auth: string;
};

