/** أمشروعٌ حفظُ قالبٍ لهذا الزوج؟ — نفس شرط المُشغّل في الجدول */
export function isLegalTemplatePair(event: TemplateEvent, audience: TemplateAudience): boolean {
  return TEMPLATE_EVENT_MATRIX[event]?.legal.includes(audience) ?? false;
}

/** أيُنتَج لهذا الزوج صفٌّ فعلاً اليوم؟ — تقولها الشاشة ولا تخفيها (‏§١) */
export function isLiveTemplatePair(event: TemplateEvent, audience: TemplateAudience): boolean {
  return TEMPLATE_EVENT_MATRIX[event]?.live.includes(audience) ?? false;
}

/**
 * متغيّرات لوحة المفاتيح لهذا الجمهور — **وما ليس فيها لا يُعرض إطلاقاً**.
 * وحين يُمرَّر `event` تُرشَّح كذلك على ما يحمله الحدث فعلاً، ليُميَّز المتاح من
 * `template-var-dead` في الشاشة.
 */
export function templateVarsFor(
  audience: TemplateAudience,
  event?: TemplateEvent
): readonly TemplateVarDef[] {
  return NOTIFICATION_TEMPLATE_VARS.filter(
    (v) =>
      (v.audiences as readonly TemplateAudience[]).includes(audience) &&
      (event === undefined ||
        v.events === "all" ||
        (v.events as readonly TemplateEvent[]).includes(event))
  );
}

/** أمسموحٌ هذا الاسم لهذا الجمهور؟ — جوابُ `template-var-forbidden` بعينه */
export function isVarAllowedFor(name: string, audience: TemplateAudience): boolean {
  const def = NOTIFICATION_TEMPLATE_VARS.find((v) => v.name === name);
  return def !== undefined && (def.audiences as readonly TemplateAudience[]).includes(audience);
}
