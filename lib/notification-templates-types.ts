/**
 * `{name}` رمزٌ، و`{{` هروبٌ يُنتج `{` حرفياً.
 *
 * 🔒 **والكشف أوسع من القبول بقصد:** الماسح يلتقط **أي** `{…}` على سطرٍ واحد
 * ثم يُطابقه بالكتالوج مطابقةً حرفية. فـ`{Payout}` و`{payout }` و`{هاتف}` كلها
 * **تُرفض** ولا تمرّ نصّاً. ولو كان الكشف ضيّقاً لمرّ الخطأ المطبعي حرفياً إلى
 * رسالة عميل — وهو الفشل الصامت الذي وُجدت لوحة المفاتيح (قرار د) لتمنعه.
 */
export const TEMPLATE_TOKEN_SCAN = /\{\{|\{([^{}\n]{1,64})\}/g;
/** الاسم المقبول بعد الكشف — والمطابقة بالكتالوج لا بالنمط وحده */
export const TEMPLATE_VAR_PATTERN = /^[a-z][a-z0-9_]{1,31}$/;

/** حدود الطول — لكلٍّ سببٌ في السطح الذي يستهلكه */
