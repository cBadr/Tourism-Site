/**
 * وصف شريط النبض لشاشة إدارية واحدة.
 *
 * `cardKeys` **ترشيح لا تجميع**: الشاشة تختار من بطاقات قسمها ما يمثّل عملها،
 * بترتيب المفاتيح لا بترتيب وصولها (`cardsByKeys` في `lib/stats/cards.ts`).
 * ومفتاح غير موجود يُسقَط بصمت — فتوسيع الهجرة ببطاقة جديدة لا يكسر شاشة،
 * وحذف بطاقة من الهجرة لا يترك فراغاً في الشبكة.
 *
 * ⚠ وقائمة فارغة تعني «كل بطاقات القسم» لا «لا بطاقات» — الفرق مقصود: قسمٌ
 * وُلد لشاشة واحدة يعرض كل ما عنده بلا تكرار أسمائه في موضعين.
 */
export type PagePulseSpec = {
  /** القسم الذي تُقرأ منه البطاقات */
  section: PulseSectionKey;
  /** مفاتيح البطاقات المعروضة بترتيبها — فارغة = كل بطاقات القسم */
  cardKeys: string[];
  /**
   * مفتاح السلسلة الزمنية للرسم المصغّر — `null` حين لا مصدر **صادق** لها.
   * وغيابها ليس نقصاً يُسدّ لاحقاً بأي رقم: شاشة بلا بُعد زمني حقيقي
   * (الإعدادات، الصيانة، كتالوج) لا تُرسم، والقاعدة ٤ أعلاه تحكم.
   */
  seriesKey: PulseSeriesKey | null;
  /** وصف الرسم لقارئ الشاشة — إلزامي متى وُجدت سلسلة */
  seriesTitle?: string;
  /**
   * صيغة قيم السلسلة — **تُكتب صراحةً ولا تُستنتج من اسم المفتاح**.
   *
   * سببه أن الاستنتاج من الاسم يعمل صامتاً حتى يوم يُضاف قسمٌ ماليّ اسمه لا
   * يشبه أسلافه، فيُعرض مبلغٌ بصيغة عدد بلا خطأ في أي سجل — وهو بالضبط شكل
   * العطب الذي يمرّ سنةً بلا أن يلاحظه أحد.
   */
  seriesFormat?: "number" | "money";
};

/**
 * **ولا نوع سلسلة هنا — `StatSeries` في `lib/analytics-types.ts` هو النوع.**
 *
 * `pulse_series` تُرجع `(key text, label text, points jsonb)` أي `StatSeries`
 * صفاً صفاً، بنقطة **لكل يوم في المدى حتى لو كانت صفراً** (رسمٌ يقفز فوق الأيام
 * الفارغة يكذب على العين — نفس عقد `funnel_daily` في هجرة 0023).
 *
 * ⚠ كان هنا نوع `PulseSeriesRow` مطابقٌ لـ`StatSeries` حقلاً بحقل، معلَّقاً
 * عليه «ولا نوع ثانٍ لها كي لا يوجد شكلان لشيء واحد» — أي أنه كان **نقض
 * قاعدته في السطر الذي يليها**، ولم يستورده أحد. أمسكته مراجعة انحراف العقود،
 * وحُذف: العقد الذي يعلن ما لا يُستهلَك هو أول درجات الانحراف الذي كُتب لمنعه.
 */

