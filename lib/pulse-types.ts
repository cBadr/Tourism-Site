import type { StatSectionKey } from "@/lib/stats/sections";

/**
 * عقد «نبض الصفحة» (الدفعة ٤ — الملاحظة ١٢) — المرجع الأوحد.
 *
 * نصّ الملاحظة بصياغة المالك في `docs/VISION.md` ملحق ٢:
 * «لوحة التحكم جامدة — تفتقر إلى المؤشرات والرسوم البيانية. يجب أن توحي بالنشاط
 * والحركة، **ولكل صفحة مؤشراتها ورسومها الخاصة التي تمثّل واجهة ذلك الجزء — لا
 * قسماً منفصلاً** — فيدرك المدير بمجرد النظر كل المعلومات الأساسية.»
 *
 * ── خمس قواعد تحكم هذا التصميم ────────────────────────────────────────────
 *
 * (١) **«لا قسماً منفصلاً» لا تعني إلغاء `/admin/stats`.** الشاشات السبع تبقى
 *     كما هي: هي المكان الذي **يُحلَّل** فيه الرقم بفترة ومقارنة ورسم كامل.
 *     ما تضيفه هذه الملاحظة طبقةٌ ثانية: على شاشة العمل نفسها يرى المدير نبض
 *     مجالها **قبل أن يعمل فيه**. أي أن العلاقة «الشاشة تعرض، والقسم يحلّل»،
 *     ومن يحذف القسم يفقد الفترة والمقارنة والجدول التفصيلي.
 *
 * (٢) **صفر تجميع في TypeScript — بلا استثناء.** كل رقم في أي شريط نبض يصل
 *     محسوباً من Postgres. وهذا ليس تكراراً لقاعدة قديمة بل تشديد عليها: مسح
 *     الشاشات وجد أن `content` و`languages` و`seo/audit` تعدّ اليوم بـ
 *     `rows.length` على صفوف حمّلتها للعرض — وهو رقم صحيح اليوم و**كاذب لحظة
 *     دخول أي سقف صفوف** (`MAX_ROWS = 100` في شاشة الطلبات نموذجاً). كل بطاقة
 *     يستبدلها هذا العمل تنتقل إلى مصدر قاعدةٍ يعدّ الكل لا المعروض.
 *
 *     ⚠ **و`seo/audit` من الثلاث لم تُستبدل، بقرار لا سهو:** أرقامها الثلاثة
 *     (صفحات مفحوصة · بها عطب · بلا بيانات مهيكلة) تُشتق من تحليل JSON-LD في
 *     `lib/seo/audit.ts` — منطقٌ يعيش في JavaScript ولا مصدر له في القاعدة
 *     أصلاً، فنقله يعني بناء مُحلِّل ثانٍ في SQL ينحرف عن الأول. ولافتتها
 *     تصف **ما فُحص وعُرض أسفلها** فتبقى صادقة تحت أي سقف — بخلاف «صفحات
 *     الموقع» التي كانت في `/admin/seo` وتدّعي الكل. الاستبدال مؤجَّل حتى
 *     يوجد مصدر قاعدة، لا محذوف.
 *
 * (٣) **«—» لا «٠».** غياب الرقم يُكتب «—» ويُشرح سببه (هجرة ناقصة / ليس
 *     مشرفاً / تعذّرت القراءة) عبر `StatsRead` نفسه الذي تستعمله شاشات
 *     الإحصائيات. صفرٌ مكان المجهول ادعاء معرفة، وهو أخطر من فراغ صريح.
 *
 * (٤) **لا مؤشر يُخترع لشاشة لا بيانات لها.** شاشة بلا مصدر رقم صادق تبقى بلا
 *     شريط حتى يوجد مصدرها — لا بطاقات صفرية ولا مقاييس تجميلية. (نفس منطق
 *     كتالوج الخدمات الذي يخرج فارغاً في `0031` بدل بذر سعر مخترع.)
 *
 * (٥) **صفر جافاسكربت وصفر سطر قياس.** كل مكوّنات النبض خادمية بلا
 *     `"use client"`، والرسوم SVG مكتوبة يدوياً (نفس قرار المرحلة ١٠: لا مكتبة
 *     رسم). وهذا يقع كله تحت `/admin` — حيث **D-44** يمنع أي وسم قياس خارجي،
 *     فلا يذهب رقم واحد من هذه الأشرطة إلى جوجل أو ميتا.
 *
 * ── قرار معماري: `pulse_stats` تفوّض ولا تستنسخ ────────────────────────────
 *
 * الأقسام السبعة القائمة (`StatSectionKey`) تُقرأ بنداء `public.section_stats`
 * **كما هي**، والأقسام الجديدة تُحسب في دالة جديدة `public.pulse_stats` تفوّض
 * إليها:
 *
 *     pulse_stats(section) = section_stats(section)   ← للأقسام السبعة
 *                          = بطاقات محسوبة محلياً     ← للأقسام الجديدة
 *
 * ولماذا التفويض لا `create or replace` على `section_stats` نفسها؟ لأن **D-58**
 * وُلد من هذا بالضبط: الدفعة ٣ أعادت كتابة جسم دالة فوق نسخة قديمة فأعادت عيباً
 * أغلقته هجرة سابقة، وتنازلت تلقائياً عن كل الهامش. التفويض يعني أن جسم
 * `section_stats` **لا يُلمَس أصلاً**، فيستحيل أن يُنتج هذا العمل انحداراً في
 * الشاشات السبع القائمة. والثمن نداء دالة داخل دالة، وهو لا شيء.
 *
 * ── تحذير صلاحيات مقيس على القاعدة الحيّة (2026-08-14) ─────────────────────
 *
 * `section_stats` و`funnel_daily` **ممنوحتان لـ`authenticated`، وهذا صحيح
 * وضروري ولا يُنقض**: جلسة المشرف نفسها تمرّ بدور `authenticated` في PostgREST،
 * والحارس `analytics_admin_allowed()` يفحص `is_admin()` **أولاً** فيمرّر المشرف،
 * ثم يرفض `anon` و`authenticated` رفضاً قاطعاً فيسقط المتعهد. سحب المنحة يكسر
 * كل شاشات الإحصائيات للمالك نفسه.
 *
 * ⚠ أي دالة جديدة هنا تلتزم **النمط نفسه حرفياً**: `security definer` +
 * `set search_path = ''` + `analytics_admin_allowed()` سطراً أول + منحة
 * `authenticated`. ومن يمنح بلا الحارس يسلّم كل متعهد لوحةَ أرقام المنصة.
 */

