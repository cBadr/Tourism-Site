/**
 * الأقسام التي **لا شاشة تحليل لها** في `/admin/stats` وتغذّي شريط نبض فقط.
 *
 * ولماذا لا تُضاف إلى `STAT_SECTIONS` في `lib/stats/sections.ts`؟ لأن ذلك
 * السجل يقود **شريط تنقّل `/admin/stats`** وصفحاته: إضافة مفتاح هناك تعني
 * التزاماً بشاشة تحليل كاملة بفترة ومقارنة وجدول. هذه المفاتيح أصغر من ذلك
 * عمداً — مؤشرات شاشة عملٍ لا قسم تحليل.
 */
export type PulseOnlySectionKey =
  | "dispatch" // البث والإسناد — فوق v_stats_dispatch القائم بلا مستهلك بطاقات
  | "quotes" // طلبات عروض الأسعار
  | "payments" // جلسات بوابات الدفع (payment_intents)
  | "accounts" // حسابات الدفع وحدودها
  | "fleet" // الأسطول: حصة كل فئة من الحجوزات
  | "extras" // الخدمات الإضافية (الدفعة ٣)
  | "notifications" // طابور الإشعارات وتسليمه
  | "redirects"; // تحويلات السيو

/** كل ما تقبله `pulse_stats` كمعامل `p_section` — السبعة القائمة + الجديدة */
export type PulseSectionKey = StatSectionKey | PulseOnlySectionKey;

/**
 * ما تقبله `pulse_series` — **مجموعة أضيق من `PulseSectionKey`**، وهذا مقصود.
 *
 * السلسلة لا تُبنى إلا حيث يوجد **بُعد زمني صادق** في القاعدة. فقسمٌ لقطتُه
 * لحظية (`redirects` · `fleet`) أو تراكمي (`partners`) لا سلسلة له، والدالة
 * ترفضه بـ`invalid-input` بدل أن تُرجع خطاً مسطّحاً من أصفار يوحي بأن الشيء
 * قِيس ووُجد معدوماً.
 *
 * ⚠ **والنوع هنا ليس زينة:** كان `seriesKey` معرَّفاً `string` وتُقوّبه
 * `lib/stats/pulse.ts` عند النداء — أي أن خطأً مطبعياً في السجل كان يمرّ من
 * المدقّق ولا يُمسك إلا بنداء حيّ يفشل. القائمة أدناه تطابق حرفاً بحرف قائمة
 * `pulse_series` في الهجرة 0035.
 */
export type PulseSeriesKey =
  | "orders"
  | "dispatch"
  | "quotes"
  | "payments"
  | "accounts"
  | "extras"
  | "notifications";

