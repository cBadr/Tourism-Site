/**
 * «الجدول/العمود/الدالة غير موجودة» — تصنيفٌ واحد يشترك فيه أكثر من سطح.
 *
 * كان هذا التصنيف يعيش داخل `app/portal/_lib/session.ts` وحده، فلمّا احتاجه
 * سطحُ حسابات العملاء (‏١٢ب) كان أمامنا نسخُه أو استيراد البورتال في مسار
 * العميل. وكلاهما خطأ: النسخة الثانية تنحرف يوم يُضاف رمزٌ إلى الأولى (وهو
 * النمط الذي تحذّر منه القاعدة ١٢ في `handover/INDEX.md`)، واستيراد البورتال
 * من `/account` يربط سطحين لا علاقة بينهما إلا هذا السطر.
 *
 * فالمصدر هنا، و`app/portal/_lib/session.ts` **يعيد تصديره** بنفس الاسم — فلا
 * سطر واحد تغيّر في اثني عشر موضع استيراد قائم.
 *
 * ولماذا رموز Postgres ورموز PostgREST معاً؟ لأن الأخيرة تسبق الأولى أحياناً:
 * PostgREST يردّ من كاش المخطط قبل أن يصل الاستعلام إلى القاعدة أصلاً.
 */
const SCHEMA_ERROR_CODES = new Set([
  "42P01", // undefined_table
  "42703", // undefined_column
  "42883", // undefined_function
  "PGRST202", // دالة غير موجودة في كاش المخطط
  "PGRST204", // عمود غير موجود في كاش المخطط
  "PGRST205", // جدول غير موجود في كاش المخطط
]);

/**
 * هل الخطأ «هجرة لم تُطبَّق» لا «عطل»؟ الفرق ليس تجميلاً: الأول يُعرض بطاقةَ
 * حالة تشرح الخطوة الناقصة، والثاني شاشة خطأ. وخلطهما يجعل قاعدةً ناقصة الهجرات
 * تبدو منهارة، ونسخةَ Whitelabel جديدة تبدو معطوبة يوم إنشائها.
 */
export function isSchemaMissing(error: { code?: string | null } | null | undefined): boolean {
  return Boolean(error?.code && SCHEMA_ERROR_CODES.has(error.code));
}
