import { CSV_MIME } from "@/lib/export-types";
import { csvDocument, csvText } from "./csv";

/**
 * بناء ردّ التنزيل لملف CSV — الترويسات وسطر إعلان السقف.
 *
 * ما يميّز هذا الملف عن أي `Response.json` في المستودع ثلاثة أشياء، وكلها
 * منصوص عليها في `lib/export-types.ts`:
 *
 *  (١) **اسم ملف عربي يصل سليماً.** ترويسة `Content-Disposition` البسيطة
 *      محصورة بـASCII، فالاسم العربي فيها يخرج رموزاً أو يُقصّ عند أول محرف
 *      غير لاتيني. فنكتب **اسمين**: لاتينياً آمناً في `filename=`، والعربي
 *      مرمَّزاً بـRFC 5987 في `filename*=` — وكل متصفح يأخذ ما يفهمه، والحديثة
 *      كلها تفضّل الثاني.
 *
 *  (٢) **السقف يُعلَن في الملف نفسه لا في الشاشة التي نزّلته.** القسم (٣) من
 *      العقد: «ملفٌ يصدّر أول مئة صف من ألف بلا أن يقول هو أخطر شكل من أشكال
 *      الرقم الكاذب — يبدو كاملاً ويُبنى عليه قرار». والملف يسافر بالبريد ويُفتح
 *      بعد شهر بلا الشاشة التي أنتجته، فأي تحذير خارجه لا وجود له.
 *
 *  (٣) **`no-store` مطلقاً.** الملف يحمل بيانات مالية بهوية جلسة مشرف؛ نسخة في
 *      كاش وسيط أو في كاش متصفح جهاز مشترك تُسلّمها لمن يفتح الرابط بعده.
 */

// ---------------------------------------------------------------------------
// (١) إعلان السقف — سطر الذيل
// ---------------------------------------------------------------------------

/**
 * حال الصفوف لحظة الكتابة.
 *
 * `available` هي **إجمالي ما أنتجه المصدر قبل القصّ**. والأنواع الأربعة كلها
 * تعرفه اليوم من `count: "exact"` — عددٌ تحسبه `COUNT(*)` في Postgres على شرط
 * الترشيح نفسه، لا مصفوفةٌ عُدَّت هنا (نفس روح D-05 وإن لم يكن مبلغاً). فيصير
 * إعلان السقف يقيناً لا تخميناً: «٥٠٠٠ من ٨١٢٤» لا «بلغنا السقف وربما هناك
 * المزيد».
 *
 * و`null` تبقى قائمة ولا تُحذف: هي حال منادٍ **قصَّ بلا أن يَعُدّ** — عدٌّ لم
 * يصل، أو مصدرٌ لا يحتمل `count`. وحينها تُصاغ الجملة بالاحتمال، فلا يُدّعى
 * يقين لا يوجد. والحالتان مختلفتان فعلاً، وخلطهما هو بالضبط خلط «لا نعرف»
 * بـ«صفر» في القاعدة ١٤.
 */
export type RowCapReport = {
  /** السقف المعلَن لهذا النوع — من `EXPORT_ROW_CAP` */
  cap: number;
  /** عدد صفوف البيانات المكتوبة فعلاً */
  written: number;
  /** ما أنتجه المصدر قبل القصّ، أو `null` إن لم يكن معلوماً */
  available: number | null;
};

/**
 * سطر السقف بالعربية وبأرقام لاتينية.
 *
 * الأرقام لاتينية هنا أيضاً رغم أن السطر نثرٌ لا يُجمَع: ملفٌ كل أرقامه لاتينية
 * إلا سطره الأخير يدفع من يحرّره لاحقاً إلى نسخ الشكل الخطأ. والوحدة أهون من
 * الجَمال في ملف يُفتح ببرنامج جداول.
 *
 * ⚠ **الفرع الأول يقيس `available > written` لا `available > cap`.** الفرق ليس
 * تجميلياً: الأول يصف **ما وقع فعلاً** (صفوفٌ لم تخرج)، والثاني يفترض أن السقف
 * هو السبب الوحيد لنقصها. ولو نقصت لسبب آخر — بانيةٌ رشّحت، أو قصّت قبل النداء —
 * لكتب الفرع الثاني «كامل ما في الفترة» فوق ملف ناقص. وهذا بالضبط الرقم الكاذب
 * الذي كُتب هذا السطر ليمنعه، فلا يجوز أن يصنعه السطر نفسه. وأمسك الفحصُ هذه
 * الصيغةَ وهي تكذب على صفوف مصنوعة.
 */
function capSentence({ cap, written, available }: RowCapReport): string {
  if (available !== null) {
    return available > written
      ? `# ${written} صفاً من ${available} — لم تخرج البقية (سقف التصدير ${cap}). ضيّق الفترة لتصدير باقيها.`
      : `# ${written} صفاً — كامل ما في الفترة، ولم يُبلغ سقف التصدير (${cap}).`;
  }

  return written >= cap
    ? `# ${written} صفاً — بُلغ سقف التصدير (${cap}) وقد تكون هناك صفوف لم تخرج. ضيّق الفترة.`
    : `# ${written} صفاً — دون سقف التصدير (${cap}).`;
}

// ---------------------------------------------------------------------------
// (٢) اسم الملف — اسمان لا واحد
// ---------------------------------------------------------------------------

/**
 * محارف يرفضها نظام الملفات (ويندوز أضيقها)، ومعها محارف التحكّم.
 *
 * تُكتب بترميز `\u….` لا بحرفها: محرف تحكّم منسوخ داخل تعبير نمطي في ملف مصدر
 * لا يُرى في المحرّر ولا يجده البحث، فيصير تعديله لاحقاً تخميناً.
 */
const FILENAME_ILLEGAL = /[\u0000-\u001f\\/:*?"<>|]+/g;

/** كل ما ليس حرفاً لاتينياً أو رقماً أو نقطة أو شرطة — للاسم الاحتياطي */
const NON_ASCII_NAME = /[^A-Za-z0-9._-]+/g;

/**
 * الاسم الاحتياطي: لاتيني بحت، بلا مسافة ولا اقتباس.
 *
 * الاقتباس تحديداً ليس تجميلاً: `filename="a"b.csv"` يُنهي القيمة عند الاقتباس
 * الثاني، فيقرأ المتصفح ما بعده ترويسةً مشوّهة. وتنظيفه هنا يُغلق الباب بنيوياً
 * بدل الاعتماد على أن أسماء المتعهدين لن تحوي اقتباساً.
 */
function asciiFilename(base: string, fallback: string): string {
  const cleaned = base
    .replace(NON_ASCII_NAME, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "")
    .slice(0, 90);
  return `${cleaned === "" ? fallback : cleaned}.csv`;
}

/**
 * ترميز RFC 5987 لقيمة `filename*`.
 *
 * `encodeURIComponent` تترك `'` و`(` و`)` و`*` بلا ترميز، وليست من `attr-char`
 * في المواصفة — والاقتباس المفرد أخطرها لأنه فاصل الأجزاء في الصيغة
 * `UTF-8''<value>` نفسها، فوجوده داخل الاسم يُشطر القيمة. ونُبقي `!` و`-` و`.`
 * و`_` و`~` بلا ترميز لأنها `attr-char` مسموحة.
 */
function rfc5987(value: string): string {
  return encodeURIComponent(value).replace(
    /['()*]/g,
    (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`
  );
}

/** ينظّف اسماً معروضاً من محارف يرفضها نظام الملفات ويطوي مسافاته */
function safeDisplayName(value: string): string {
  return value.replace(FILENAME_ILLEGAL, " ").replace(/\s{2,}/g, " ").trim().slice(0, 120);
}

