// (٣) الردّ
// ---------------------------------------------------------------------------

export type CsvFile = {
  headers: readonly string[];
  /** الصفوف **بعد** القصّ عند السقف */
  rows: readonly (readonly string[])[];
  /** الاسم اللاتيني بلا امتداد — مثال: `partner-statement-2026-08-01_2026-08-14` */
  asciiName: string;
  /** الاسم العربي المعروض بلا امتداد */
  displayName: string;
  rowCap: RowCapReport;
  /**
   * سطر مصدر يسبق سطر السقف — «المصدر: partner_statement() · الفترة …».
   * غرضه أن يبقى الملف مفهوماً بعد أن يُعاد تسميته ويُرسَل بالبريد.
   */
  sourceNote?: string;
};

/**
 * ردّ HTTP كامل لملف CSV.
 *
 * `X-Content-Type-Options: nosniff` مضافة عمداً: الملف يحمل نصّاً كتبه بشر
 * (ملاحظات التشغيل)، ومتصفحٌ يستنتج النوع بنفسه قد يقرّر أنه HTML فيعرضه بدل
 * تنزيله — وحينها يصير ما كتبه المستخدم صفحةً تعمل على أصلنا. الترويسة تُلزمه
 * بالنوع المعلَن.
 */
export function csvFileResponse(file: CsvFile): Response {
  const trailer: string[] = [];
  /**
   * ⚠ **سطر المصدر يمرّ بـ`csvText` مثله مثل أي خانة بيانات.** وهو يُركَّب من
   * قيم قاعدة (اسم شركة المتعهد، تسمية الحساب، رمز العملة)، فسطرٌ جديد داخل
   * أحدها يشطر التعليق إلى سطرين — والثاني لا يبدأ بـ`#` فيعدّه سكربت المطابقة
   * البنكية **صفَّ بيانات**. وهذا بعينه ما كُتب طيُّ الأسطر في `csvText` لمنعه
   * (انظر ترويستها)، فلا يجوز أن يفلت منه السطر الذي يوثّق الملف نفسه.
   *
   * والاقتباس وحده لا يكفي هنا: `csvLine` تقتبس فيسلم المحلّل الكامل، ونصف من
   * يقرأ هذه الملفات فعلاً يقرؤها سطراً سطراً بلا محلّل.
   */
  if (file.sourceNote) trailer.push(`# ${csvText(file.sourceNote)}`);
  // وسطر السقف لا يحتاج بوّابة: كل ما فيه أعداد ونصٌّ ثابت في هذا الملف
  trailer.push(capSentence(file.rowCap));

  const body = csvDocument({ headers: file.headers, rows: file.rows, trailer });

  const ascii = asciiFilename(file.asciiName, "export");
  const display = `${safeDisplayName(file.displayName) || file.asciiName}.csv`;

  return new Response(body, {
    headers: {
      "Content-Type": CSV_MIME,
      "Content-Disposition": `attachment; filename="${ascii}"; filename*=UTF-8''${rfc5987(display)}`,
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff",
    },
  });
}
