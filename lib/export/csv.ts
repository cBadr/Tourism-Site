export type CsvDocument = {
  /** عناوين الأعمدة بالعربية — الصف الأول */
  headers: readonly string[];
  /** الصفوف بعد القصّ عند السقف؛ كل صف مصفوفة خانات خام */
  rows: readonly (readonly string[])[];
  /**
   * سطور تُكتب بعد البيانات — سطر تعليق لكل واحد (خانة واحدة تبدأ بـ`#`).
   * القسم (٣) من العقد يوجب فيها إعلان عدد الصفوف وحال السقف.
   */
  trailer?: readonly string[];
};

/**
 * نصّ الملف كاملاً: BOM ثم العناوين ثم الصفوف ثم سطور الذيل، وكلها بـCRLF
 * **ومعها نهاية سطر أخيرة**.
 *
 * والنهاية الأخيرة مقصودة: محلّلاً يقرأ سطراً سطراً يحتاجها كي يُغلق آخر سطر،
 * وإكسل يتجاهل السطر الفارغ الناتج عنها.
 *
 * والصفوف القصيرة تُملأ بخانات فارغة حتى طول العناوين، فيبقى الملف **مستطيلاً**
 * — جدولٌ مثلوم يزيح أعمدة إكسل عند أول صف ناقص فتُقرأ «الملاحظة» في خانة
 * «الرصيد». والصف الأطول من العناوين لا يُقصّ: القصّ يُخفي بياناً، والفيض يجعل
 * الخطأ مرئياً في أول فتحة للملف.
 */
export function csvDocument({ headers, rows, trailer = [] }: CsvDocument): string {
  const width = headers.length;

  const lines: string[] = [csvLine(headers)];

  for (const row of rows) {
    const cells = row.length >= width ? row : [...row, ...Array(width - row.length).fill("")];
    lines.push(csvLine(cells));
  }

  // سطر التعليق خانة واحدة لا صفّ بيانات، فلا يفسد جدولاً ولا يدخل مجموعاً
  for (const note of trailer) lines.push(csvLine([note]));

  return CSV_BOM + lines.join(CSV_EOL) + CSV_EOL;
}
