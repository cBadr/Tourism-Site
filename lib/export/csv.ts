/**
 * قراءة قيمة رقمية إلى حرفيّة لاتينية — أو `null` حين **لا نُعرَف** القيمة.
 *
 * و«لا نعرف» ليست صفراً (القاعدة ١٤ في `handover/INDEX.md`): الخانة الفارغة في
 * إكسل تُتخطّى في `SUM` و`AVERAGE`، أمّا الصفر المكتوب فيدخل المتوسط ويخفض
 * الرقم. فكل ما تعذّرت قراءته يخرج فارغاً لا صفراً.
 *
 * والقيمة العددية التي لا ينتج عنها `String` حرفيّةً بسيطة (أي أن حجمها بلغ
 * الصيغة الأسّية) تُعدّ خارج عالم هذا المشروع — أكبر عمود مالي فيه
 * `numeric(14,2)` أي أقل من ‎1e12 — فتخرج فارغة بدل كتابة `1e+21` في خانة يقرؤها
 * محاسب.
 */
function numericLiteral(value: unknown): string | null {
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return null;
    // `Object.is` تميّز ‎−0‎ عن ‎0‎، و`String(-0)` تُخرج "0" — وهو المطلوب
    const text = String(Object.is(value, -0) ? 0 : value);
    return CSV_NUMERIC_LITERAL.test(text) ? text : null;
  }

  if (typeof value === "string") {
    const trimmed = value.trim();
    // ⚠ الخانات العربية الهندية لا تُقبل ولا تُحوَّل: وصولها هنا يعني أن
    // مُنسِّق عرض سبقنا إلى القيمة، وهو عيبٌ يُصلَح في مصدره لا يُرقَّع هنا.
    return CSV_NUMERIC_LITERAL.test(trimmed) ? trimmed : null;
  }

  return null;
}

/** عدد صحيح أو كسري كما وصل — للعدّادات والنسب وما ليس مالاً */
export function csvNumber(value: unknown): string {
  return numericLiteral(value) ?? "";
}

/** يُلحق أصفاراً عن اليمين حتى تبلغ الخانات العشرية `minScale` — زيادة لا تقريب */
function padScale(literal: string, minScale: number): string {
  const dot = literal.indexOf(".");
  if (dot < 0) return `${literal}.${"0".repeat(minScale)}`;
  const scale = literal.length - dot - 1;
  return scale >= minScale ? literal : literal + "0".repeat(minScale - scale);
}

/**
 * مبلغ مالي — نفس أرقام القاعدة، بخانتين عشريتين على الأقل.
 *
 * ⚠ **بلا رمز عملة ولا فاصل آلاف.** العملة عمودٌ مستقل أو تُكتب في عنوان
 * العمود؛ ووصلها بالرقم (`4650 ج.م`) يحوّل العمود كله إلى نصّ في إكسل.
 *
 * والتوحيد إلى خانتين تجميلٌ **بلا فقد**: `360` تصير `360.00`، و`360.5` تصير
 * `360.50`، و`360.567` **تبقى كما هي** — لا تُقرَّب إلى `360.57`. فأي رقم يخرج
 * من هنا يساوي الرقم الذي أنتجته Postgres بالضبط، وهو شرط D-05 لا تفضيل شكلي:
 * ملفٌ مجموعُه يخالف الشاشة أسوأ من ملفٍ لا يوجد.
 */
export function csvMoney(value: unknown): string {
  const literal = numericLiteral(value);
  return literal === null ? "" : padScale(literal, 2);
}

/**
 * قيمة منطقية بالعربية — و«لا نعرف» تخرج فارغة لا «لا».
 *
 * الفرق ليس لغوياً: عمودٌ فيه «لا» يُعدّ في فلتر إكسل مع المرفوض فعلاً، فيقول
 * الملف عن صفٍّ لم يُقرأ أصلاً إنه سالب.
 */
export function csvBool(value: unknown): string {
  if (typeof value === "boolean") return value ? "نعم" : "لا";
  if (typeof value === "string") {
    const s = value.trim().toLowerCase();
    if (s === "true" || s === "t") return "نعم";
    if (s === "false" || s === "f") return "لا";
  }
  return "";
}

