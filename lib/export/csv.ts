import {
  CSV_BOM,
  CSV_EOL,
  CSV_FORMULA_PREFIXES,
  CSV_NUMERIC_LITERAL,
} from "@/lib/export-types";

/**
 * مُسلسِل CSV عربي — نقيّ، بلا اعتماديات، ولا حساب فيه.
 *
 * ينفّذ القسم (٣) من `lib/export-types.ts` حرفاً بحرف: BOM، ونهاية سطر CRLF،
 * واقتباس **كل** خانة مع مضاعفة الاقتباس بداخلها، وتحييد حقن الصيغ، وأرقام
 * لاتينية خاماً.
 *
 * ── ⛔ المُنسِّقات القائمة في المستودع ممنوعة هنا، وهذه أسماؤها ────────────────
 *
 * **`components/booking/format.ts`** — `formatAmount` و`formatNumber`
 * و`formatMoney` و`toArabicDigits` و`toLocaleDigits` و`formatDateLabel`
 * و`formatDateTimeLabel` و`createFormatter`. تُخرج الخانات العربية الهندية
 * (‏U+0660–U+0669) وفاصل الآلاف U+066C وعلامة عشرية U+066B وسالباً U+2212،
 * والمبلغ موصولاً بـ«ج.م»، والتاريخ بصيغة «الأحد ١٤ سبتمبر ٢٠٢٦ — ٣:٣٠ م».
 *
 * **`lib/stats/format.ts`** — `formatStatValue` و`formatStatPercent`
 * و`formatDelta` و`cardsToBars`. مبنيّة فوق الأولى، وتضيف علامة النسبة العربية
 * U+066A و«—» لغير المعروف.
 *
 * وكلها **صحيحة على الشاشة وخاطئة في الملف**. السبب واحد: إكسل يستقبل
 * `١٬٢٣٤٫٥ ج.م` و`٢٠٢٦-٠٨-١٤` **نصّاً لا رقماً ولا تاريخاً** — لا تُجمع في
 * عمود، ولا تُرتَّب، ولا تدخل جدولاً محورياً، ولا يقارنها فلتر بحدّ. والملف
 * الذي لا يُجمع عموده لا سبب لوجوده أصلاً.
 *
 * فالبديل هنا: خانات لاتينية `0-9`، فاصلة عشرية `.`، سالب ASCII `-`، بلا فواصل
 * آلاف إطلاقاً (فاصلة الآلاف في CSV تعني فاصل خانات لمن يقرؤه بغير إكسل)،
 * والعملة **عمودٌ مستقل أو عنوان** لا لاحقةٌ داخل الرقم.
 *
 * ── حدود هذا الملف ───────────────────────────────────────────────────────────
 *
 * **لا يحسب شيئاً (D-05).** لا جمع ولا طرح ولا تقريب. و`csvMoney` تحديداً
 * **تُبقي كل خانة عشرية وصلت** ولا تقصّ واحدة: ما تفعله هو إلحاق أصفار عن
 * اليمين إن نقصت الخانات عن اثنتين — وهي زيادةٌ لا تغيّر القيمة ولا تفقد رقماً،
 * بعكس `toFixed(2)` التي **تُقرّب** وتصنع بذلك رقماً ثانياً يخالف الشاشة.
 *
 * **مسؤولية الهروب واحدة ولا تتكرر:** المُساعِدات أدناه تُرجع **نصّ الخانة
 * الخام**، و`csvLine` وحدها هي التي تقتبس وتضاعف وتُحيّد. لو هربت المُساعِدات
 * أيضاً لخرج الملف باقتباسات مضاعفة على خانة ومفردة على أخرى — وهو عيبٌ لا
 * يظهر إلا في الخانة التي فيها اقتباس، أي بعد الشحن بأسابيع.
 */

