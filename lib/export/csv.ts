/**
 * ⚠ **حرفيّة الرقم اللاتيني تُستورد من العقد ولا تُكتب هنا** —
 * `CSV_NUMERIC_LITERAL` في `lib/export-types.ts`.
 *
 * وكانت هنا نسخة محليّة مطابقة لها حرفاً بحرف، وحذفُها ليس تنظيفاً شكلياً: هذا
 * النمط **استثناءٌ من حارس حقن الصيغ** أُضيف بعد عيبٍ وقع فعلاً (كل مبلغ سالب
 * كان يصل إكسل نصّاً لا رقماً، القسم ٣ من العقد). واستثناءٌ أمني يعيش في موضعين
 * مستقلّين يعني أن تعديل العقد **لا يغيّر السلوك المشحون** — يبقى المستهلك على
 * نسخته القديمة بلا أن يفشل شيء ولا يُطبع تحذير. فالموضع واحد، والعقد هو هو.
 *
 * وهي تخدم غرضين هنا: تصديق ما ينتجه `String(number)` قبل كتابته، وتمرير ما وصل
 * **نصّاً من Postgres** كما هو. والثاني هو الأنقى في D-05: خاناتُ القاعدة نفسها
 * بلا مرور على `Number` — فلا تقريب ولا فقد دقة في أي حال.
 *
 * ⚠ ولا تُضاف إليها الراية `g` أبداً: `test()` على نمطٍ عامّ يحمل `lastIndex`
 * بين النداءات فيُخرج `false` في كل نداء ثانٍ — أي **مبلغٌ سالب يُحيَّد نصّاً
 * مرة ويمرّ رقماً مرة**، وهو أسوأ من الفشل المطّرد لأنه لا يُرى في اختبار.
 */

/**
 * هل تبدأ الخانة ببادئة تنفّذها إكسل صيغةً؟
 *
 * القائمة من العقد حرفياً (‏`CSV_FORMULA_PREFIXES`): `=` و`+` و`-` و`@` والجدولة
 * والإرجاع. والأخيران ليسا زينة: إكسل يتخطّاهما ثم يقرأ ما بعدهما، فخانة تبدأ
 * بجدولة ثم `=` تنفَّذ صيغةً وتنجو من فحصٍ يقرأ المحرف الأول وحده.
 *
 * ── ⚠ والاستثناء الوحيد ليس تخفيفاً للقاعدة بل شرطُ عملها ────────────────────
 *
 * **الرقم السالب لا يُسبَق بشيء.** البادئة `-` في القائمة، وتطبيقُها حرفياً على
 * كل خانة يجعل `'-360.50` نصّاً في إكسل — أي أن **عمود الرصيد كله يخرج نصّاً**،
 * لأن الرصيد سالبٌ عند كل متعهد عليه لنا (وهم خمسة من ستة في قاعدة بدر اليوم).
 * فيصير الملف لا يُجمع ولا يُرتَّب، وهو كل غرضه. وأمسك هذا الفحصُ العيبَ حياً
 * على صفوف مصنوعة قبل أن يُشحن سطرٌ واحد.
 *
 * ولماذا الاستثناء **آمن بنيوياً لا احتمالياً**: خطر البادئة `-` ليس في السالب
 * نفسه بل فيما بعده — `-2+3+cmd|'/c calc'!A0` صيغة، أمّا `-360.50` فرقمٌ يكتبه
 * أي إنسان في أي خلية. والشرط هنا **مطابقة الحرفيّة الرقمية كاملةً** لا فحص
 * محرفها الأول: فما إن يظهر محرف واحد خارج `-` و`0-9` و`.` تسقط المطابقة ويعود
 * التحييد. و`=1` و`+1` و`@x` و`-2+3` كلها تفشل المطابقة فتُحيَّد كما يوجب العقد.
 */
function startsFormula(raw: string): boolean {
  if (CSV_NUMERIC_LITERAL.test(raw)) return false;
  return CSV_FORMULA_PREFIXES.some((prefix) => raw.startsWith(prefix));
}

/**
 * خانة واحدة جاهزة للكتابة: تحييد ثم مضاعفة ثم اقتباس — **بهذا الترتيب**.
 *
 * الاقتباس **شامل لا شرطي**: القاعدة «اقتبس ما فيه فاصلة أو اقتباس أو سطر»
 * تنتج ملفاً مختلط الشكل، وأول قارئ يكسره هو من يفتحه بمحلّل بسيط. والاقتباس
 * الشامل يكلّف حرفين لكل خانة ويُنهي الصنف كله.
 *
 * وعلامة الاقتباس المفردة `'` تُكتب **داخل** الاقتباس: إكسل يفكّ الاقتباس أولاً
 * فتصل الخانة إلى محرك الصيغ مسبوقةً بها، وهي إشارته المتفق عليها لـ«هذا نص لا
 * صيغة». ولا تظهر في الخلية بعد الفتح.
 */
export function csvEscape(raw: string): string {
  const guarded = startsFormula(raw) ? `'${raw}` : raw;
  return `"${guarded.replace(/"/g, '""')}"`;
}

/**
 * سطر واحد بلا نهاية سطر — **نقطة الهروب الوحيدة في الملف كله**.
 *
 * كل خانة تمرّ من هنا مهما كان مصدرها، فلا توجد طريقة لكتابة خانة غير مهروبة
 * إلا بتجاوز هذه الدالة صراحةً.
 */
export function csvLine(cells: readonly string[]): string {
  return cells.map(csvEscape).join(",");
}

