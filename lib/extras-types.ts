/**
 * عقد الدفعة ٣ — جراحة التسعير الواحدة (هجرة `0031`).
 *
 * ثلاث ملاحظات من ملحق ٢ في `docs/VISION.md` تمسّ **الأعضاء الثلاثة نفسها**
 * (`quote_price` · `quote_public` · `create_booking`) ولقطة `bookings.trip`
 * المشتركة بينها — فتُنفَّذ مرة واحدة لا ثلاثاً:
 *
 *   (٧) تاريخ العودة يُعرض، وساعات الانتظار تُشتق منه تلقائياً حين تكون العودة
 *       في اليوم نفسه؛ ويُخفى حقل الانتظار من «خيارات إضافية» وتحلّ محله خدمات
 *       إضافية حقيقية تُدار من اللوحة بأسعارها ومواصفاتها.
 *   (٨) الحقائب: عدد لكل فئة سيارة، وافتراضياته من إعدادات الفئات.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ثلاثة قرارات حسمها بدر نصاً (2026-08-14) — وهي أساس كل ما بعدها
 * ══════════════════════════════════════════════════════════════════════════
 *
 * **(أ) الخدمة طبقةٌ مستقلة بعد الذروة، لا حدٌّ داخل المعادلة.**
 * كرسي الأطفال بـ٢٠٠ يبقى ٢٠٠ في يوم الذروة. والمكسب المعماري أكبر من الظاهر:
 * ما دامت الخدمات **خارج `pre_peak` كلياً**، فمعادلة الهامش في `quote_price`
 * (‏`pre_peak − waiting − applied_cost`) **لا يتغير فيها حرف**، وترتيب
 * الأرضية ← معامل العودة ← الانتظار ← الذروة يبقى كما حسمه D-11 وتختبره
 * `quote_tests.sql`. الجراحة تصير **إضافة** لا إعادة ترتيب.
 *
 * **(ب) الخدمات خارج أساس الهامش وخارج أساس الخصم.**
 * السابقة محفورة في الكود: ساعات الانتظار **تُطرح صراحةً** من الهامش
 * (‏`0011:228-230`) لأنها تموّل تكلفة تشغيلية لا ربحاً. والخدمة مثلها. وأثره:
 * الكوبون يخصم **سعر الرحلة وحده** ولا يمسّ كرسي الأطفال، وسقف موجة البث
 * (‏`dispatch_ceiling`) لا يتسع بقيمة الخدمات فلا يقبل متعهداً أغلى بمالٍ ليس
 * هامشاً أصلاً.
 *
 * **(ج) خدماتٌ ننفّذها نحن وحدنا في هذه الدفعة.**
 * لا يوجد في المستودع كله مكان يُدفع فيه للمتعهد مقابل إضافة: `price_list_items`
 * تحمل `(classSlug, cost)` ولا شيء غيرهما، و`assigned_payout` يُشتق من سقف
 * الموجة وقائمة أسعاره. فما ينفّذه المتعهد (مرشد سياحي · استقبال مطار) **مؤجَّل
 * بسبب مكتوب** (D-39) — بناؤه صحيحاً يمسّ قوائم الأسعار وسقف الموجة ودالة
 * القبول وعرض المقاصة، أي جراحة رابعة فوق ثلاث.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  المعادلة بعد الجراحة — والفرق عن اليوم سطران في آخرها
 * ══════════════════════════════════════════════════════════════════════════
 *
 *   subtotal   = base_fee + km × per_km            أو   partner_cost + margin
 *   subtotal   = max(subtotal, min_price)                  ← أرضية الفئة
 *   subtotal   = subtotal × round_trip_factor              ← إن ذهاب وعودة
 *   subtotal   = subtotal + waiting_hours × waiting_hour_price
 *   ride_total = round(subtotal × (1 + peak_percent/100))  ← الذروة آخر خطوة
 *   ─────────────────────────────────────────────────────────────────────────
 *   ride_total = ride_total − discount_amount              ← الخصم على الرحلة وحدها
 *   total      = ride_total + extras_total                 ← ★ الخدمات آخر شيء
 *
 * فالخصم يقع على **سعر الرحلة** كما يقع اليوم حرفياً، والخدمات تُجمع بعده.
 * ومن أراد يوماً أن يخصم الكوبون الخدمات أيضاً فليعلم أنه ينقض (ب) صراحةً.
 */

/**
 * خدمة إضافية في الكتالوج — صف في `extra_services` يديره المالك من
 * `/admin/extras`. لا شيء منها مبذور: أسعارُ كرسي الأطفال والواي فاي لا يعرفها
 * إلا هو (نفس سبب عدم بذر التعريفات في `0005`).
 */
export type ExtraServiceRow = {
  id: string;
  /** معرّف ثابت للاستعمال في الكود والترجمة — لا يتغير بتغير الاسم المعروض */
  slug: string;
  title: string;
  description: string | null;
  /** سعر الوحدة بالجنيه — يُضرب في الكمية، ولا يمسّه ذروة ولا خصم ولا أرضية */
  price: number;
  /**
   * أقصى كمية يختارها العميل من هذه الخدمة في الحجز الواحد.
   * كرسي أطفال ٣ · واي فاي ١. والحدّ مفروض في القاعدة لا في الواجهة.
   */
  maxQty: number;
  active: boolean;
  sort: number;
};

/**
 * خدمة مختارة في حجز بعينه — صف في `booking_extras`.
 *
 * 🔒 **اللقطة مجمَّدة كما في الكوبونات (‏0024).** `unitPrice` و`total` يُخزَّنان
 * لحظة الحجز، فتعديل سعر الخدمة في الكتالوج غداً **لا يعيد كتابة حجز الأمس**.
 * وهذا ليس تنسيقاً: بدونه ينهار كل كشف ربحية بأثر رجعي عند أول تعديل سعر
 * (نفس مبرر D-10 للقطة السعر).
 */
export type BookingExtraRow = {
  bookingId: string;
  extraId: string;
  /** نسخة الاسم لحظة الحجز — الكتالوج قد يُحذف منه الصف لاحقاً */
  titleSnapshot: string;
  qty: number;
  unitPrice: number;
  total: number;
};

/** ما يختاره المتصفح ويرسله — **الرمز والكمية فقط، ولا سعر أبداً** */
export type ExtraSelection = {
  slug: string;
  qty: number;
};

/**
 * مواصفة الحقائب على الفئة — عمود جديد على `vehicle_classes` (الملاحظة ٨).
 *
 * الأهلية تصير شرطين لا شرطاً واحداً:
 *     capacity ≥ passengers  **و**  luggage_capacity ≥ luggage
 * وموضعها **داخل `quote_price` حصراً** كما هي أهلية الركاب اليوم (D-12): قاعدة
 * أهلية في الواجهة تعني فئةً تُعرض ثم يرفضها الحجز.
 */
export type VehicleClassLuggage = {
  /** أقصى عدد حقائب تستوعبه الفئة — يضبطه المالك من `/admin/fleet` */
  luggageCapacity: number;
};

/**
 * اشتقاق ساعات الانتظار من تاريخ العودة (الملاحظة ٧).
 *
 * القاعدة: العودة في **اليوم نفسه** ⇒ الانتظار مشتق، وفي يوم آخر ⇒ الانتظار صفر
 * ومعامل الذهاب والعودة وحده هو ما يسعّر العودة (السائق ينصرف ويعود).
 *
 *     waiting_hours = ceil( (return_at − pickup_at) بالساعات )
 *
 * **والتقريب إلى الساعة الأعلى قرار معلن لا سهو:** سعر الساعة ثابت لكل فئة
 * (D-38) بلا تدرّج، والساعة المبدوءة ساعةٌ مدفوعة — وهو عرف هذا النشاط. تغييره
 * سطر واحد في `derive_waiting_hours`، ونقضه يجب أن يُكتب هنا.
 *
 * وسقفٌ صريح `MAX_DERIVED_WAITING_HOURS` يمنع أن يتحول خطأ في التاريخ إلى فاتورة
 * فلكية: ما تجاوزه ليس انتظاراً بل حجز يوم آخر.
 */
export const MAX_DERIVED_WAITING_HOURS = 12;

/**
 * تواقيع Postgres التي تضيفها أو تغيّرها هجرة 0031:
 *
 *   extra_services(...)                — كتالوج الخدمات، يديره المشرف
 *   booking_extras(...)                — لقطة ما اختاره الحجز، مجمَّدة
 *   vehicle_classes.luggage_capacity   — عمود جديد بقيمة افتراضية آمنة
 *
 *   public_extras()
 *     → table(slug text, title text, description text, price numeric, max_qty integer)
 *     كتالوج الخدمات المفعّلة للواجهة العامة. **بلا أي عمود داخلي** — نفس مبدأ
 *     `quote_public()`: ما لا يوجد في نوع الإرجاع لا يُسرَّب بخطأ في الواجهة.
 *
 *   price_extras(p_selection jsonb)
 *     → table(extra_id uuid, slug text, title text, qty integer,
 *             unit_price numeric, line_total numeric)
 *     تسعير اختيار الخدمات **في القاعدة لا في المتصفح**: تقرأ الأسعار من
 *     الكتالوج، وتقصّ الكمية على `max_qty`، وتتجاهل أي رمز غير مفعّل. المتصفح
 *     يرسل رموزاً وكميات فقط — ولا سعر، على نفس قاعدة D-09 حرفياً.
 *
 *   derive_waiting_hours(p_pickup_at timestamptz, p_return_at timestamptz)
 *     → numeric   — القاعدة أعلاه، وصفر حين لا عودة أو حين تكون في يوم آخر.
 *
 * والتواقيع الثلاثة المُعاد تعريفها (وكلها تُسقَط بصيغتها القديمة صراحةً، على
 * سابقة `0024:1197-1200`، وإلا صار كل نداء `function is not unique`):
 *
 *   quote_price(… , p_luggage integer default 0)
 *   quote_public(… , p_luggage integer default 0, p_extras jsonb default null)
 *   create_booking(… , p_return_at timestamptz default null,
 *                      p_luggage integer default 0, p_extras jsonb default null)
 *
 * ⚠ **والغلاف الرباعي `quote_price(numeric,integer,boolean,numeric)`** — الممنوح
 * لـ `anon` و`authenticated` منذ `0010` ولم يُسحب — هو مسار السقوط في
 * `/api/quote`. إبقاؤه بلا حقائب يعني **بوابة خلفية تُنتج سعراً أرخص**: فئةٌ لا
 * تتسع لحقائب العميل تُعرض عليه من هذا الطريق. يُعالَج في 0031 صراحةً.
 */
