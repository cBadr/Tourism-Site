/**
 * سائق في سجلّ متعهد. `photoPath` مسار في دلو خاص — **ولا يخرج خاماً أبداً**:
 * الواجهة تتلقّى رابطاً موقَّتاً موقَّعاً، لأن مسار الدلو بلا توقيع لا يُفتح
 * ووجودُه في حمولة عامة يغري بمحاولة الوصول (نفس قرار `receipt_path` في 0039).
 */
export type PartnerDriver = {
  id: string;
  subcontractorId: string;
  name: string;
  phone: string;
  /** مسار الصورة في التخزين — لا يصل العميل، ويُستبدل برابط موقَّع */
  photoPath: string | null;
  /** رقم الرخصة — للمتعهد والإدارة، **ولا يصل العميل إطلاقاً** */
  licenseNo: string | null;
  active: boolean;
};

/**
 * الحقول المضافة إلى `subcontractor_vehicles` — نصّ الملاحظة يطلب «شكلها
 * ولونها» صراحةً، والجدول يحمل اللوحة والسنة والمقاعد ولا يحمل هذين.
 */
export type VehicleAppearance = {
  /** لون المركبة كما يصفه المتعهد — نصّ حرّ لا قائمة: «فضي» و«رمادي فاتح» */
  color: string | null;
  /** صورة المركبة — نفس معاملة صورة السائق */
  photoPath: string | null;
};

