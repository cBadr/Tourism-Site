/**
 * ما يكتبه المتعهد بعد قبوله الرحلة: أي مركبة من مركباته، وأي سائق من سائقيه.
 *
 * ⚠ **والمُخزَّن معرِّفان لا لقطة** — بخلاف `booking_extras` التي تجمّد السعر.
 * والفرق مقصود: السعر **حقٌّ مالي** يجب ألا يتغيّر بعد الاتفاق، أما اسم السائق
 * ولوحة المركبة فـ**واقعٌ تشغيلي** يُقرأ لحظة قراءته: تصحيحُ لوحة كُتبت خطأً
 * يجب أن يصل العميل فوراً، لا أن يبقى الخطأ مجمَّداً على صفحته.
 */
export type TripCrew = {
  bookingId: string;
  vehicleId: string | null;
  driverId: string | null;
  assignedAt: string | null;
  /** أدخلته الإدارة نيابةً عن الشريك — يُوسم ولا يُخفى */
  byAdmin: boolean;
};

/**
 * ما **يراه العميل** — نوع الإرجاع الذي تضيفه `get_booking_by_token`.
 *
 * 🔒 الحقول الغائبة هنا غائبة **من نوع إرجاع الدالة نفسها**، لا مخفيّة في
 * الواجهة: رقم رخصة السائق، ومعرّفات المتعهد، وأي تكلفة أو هامش. وما لا وجود
 * له في النوع لا يصل الشاشة بخطأ برمجي (قاعدة المرحلة ٥).
 */
export type CustomerCrewView = {
  /** وصف المركبة كما يراه العميل: «سيدان — كورولا فضي» */
  vehicleLabel: string | null;
  vehicleColor: string | null;
  vehiclePlate: string | null;
  /** سنة الموديل — مفيدة للعميل ومقصودة، ثُبِّتت في العقد بعد المراجعة */
  vehicleYear: number | null;
  driverName: string | null;
  /**
   * 🔒 `null` خارج نافذة الظهور — **والقاعدة هي التي تقرّر**، لا الواجهة.
   * فالعميل الذي يستعجل لا يجده بنداء مباشر على PostgREST كذلك.
   *
   * ⚠ **والنافذة بطرفين** منذ 0043: تُفتح قبل الالتقاء بالمهلة و**تُغلق بعده
   * باثنتي عشرة ساعة**. كانت ذات طرف واحد، فبقي الرقم مكشوفاً بعد الرحلة
   * بشهر — والمبرر التجاري («كل رقم يُسلَّم مبكراً نافذة تخطٍّ») يسري بعد
   * الرحلة كما يسري قبلها.
   */
  driverPhone: string | null;
  /** متى يظهر الهاتف — يُعرض للعميل كي لا يظنّ غيابه عطلاً */
  phoneVisibleAt: string | null;
};

/**
 * ── 🔒 ما حُذف من حمولة العميل في 0043، ولا يُعاد ────────────────────────
 *
 * كانت 0040 تُخرج `byAdmin` و`assignedAt` إلى `anon`، وليسا في هذا النوع.
 * و`byAdmin` تحديداً **علمٌ تشغيلي يخبر العميل أن جهةً غير كاتب الصفحة أملت
 * البيانات** — أي إشارةٌ إلى وجود منفّذٍ ثالث، وهي بعينها ما لا يبلغ العميل في
 * منتج white-label. وكانت الصفحة «لا تعرضهما رغم وصولهما» — أي حجبٌ في العرض،
 * وهو ما ترفضه القاعدة التي بُني عليها هذا العقد: **ما لا يجب أن يصل، لا يخرج
 * من الدالة أصلاً**.
 *
 * ── وصورة المركبة والسائق ليستا هنا بقصد ────────────────────────────────
 *
 * `photo_path` عمودان قائمان، ولا رفع ولا عرض بعد (الترويسة تشرح: دلو `media`
 * عام، وصورة السائق بيانات طرفٍ ثالث). فلا حقل صورة في هذا النوع حتى تُشحن
 * هجرة الدلو الخاص — وإضافته حينها **توسعة لا تغيير**.
 */

