/**
 * عقد «المركبة والسائق بعد الإسناد» (الدفعة ٥ — الملاحظة ٥، الشقّ الأول)
 * — المرجع الأوحد.
 *
 * نصّ المالك في `docs/VISION.md` ملحق ٢ ملاحظة ٥:
 * «**العميل لا يعرف ما سيأتيه** — لا نوع السيارة ولا شكلها ولا رقمها ولا لونها،
 * ولا السائق (اسم · هاتف · صورة).»
 *
 * والخارطة قسمتها شقّين: **هذا الشقّ** يجيب السؤال بعد الإسناد (أي بعد أن يُعرف
 * المنفّذ فعلاً)، والشقّ الثاني — اختيار موديل بعينه **وقت البحث** — مؤجَّل
 * بسبب مكتوب في `docs/ROADMAP.md`.
 *
 * ── القيد الذي يحكم الشكل كله: بلا أصول ────────────────────────────────────
 *
 * «قسم السائقين **أُلغي بقرار بدر** (2026-08-11) — لا إدارة سائقين مباشرين
 * إطلاقاً» (‏`OVERVIEW.md`، العمود الأول من أعمدة المنتج الأربعة). فالمنصة لا
 * تملك سائقاً ولا تديره، ولا يجوز أن يصير هذا العمل باباً خلفياً لذلك.
 *
 * وحُسم مع المالك (2026-08-14): **السجلّ ملك المتعهد لا المنصة.**
 * `subcontractor_drivers` نظير `subcontractor_vehicles` حرفاً بحرف — يملؤه
 * المتعهد من بورتاله ويديره بنفسه، ولا شاشة إدارة سائقين في `/admin` إطلاقاً.
 * فالمنصة **تعرض** ما أعلنه الشريك ولا **تدير** من ينفّذ.
 *
 * ولماذا سجلّ لا حقول لكل رحلة؟ لأن متعهداً بعشر رحلات يومياً يعيد كتابة اسم
 * السائق وهاتفه خمسين مرة في الأسبوع — ومن يفعل ذلك أسبوعاً يتوقف عن فعله،
 * فيبقى العميل بلا معلومة والميزة مبنيّة ولا تُستعمل. النقرتان هما الفرق بين
 * ميزةٍ تعمل وميزةٍ تُتجاهَل.
 *
 * ── 🔒 القرار الثاني: هاتف السائق مؤقَّت، والتوقيت يُفرَض في القاعدة ────────
 *
 * حُسم مع المالك: الاسم والمركبة واللوحة تظهر **فور الإسناد** (وهي ما يطمئن
 * العميل)، أما **الهاتف** فيظهر قبل موعد الالتقاء بمدة تُضبط من اللوحة.
 *
 * والسبب تجاري لا تجميلي: عميلٌ يملك رقم السائق من اليوم الأول يستطيع الاتفاق
 * معه مباشرةً في المرة القادمة — أي أن كل رقم يُسلَّم مبكراً نافذة تخطٍّ
 * للمنصة نفسها. والمدة تضيّق النافذة ولا تلغيها: من يقف في المطار ولا يجد
 * سيارته يحتاج الرقم فوراً.
 *
 * 🔒 **والحجب يقع داخل `get_booking_by_token` نفسها لا في JSX.** الدالة ممنوحة
 * لـ`anon` وتُنادى مباشرةً من PostgREST، فحاجبٌ في الواجهة يُتخطّى بنداء واحد.
 * وهذا نفس ما فُعل بإيصالات الأدمن في الدفعة ٢: «الحجب داخل الدالة لا في
 * العرض» — والحقل المحجوب **يخرج من نوع الإرجاع أصلاً** فلا مسار له إلى
 * الشاشة (نفس مبدأ `quote_public` و`portal_offers`).
 *
 * ── 🔒 القرار الثالث: من يكتب طاقم الرحلة؟ ────────────────────────────────
 *
 * **المتعهد المُسنَد إليه وحده**، عبر دالة `security definer` تشتق هويته من
 * `current_subcontractor_id()` ولا تقبلها وسيطاً — نفس نمط `accept_offer`.
 * فمتعهدٌ آخر لا يكتب طاقم رحلةٍ ليست له، ولا ينتحل أحدٌ هوية أحد.
 *
 * وللإدارة تجاوزٌ صريح (‏`ops` يتصل بالشريك هاتفياً ويسجّل عنه) — على سابقة
 * `admin_attach_receipt`: مسارٌ منفصل محروس بـ`is_admin()` يترك أثره في السجل
 * بوسم أنه إدخال إداري، لا التفافٌ صامت على الحارس.
 */

