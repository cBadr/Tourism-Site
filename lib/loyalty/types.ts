/**
 * عقد الواجهة العامة للاستبدال — ما يغادر الخادم إلى المتصفح، لا أكثر.
 *
 * العقد الأم `lib/loyalty-types.ts` يصف الحقيقة الداخلية والقرارات (‏§١–§٦
 * محسومة ولا تُشتقّ من جديد)، وهذا الملف نظيرُ `lib/discounts/types.ts` حرفاً
 * بحرف: **النسخة المنقّحة** التي يراها العميل في مسار الحجز. الكائن يُبنى حقلاً
 * حقلاً، فما لا يوجد في هذا النوع لا يتسرّب ولو أضافت دالة SQL عموداً غداً.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔒 (١) ما لا يوجد في هذا الملف، بقصد
 * ══════════════════════════════════════════════════════════════════════════
 *
 * - **لا `phoneNorm` ولا هاتف بأي صورة.** الرصيد يُجمَّع عليه في القاعدة
 *   (‏§٣ في العقد الأم)، والعميل لا يحتاج رؤية شكل تطبيعنا لرقمه. وهي القاعدة
 *   نفسها التي حذفت الحقل من `MyLoyaltyView`.
 * - **لا رايةَ «قلّصته الأرضية»**. `apply_discount` تحمل `clamped` ولا تُخرجها
 *   إلى المتصفح للسبب المكتوب في `lib/discounts/types.ts`: من يجرّب رحلات
 *   ويراقب الراية يرسم خريطة هوامشنا من الخارج. والاستبدال **أخطر**، لأن
 *   السقف الحقيقي عليه هو أرضية §١ نفسها: فسبب «لا مساحة» يُطوى في
 *   `not-applicable` بلا رقم ولا تفسير.
 * - **لا تكلفة متعهد ولا هامش ولا أي أثر لهما** — لا يوجد لهما حقل أصلاً.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  🔒 (٢) القاعدة تقرّر المبلغ، والمتصفح يقول «نعم» فقط
 * ══════════════════════════════════════════════════════════════════════════
 *
 * **D-05** و«لا سعر من العميل» يجتمعان هنا في قاعدةٍ واحدة: لا يوجد في
 * `RedeemRequest` حقلُ نقاطٍ ولا حقلُ مبلغ. المتصفح يرسل مدخلات الرحلة ورمز
 * الكوبون القائم، والقاعدة تُرجع **كم ستُنفَق وكم ستوفّر**. وعند التأكيد يُرسَل
 * إلى `/api/booking` **رايةٌ منطقية واحدة** (`redeemPoints: true`) — لا رقم.
 *
 * ⚠ وحتى الهوية لا تُرسَل: صاحبُ الرصيد يُشتقّ من **جلسة الطلب** على الخادم
 * (‏`auth.getUser()`)، لا من معرّفٍ في الجسم. ولو قُبل معرّف من المتصفح لصار
 * إنفاقُ رصيد أي حسابٍ نداءً واحداً.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ⚠ (٣) لماذا لا يختار العميل «كم نقطة أُنفق» — تأجيلٌ بسببٍ مكتوب (D-39)
 * ══════════════════════════════════════════════════════════════════════════
 *
 * الاستبدال في هذه الدفعة **مفتاحٌ لا حقل رقم**: إمّا أن يُنفق أقصى ما تسمح به
 * القاعدة أو لا يُنفق شيء. والسبب أن الرقم الجزئي يُدخل مدخلاً جديداً من
 * المتصفح إلى مسار المال، فيحتاج حارساً في القاعدة لكل ما يُشتقّ منه؛ ولا يشتري
 * ذلك للعميل شيئاً اليوم — النقاط لا تنتهي صلاحيتها (‏§٦)، فالاحتفاظ بها لرحلةٍ
 * تالية ليس أفضل من إنفاقها الآن بأي حساب. ويوم يوجد الانتهاء يصير للاختيار
 * معنى، فيُضاف حينها بحارسه.
 */

/**
 * سبب تعذّر الاستبدال كما يراه العميل — اتحاد مُصغَّر عمداً، نظير
 * `PublicRejection` في طبقة الخصم.
 *
 * ⚠ **`not-applicable` هي الحالة الجامعة للأرضية**: «لا مساحة بعد الكوبون»
 * و«الأرضية لا تحتمل» و«ناتج الحساب صفر» كلها رسالة واحدة بلا رقم. التفريق
 * بينها يخبر العميل — ومن يراقب — أين يقف حاجز الهامش بالضبط.
 */
export type RedeemUnavailable =
  /** لا جلسة عميل: الرصيد يُقرأ عبر `auth.uid()` وحده (‏§٣) */
  | "signed-out"
  /** لا رصيد مُثبَت، أو الرصيد صفر — والحالتان تُفرّقان في `/account` لا هنا */
  | "no-balance"
  /** الرصيد دون `minRedeemPoints` — قاعدةٌ معلَنة لا تكشف شيئاً عن الهامش */
  | "below-minimum"
  /** الأرضية أو السقف لم يتركا مساحة — بلا سبب وبلا رقم (انظر أعلاه) */
  | "not-applicable"
  /** نظام الولاء مطفأ أو غير مجهَّز على هذا الخادم */
  | "unavailable"
  /** تجاوز حدّ المحاولات على مسار المعاينة */
  | "rate-limited";

/**
 * جسم طلب `POST /api/loyalty/preview`.
 *
 * **لا سعر ولا مسافة من العميل** — نفس المبدأ الحاكم في `/api/booking` و
 * `/api/discount/verify`: المسافة تُعاد حسابها على الخادم، والسعر يخرج من دوال
 * القاعدة. ولو قبِل هذا المسار `total` لصار مسبار هوامش كما كُتب هناك حرفياً.
 */
export type RedeemRequest = {
  origin: { lat: number; lng: number };
  destination: { lat: number; lng: number };
  passengers: number;
  roundTrip: boolean;
  waitingHours: number;
  /**
   * عدد الحقائب كما سُعِّرت به الرحلة — **مُدخل أهلية لا معلومة عرض**، للسبب
   * المكتوب في `coupon-field.tsx`: الحقائب تُزيح زوج الفئات المعروض، فنداءٌ
   * بلا حقائب لا يجد فئة العميل أصلاً فيردّ «الفئة غير متاحة» بلا سبب مفهوم.
   */
  luggage: number;
  classSlug: string;
  /**
   * 🔒 **رمز الكوبون المطبَّق الآن — وهو أهمّ حقل في هذا الطلب.**
   *
   * §١ في العقد الأم: **سقفٌ واحد للطبقتين مجتمعتين، لا سقفان يُجمعان**.
   * فمعاينةٌ تُحسب بلا علمٍ بالكوبون تَعِد العميل بنقاطٍ أكلها الكوبون سلفاً،
   * ثم تُخيّبه لحظة التأكيد — أو أسوأ: تمرّ فتنزل بالإجمالي تحت الأرضية.
   * `null` حين لا كوبون مطبَّق.
   */
  couponCode: string | null;
};

/**
 * الاستبدال متاح — كل رقم هنا من القاعدة، ولا عملية حسابية واحدة في المتصفح.
 *
 * ولذلك يُرجَع `rideAfter` مبنيّاً من القاعدة بدل أن تطرح الواجهة `worth` من
 * `rideBefore`: طرحٌ في TypeScript يعني رقماً ثانياً لسعر الرحلة لا يطابق ما
 * تُثبّته `create_booking` (اتفاقية ٢ في `CONVENTIONS.md`).
 */
export type RedeemOffered = {
  ok: true;
  available: true;
  /** ما سيُنفَق فعلاً من رصيده — بعد كل حدود القاعدة */
  points: number;
  /** ما يوفّره ذلك بالجنيه */
  worth: number;
  /** رصيده كله — يُعرض ليعرف كم يبقى، ولا يُطرح منه شيء هنا */
  balance: number;
  /** سعر الرحلة قبل النقاط — أي **بعد** الكوبون إن وُجد (‏§٢) */
  rideBefore: number;
  /** سعر الرحلة بعدها */
  rideAfter: number;
  currency: string;
};

/** الاستبدال غير متاح — سبب مُجمَّع ونص عربي جاهز */
export type RedeemDeclined = {
  ok: true;
  available: false;
  reason: RedeemUnavailable;
  message: string;
};

/** خطأ طلب أو بيئة — نفس شكل `CouponRequestError` و`BookingError` */
export type RedeemRequestError = {
  ok: false;
  /** invalid-input | rate-limited | db-unavailable | pricing-failed */
  code: string;
  message: string;
};

export type RedeemResponse = RedeemOffered | RedeemDeclined | RedeemRequestError;

/**
 * الاستبدال المعروض كما تحمله واجهة الحجز بين مكوّناتها.
 *
 * ⚠ **معاينة لا التزام** — بنفس نصّ `AppliedDiscount` حرفياً وللسبب نفسه:
 * الأرقام هنا ناتجُ حسابٍ على سعرٍ حُسب لحظة المعاينة، والرقم المُلزِم ما
 * تُثبّته `create_booking` داخل معاملتها (‏**D-48**). ولذلك لا يُرسَل من
 * المتصفح عند التأكيد إلا رايةُ «استبدل» — ولا نقطة ولا جنيه.
 *
 * وإن تعذّر الاستبدال لحظة التأكيد (أنفق العميل رصيده في تبويب آخر، أو ضاقت
 * المساحة) **فالحجز يفشل ولا يُنشأ بالسعر الأعلى بصمت**: هو اختار سعراً
 * مخفَّضاً، وإنشاء حجزٍ بغيره بلا علمه أسوأ من رسالة خطأ. نفس قرار
 * `coupon-rejected` في `0024` بعينه.
 */
export type AppliedRedemption = {
  points: number;
  worth: number;
  rideBefore: number;
  rideAfter: number;
  currency: string;
};

/**
 * ══════════════════════════════════════════════════════════════════════════
 *  تواقيع Postgres — ما هو **مطبَّق فعلاً** (‏0047)، وما يُنقصه هذا السطح
 * ══════════════════════════════════════════════════════════════════════════
 *
 * قِيست القاعدة الحيّة بعد تطبيق `0047_loyalty.sql` (‏`schema_migrations`
 * تحملها). وهذه القائمة **مقروءةٌ من الكتالوج لا منقولةٌ من ملف الهجرة**
 * (‏**D-58**)، وهي المرجع الأوحد لهذه الأسماء في طبقة TypeScript.
 *
 * ── ✅ ما يستعمله هذا السطح ويعمل اليوم ────────────────────────────────────
 *
 *   my_loyalty()
 *       returns table (points integer, worth numeric, currency text,
 *                      proven_phones integer)
 *       — `security definer`، تشتقّ الهوية من `auth.uid()` **داخلها** كما
 *         `my_bookings()`، ممنوحة لـ authenticated. وتجمّع على الهواتف
 *         **المُثبَتة** وحدها (‏`link_source = 'reference'`) — أي §٣ منفَّذاً.
 *         🔒 ولا `phone_norm` في نوع إرجاعها (‏`LOYALTY_FORBIDDEN_COLUMNS`).
 *         يقرؤها `app/account/bookings/loyalty.ts` وحده.
 *
 *   loyalty_config()
 *       returns table (enabled boolean, points_per_currency numeric,
 *                      currency_per_point numeric, min_redeem_points integer,
 *                      max_redeem_percent numeric)
 *       — 🔒 `service_role` وحده. يقرؤها `lib/loyalty/settings.ts` ولا يُخرج
 *         منها إلا `enabled`.
 *
 * ── ⛔ الناقص: **دالةُ معاينةٍ واحدة**، وبها وحدها يعمل شقّ الحجز ───────────
 *
 *   preview_redeem_points(p_profile uuid, p_distance_km numeric,
 *                         p_passengers integer, p_round_trip boolean,
 *                         p_waiting_hours numeric, p_origin_lat numeric,
 *                         p_origin_lng numeric, p_dest_lat numeric,
 *                         p_dest_lng numeric, p_class_slug text,
 *                         p_coupon_code text, p_luggage integer)
 *       returns table (points numeric, worth numeric, balance numeric,
 *                      ride_before numeric, ride_after numeric,
 *                      currency text, reason text)
 *
 *   **ولماذا لا يمكن بناؤها في TypeScript**: `apply_points` تحتاج
 *   `p_partner_cost` وسيطاً، فمناداتها من مسارٍ في `app/api` تعني أن ذلك المسار
 *   **يقرأ تكلفة المتعهد ويحملها في متغيّر** — وهو بعينه ما رفضته الحراسة (٣)
 *   في `/api/discount/verify`، ولذلك تنادي تلك الشاشةُ `quote_public` لا
 *   `apply_discount`. و`quote_public` **لا تحمل عمود تكلفة أصلاً** (0012 ثم
 *   0024)، فلا سبيل من هنا إلى الأرضية. فالمعاينة تلزمها دالةٌ تسعّر وتقرأ
 *   التكلفة وتنادي `apply_points` **داخلها**، وتُرجع الأرقام المعروضة وحدها.
 *
 *   وحتى تصل: `/api/loyalty/preview` يردّ `available: false` بسببٍ
 *   `unavailable`، ولوحةُ الاستبدال **لا تظهر إطلاقاً** — تدهورٌ صادق لا عطل.
 *
 * ── 🔴 وقبلها: الاستبدال في `create_booking` بلا إثبات ملكيةٍ للهاتف ────────
 *
 *   المطبَّق اليوم:  create_booking(..., p_redeem_points integer default 0)
 *   وداخلها:        apply_points(v_phone, …) حيث `v_phone = p_customer_phone`
 *
 *   أي أن النقاط تُنفَق من رصيد **الرقم المكتوب في نموذج الحجز**، ولا
 *   `auth.uid()` في هذا المسار ولا قراءةَ `customer_bookings` — قِيس بقراءة
 *   الجسم الحيّ. فمن يعرف رقم عميلٍ آخر يكتبه في حجزه فينفق رصيد صاحبه.
 *
 *   وهو **§٢ و§٣ يُفتحان من بابٍ ثالث**: `my_loyalty` تحرس القراءة بالهاتف
 *   المُثبَت حرصاً شديداً، والكتابةُ بجوارها بلا حارس. والفارق أن القراءة
 *   تكشف رصيداً والكتابة **تُنفقه**.
 *
 *   🔒 ولذلك **لا يمرّر `/api/booking` هذا المعامل إطلاقاً** في هذه الدفعة:
 *   الحارس لا يمكن أن يعيش في TypeScript — لا دالةَ تُجيب «هل هذا الرقم من
 *   هواتف جلستي المُثبَتة؟»، و`my_loyalty` لا تُرجع هاتفاً بقرارٍ صحيح. فالمطلوب
 *   من هجرة التصليب أن تأخذ `p_redeem_profile uuid` وتشترط داخلها صفَّ
 *   `customer_bookings` بـ`link_source='reference'` يربط ذلك الحساب بهاتف
 *   الحجز — عندها يصير الحارس بنيوياً كبقية المشروع، ويُوصَل هذا السطح بسطر.
 *
 *   وتلميح الرفض المطبَّق `points-rejected` (لا `redeem-rejected`)، ويُترجَم في
 *   `/api/booking` إلى الرمز `redeem-rejected` الذي تقرؤه `Checkout`.
 *
 *   redeem_points(p_booking uuid, p_phone text, p_points integer,
 *                 p_amount numeric) returns uuid
 *       — الكتابة والقفل (‏`for update`) داخل معاملة `create_booking` وحدها،
 *         نظير `redeem_coupon`. **ولا تُنادى من TypeScript في أي مسار.**
 */
