/**
 * 🔴 صندوق مصر بهامشٍ سخي — **مصدرٌ واحد يقرؤه الخادم والخريطة معاً**.
 *
 * وهو هنا لا في المسار لأن **الطرفين يحتاجانه**: المسار يرفض ما خرج عنه،
 * والخريطة تمنع العميل من الخروج أصلاً. ونسختان منه تنحرفان، فتصير الخريطة
 * تسمح بما يرفضه المسار — وهي بعينها الحالة التي وُلد هذا الثابت لمنعها.
 *
 * ⚠ **وما يمنعه ليس تجميلاً:** الدبوس بلا حدّ يعني أن يضع الزائر نقطته في روما
 * ثم يضغط «احسب السعر»، فيُنفق محرّك المسافات نداءً مدفوعاً على مسار
 * القاهرة–روما، **ويُخزّنه في `distance_cache` دائماً**، ويخرج الزائر بسعرٍ
 * حقيقيٍّ قابلٍ للحجز لرحلةٍ لا يمكن أن ننفّذها.
 *
 * والهامش سخيٌّ بقصد: حدود مصر الفعلية ≈ ٢١٫٥–٣٢ عرضاً و٢٤٫٥–٣٧ طولاً،
 * والصندوق أوسع منها فلا يُرفض ساحلٌ أو واحةٌ على الحافة.
 */
export const SERVICE_BOUNDS = {
  minLat: 20,
  maxLat: 34,
  minLng: 23,
  maxLng: 38,
} as const;

/**
 * وسمُ الطوارئ حين يتعذّر تسمية نقطة — إحداثياتٌ مقرَّبة.
 *
 * ⚠ **بفاصلة لاتينية لا عربية**: الوسم يُعرض على `/en` كما يُعرض على العربية،
 * و«،» وسط أرقامٍ لاتينية على صفحة إنجليزية محرفٌ غريب لا فاصل. وهو موضعٌ
 * واحد لأنه كان مكرَّراً في ثلاثة (‏`geocode.ts` ومرّتين في `place-field.tsx`)
 * — وثلاث نسخٍ من نصٍّ واحد تنحرف بأول تعديل.
 */
export function formatCoordsLabel(lat: number, lng: number): string {
  return `${lat.toFixed(5)}, ${lng.toFixed(5)}`;
}

/**
 * هل النقطة داخل منطقة الخدمة؟ — **الفحص الوحيد**، يناديه الخادم والخريطة
 * ومولّد صورة الخريطة ورابط الاتجاهات معاً.
 *
 * ⚠ ومن يحتاج «هل هذه النقطة داخل مصر؟» في عملٍ جديد ينادي هذه — **ولا يكتب
 * صندوقاً ثانياً**. تعريفان لمنطقة الخدمة يختلفان يوماً، والخلاف يكون حجزاً
 * سُعِّر لمسارٍ لا نخدمه.
 */
export function isWithinServiceArea(lat: number, lng: number): boolean {
  return (
    Number.isFinite(lat) &&
    Number.isFinite(lng) &&
    lat >= SERVICE_BOUNDS.minLat &&
    lat <= SERVICE_BOUNDS.maxLat &&
    lng >= SERVICE_BOUNDS.minLng &&
    lng <= SERVICE_BOUNDS.maxLng
  );
}

