/**
 * الإعدادات كما تراها الواجهة. مصدرها الوحيد جدول `place_search_settings`
 * (هجرة 0076)، وحدودها مفروضة **في القاعدة** لا في النموذج وحده.
 *
 * ⚠ **ولا مفتاح جوجل هنا ولا في الجدول ولا في أي حقل لوحة.** المفتاح
 * `GOOGLE_MAPS_API_KEY` في البيئة وحدها (اتفاقية §٣: «الأسرار في البيئة،
 * الوجهات في اللوحة»). ما تملكه اللوحة هو **هل يُستعمل**، لا **ما هو**.
 */
export type PlaceSearchSettings = {
  /** مفتاح القطع: إطفاؤه يُعيد سلوك اليوم بلا نشر */
  googleEnabled: boolean;
  /** من يُسأل أولاً — والثاني ارتدادٌ له */
  primaryProvider: PlaceProvider;
  mapPickerEnabled: boolean;
  quoteFallbackEnabled: boolean;
  /** أقل عدد حروف قبل أول نداء — ضابط تكلفة */
  minQueryChars: number;
  /** تأجيل النداء بعد آخر ضغطة مفتاح — ضابط تكلفة */
  debounceMs: number;
  /**
   * 🔴 **مرساةُ الخريطة** — أين تفتح نافذة اختيار المكان حين لا وجهة بعد.
   * مطار القاهرة افتراضاً بقرار المالك (2026-08-17): «النقطة الرئيسية عند طلب
   * تسعير بلا وجهة معيّنة هي مطار القاهرة» — وهو حيث يبدأ أكثر عمله.
   *
   * ⚠ **ومركزُ فتحٍ ليس قيمةً افتراضية.** الخريطة تفتح هناك، والحجزُ **لا**
   * يحمل مطار القاهرة مبدأً: `MapPicker` لا يستدعي `onPick` إلا من زرّ
   * «تأكيد هذا الموقع». والخلط بينهما — دبوسٌ يبدو موضوعاً وليس مختاراً —
   * أسوأ من خريطةٍ فارغة، ولذلك لا يُكتب في الحقل حرفٌ قبل التأكيد.
   *
   * وهي إعدادٌ لا ثابتٌ في مكوّن (‏0080): نسخةُ Whitelabel في مدينةٍ أخرى
   * تُطلق بتعديل بياناتٍ لا بتفريع كود (D-01)، ومركزٌ محفورٌ في
   * `map-picker.tsx` كان يمنع ذلك وحده.
   */
  defaultCenter: { lat: number; lng: number };
};

/**
 * 🔒 **الافتراضيات تُعيد سلوك اليوم حرفياً**: جوجل مطفأ، والأساسي Nominatim،
 * والحرفان والـ٣٥٠ مللي هما `MIN_QUERY_LENGTH` و`DEBOUNCE_MS` اللذان كانا
 * محفورَين في `search-widget.tsx`. فالهجرة وحدها لا تغيّر نداءً واحداً.
 *
 * ⚠ ومخرجا الطبقتين الثالثة والرابعة **مفعّلان بالافتراض** — وهما مجانيان
 * ولا يمسّان سعراً ولا مزوّداً مدفوعاً؛ إطفاؤهما يعني إبقاء العميل الذي لم
 * يجد مكانه بلا مخرج، وهو العطل الذي وُلد هذا العمل لعلاجه.
 */
export const PLACE_SEARCH_DEFAULTS: PlaceSearchSettings = {
  googleEnabled: false,
  primaryProvider: "nominatim",
  mapPickerEnabled: true,
  quoteFallbackEnabled: true,
  minQueryChars: 2,
  debounceMs: 350,
  // مطابق لافتراضَي العمودين في 0080 — صالات مطار القاهرة الدولي
  defaultCenter: { lat: 30.1219, lng: 31.4056 },
};

/**
 * حدود الحقلين الرقميين — **نسخةٌ من قيود القاعدة لا مصدرٌ لها**.
 * القاعدة هي الحارس (‏`check` في 0076)؛ وهذه تُبقي النموذج من إرسال ما تعرف
 * أنه سيُرفض، وتغذّي `min`/`max` في الإدخال.
 */
export const PLACE_SEARCH_BOUNDS = {
  minQueryChars: { min: 2, max: 6 },
  debounceMs: { min: 150, max: 2000 },
} as const;

