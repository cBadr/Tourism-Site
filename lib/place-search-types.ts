import type { GeoPlace } from "@/lib/pricing-types";

/**
 * عقد بحث الأماكن — أربع طبقات، على شكل محرّك المسافات نفسه (D-13).
 *
 *   Google Places  →  Nominatim  →  «حدّد على الخريطة»  →  «اطلب عرض سعر»
 *
 * 🔒 **الإحداثيات مصدر الحقيقة في كل طبقة.** لا يُسعَّر نصٌّ لم يُحلّ إلى نقطة:
 * سعرٌ محسوبٌ من نصٍّ غير محلول سعرٌ نلتزم به ولا نعرف مسافته (D-09).
 *
 * ⚠ هذا الملف **بلا `server-only`** بقصد: العميل يقرأ منه الأنواع والحدود
 * ويولّد رمز الجلسة. ولا يحمل مفتاحاً ولا نداءً خارجياً — المفتاح في البيئة
 * وحدها، والنداء في `lib/geo/*` خلف `server-only`.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  لماذا خطوتان (اقتراح ← تحويل) بدل نداءٍ واحد يرجع إحداثيات
 * ══════════════════════════════════════════════════════════════════════════
 *
 * لأن **هذا هو نموذج فوترة جوجل**. `places:autocomplete` لا يُرجع إحداثيات
 * أصلاً — يُرجع `placeId` ونصّاً — والإحداثيات تأتي من `places/{id}` وحدها.
 * فمن يريد إحداثيات كل اقتراح يدفع تفاصيلَ لكل سطرٍ يراه العميل ولا يختاره.
 * والخطوتان تعنيان أن **العميل يُحلّ مكاناً واحداً: الذي اختاره بالفعل**.
 *
 * و Nominatim يُرجع الإحداثيات مع الاقتراح مجاناً، فاقتراحه يحمل `place`
 * جاهزاً و«التحويل» عنده لا يلمس الشبكة إطلاقاً.
 */

/** مزوّد بحثٍ حقيقي — الطبقتان الأوليان وحدهما (الخريطة وعرض السعر مخرجان لا مزوّدان) */
export type PlaceProvider = "google" | "nominatim";

/**
 * اقتراح واحد في قائمة الإكمال التلقائي.
 *
 * `place` حاضرٌ ⇒ الاختيار فوري بلا نداء. غائبٌ ⇒ يلزم `POST /api/geocode/resolve`
 * بـ`ref` و`sessionToken` — وهو ما يُنهي جلسة جوجل ويجعلها **فوترةً واحدة**.
 */
export type PlaceSuggestion = {
  /** مفتاح العنصر في القائمة — `placeId` عند جوجل، `osm_type/osm_id` عند Nominatim */
  ref: string;
  provider: PlaceProvider;
  /** السطر الأول: اسم المكان كما يعرفه العميل */
  label: string;
  /** السطر الثاني: العنوان الإداري — قد يغيب */
  secondary?: string;
  /** إحداثيات جاهزة (Nominatim وحده) */
  place?: GeoPlace;
};

/**
 * ردّ `/api/geocode/suggest`.
 *
 * `provider` هو من ردّ فعلاً — **والواجهة تعرض إسناد جوجل حين وحين فقط يكون
 * `"google"`** (شرط جوجل: الإسناد حيث تُعرض نتائجه، لا حيث يُحتمل عرضها).
 *
 * `exhausted` تعني «المزوّدون ردّوا ولم يجدوا» — عندها تُعرض مخارج الطبقتين
 * الثالثة والرابعة. وهي **ليست خطأً**: صفر نتيجة جوابٌ صحيح.
 */
export type SuggestResponse =
  | {
      ok: true;
      provider: PlaceProvider | null;
      suggestions: PlaceSuggestion[];
      /** لم يبقَ مزوّدٌ يُسأل — أظهر «حدّد على الخريطة» و«اطلب عرض سعر» */
      exhausted: boolean;
    }
  | { ok: false; code: PlaceSearchErrorCode };

/** ردّ `/api/geocode/resolve` و`/api/geocode/reverse` — مكانٌ بإحداثيات أو رمز خطأ */
export type ResolveResponse =
  | { ok: true; place: GeoPlace; provider: PlaceProvider }
  | { ok: false; code: PlaceSearchErrorCode };

/**
 * رموز السلك — **رمزٌ لا جملة** (اتفاقية §٤): الواجهة تترجمه بلغة الزائر،
 * فلا تُطبع عربية الخادم على `/en`.
 */
export type PlaceSearchErrorCode =
  /** النص أقصر من الحد الأدنى المضبوط من اللوحة */
  | "too-short"
  /** جسم الطلب ليس بالشكل المتوقع */
  | "invalid-input"
  /** المزوّد لم يعرف هذا المرجع (منتهٍ أو مختلَق) */
  | "not-found"
  /** نقطةٌ خارج منطقة الخدمة — **تُرفض ولا تُسعَّر** (انظر `SERVICE_BOUNDS`) */
  | "out-of-area"
  /** كل المزوّدين سقطوا — لا نتيجة ولا حتى صفر نتيجة موثوقة */
  | "unavailable";

