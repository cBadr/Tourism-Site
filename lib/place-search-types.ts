/* 🔴 رمز الجلسة — أهم تفصيلة في هذا العمل كلّه                         */
/* ------------------------------------------------------------------ */

/**
 * 🔴 **رمز الجلسة هو الفرق بين فاتورةٍ واحدة وسبع فواتير.**
 *
 * جوجل يفوتر الإكمال التلقائي **بالجلسة** حين يصل `sessionToken` صحيحاً،
 * و**بالطلب** حين يغيب. من يكتب «القاهرة» يُطلق سبعة نداءات: بلا رمزٍ هي سبع
 * وحدات فوترة، وبرمزٍ واحدٍ يمتد من أول حرفٍ حتى الاختيار هي **وحدة واحدة**.
 *
 * ودورة الحياة التي تجعلها واحدة:
 *   ١) يولّد العميل رمزاً عند بدء الكتابة في الحقل.
 *   ٢) يُرسَل مع **كل** نداء اقتراح — النص يتغيّر والرمز لا.
 *   ٣) يُرسَل مع نداء التحويل (`resolve`) — وهو ما **يُنهي** الجلسة عند جوجل.
 *   ٤) يُتلَف فوراً، ويولَّد غيره للبحث التالي.
 *
 * ⚠ **ولا تُبسَّط هذه الدورة.** إعادةُ استعمال رمزٍ منتهٍ، أو توليدُ رمزٍ لكل
 * ضغطة مفتاح، أو حذفُه «لأنه يبدو زائداً» — ثلاثتها تعمل بلا خطأٍ ظاهر وتضرب
 * الفاتورة في عدد حروف ما يكتبه العميل.
 *
 * 🔴 **والشكل ليس تفصيلاً تجميلياً — مقيسٌ على واجهة جوجل الحيّة:**
 * رمزٌ خارج base64 الآمن للروابط (مثل `probe-0.55`) يردّ
 * **`HTTP 400: session_token: must be a URL and filename safe base64 string`**
 * — أي **كل** نداءات جوجل تفشل، والمحرّك ينزل إلى Nominatim إلى الأبد بلا أن
 * يشتكي أحد. لذلك يُفحص الرمز قبل إرساله، ويُسقَط عند الشك: **فوترةٌ أغلى
 * أهون من ميزةٍ ميتة صامتة**.
 */
const SESSION_TOKEN_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

/**
 * رمز جلسة جديد — UUID v4 وهو ضمن base64 الآمن للروابط.
 *
 * ⚠ و`crypto.randomUUID` **غير موجودة في سياقٍ غير آمن** (‏http على مضيفٍ غير
 * localhost). فبلا الارتداد أدناه كان الحقل ينهار بـ`TypeError` على أول ضغطة
 * مفتاح في معاينةٍ على http — أي **حقل البحث كله معطّل**، لا الفوترة وحدها.
 * والارتداد يبني الرمز من `getRandomValues` بأحرف base64 الآمنة نفسها.
 */
export function newSessionToken(): string {
  const api = globalThis.crypto;
  if (typeof api?.randomUUID === "function") return api.randomUUID();

  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
  const bytes = new Uint8Array(32);
  api.getRandomValues(bytes);
  let token = "";
  for (const byte of bytes) token += alphabet[byte % alphabet.length];
  return token;
}

/** هل الرمز صالحٌ لأن يُرسل إلى جوجل؟ (انظر التعليق أعلاه — الفاسد يردّ ٤٠٠) */
export function isSessionToken(value: unknown): value is string {
  return typeof value === "string" && SESSION_TOKEN_PATTERN.test(value);
}
