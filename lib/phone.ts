/**
 * أرقام الهاتف على الحدود الخارجة — وحدةٌ **ورقية بلا استيراد واحد**.
 *
 * ⚠ وخلوّها من الاستيراد شرطُ وجودها لا صدفة: `lib/maintenance.ts` يناديها،
 * وهو يُستورَد من `proxy.ts` أي من **الوسيط الذي يمرّ عليه كل طلب**؛ وترويسته
 * تنصّ على «صفر تبعيات — ولا حتى `site-config`» كي لا تُسحب حزمة كاملة إلى
 * هناك. فلو وُضع ما في هذا الملف داخل `site-config.ts` — وهو يستورد ثلاثة
 * عقود — لكان الخياران كلاهما خاسراً: نقضُ ذلك القرار، أو **نسخةٌ ثانية** من
 * المنطق نفسه (النمط ٨: رقمٌ واحد بمصدرين). فالورقة تحلّهما معاً.
 *
 * ملاحظة: التطبيع **للمطابقة** شيء آخر ومكانه القاعدة (`normalize_phone`،
 * الدفعة ١) — وهذا الملف للعرض والروابط الخارجة فقط. (**D-05**)
 */

/**
 * رمز الاتصال الدولي لمصر بلا `+`.
 *
 * ولماذا ثابتٌ لا إعداد؟ لأن السوق مثبَّتٌ في طبقةٍ أعمق سلفاً: `normalize_phone`
 * تعرف أنماط الموبايل المصري وحدها، والتسعير بالجنيه، والتغطية بمحافظات. فإعدادٌ
 * هنا يوهم بمرونةٍ لا تملكها القاعدة تحته. **وموضع التعميم حين يحتاجه مصنع
 * الـwhitelabel** (المرحلة ١٤): `business.addressCountry` قائمٌ في العقد بحرفين
 * (`EG`) — يُبنى عليه جدول رموزٍ حينها، وتُعمَّم `normalize_phone` معه في الحركة
 * نفسها. تعميم أحدهما دون الآخر يصنع نصف نظام.
 */
export const WA_DIALING_CODE = "20";

/**
 * رقم `wa.me` بصيغته الدولية — أو `null` إن تعذّر بناؤه.
 *
 * ── العيب الذي وُجدت لأجله ─────────────────────────────────────────────────
 *
 * كان البناء `whatsapp.replace(/\D/g, "")` حرفياً، فرقمُ المالك المخزَّن
 * `01010000506` يخرج `wa.me/01010000506`. و**واتساب يشترط رقماً دولياً بلا صفر
 * بادئ**، فيردّ «الرقم غير صالح» — أي أن **الزر العائم في كل صفحة**، وقسم التواصل،
 * وصفحة متابعة الحجز، وصفحة العودة من الدفع، وأزرار الاستفسار في بطاقات العروض،
 * وصفحة الصيانة، كلها تفتح واتساب على رسالة خطأ. وهي القناة الأولى في سوقٍ
 * يراسل قبل أن يتصل.
 *
 * ── ولماذا لا يكفي أن تطلب الشاشة الصيغة الدولية ───────────────────────────
 *
 * لأنها **تطلبها فعلاً** منذ بنائها («الواتساب بصيغة دولية بدون + … لأنه يُستخدم
 * في رابط `wa.me`»)، والمخزَّن محليٌّ رغمها. فالتلميح ليس حارساً، والحارس مكانه
 * هنا: **ما يُكتب يُقبل، وما يخرج يكون صحيحاً**.
 *
 * ── القواعد ────────────────────────────────────────────────────────────────
 *
 * 1. `+` بادئة ⇒ الرقم دوليٌّ كما كتبه صاحبه، تُنزع الرموز ويُترك.
 * 2. صفرٌ بادئ ⇒ محليّ، فيُستبدل الصفر برمز الدولة.
 * 3. يبدأ برمز الدولة سلفاً ⇒ يُترك (لا يُضاعَف الرمز).
 * 4. أقصر من تسع خانات ⇒ `null`؛ ورابطٌ يفتح خطأً أسوأ من زرٍّ غائب — وهو الحكم
 *    نفسه الذي حكم به `socialHref` في `site-config.ts`.
 */
export function waNumber(whatsapp: string | null | undefined): string | null {
  const raw = (whatsapp ?? "").trim();
  if (raw === "") return null;

  const international = raw.startsWith("+");
  let digits = raw.replace(/\D/g, "");
  if (digits === "") return null;

  if (!international) {
    if (digits.startsWith("0")) digits = WA_DIALING_CODE + digits.slice(1);
    else if (!digits.startsWith(WA_DIALING_CODE)) digits = WA_DIALING_CODE + digits;
  }

  return digits.length >= 9 ? digits : null;
}
