/**
 * أرقام الهاتف على الحدود الخارجة — وحدةٌ **ورقية بلا استيراد واحد**.
 *
 * ⚠ وخلوّها من الاستيراد شرطُ وجودها لا صدفة: `lib/maintenance.ts` يناديها،
 * وهو يُستورَد من `proxy.ts` أي من **الوسيط الذي يمرّ عليه كل طلب**؛ وترويسته
 * تنصّ على «صفر تبعيات — ولا حتى `site-config`» كي لا تُسحب حزمة كاملة إلى
 * هناك. فلو وُضع ما في هذا الملف داخل `site-config.ts` — وهو يستورد ثلاثة
 * عقود — لكان الخياران كلاهما خاسراً: نقضُ ذلك القرار، أو **نسخةٌ ثانية** من
 * المنطق نفسه (النمط ٨: رقمٌ واحد بمصدرين). فالورقة تحلّهما معاً.
 *
 * ملاحظة: التطبيع **للمطابقة** شيء آخر ومكانه القاعدة (`normalize_phone`،
 * الدفعة ١) — وهذا الملف للعرض والروابط الخارجة فقط. (**D-05**)
 */

/**
 * رمز الاتصال الدولي لمصر بلا `+`.
 *
 * ولماذا ثابتٌ لا إعداد؟ لأن السوق مثبَّتٌ في طبقةٍ أعمق سلفاً: `normalize_phone`
 * تعرف أنماط الموبايل المصري وحدها، والتسعير بالجنيه، والتغطية بمحافظات. فإعدادٌ
 * هنا يوهم بمرونةٍ لا تملكها القاعدة تحته. **وموضع التعميم حين يحتاجه مصنع
 * الـwhitelabel** (المرحلة ١٤): `business.addressCountry` قائمٌ في العقد بحرفين
 * (`EG`) — يُبنى عليه جدول رموزٍ حينها، وتُعمَّم `normalize_phone` معه في الحركة
 * نفسها. تعميم أحدهما دون الآخر يصنع نصف نظام.
 */
export const WA_DIALING_CODE = "20";

/**
 * رقم `wa.me` بصيغته الدولية — أو `null` إن تعذّر بناؤه.
 *
 * ── العيب الذي وُجدت لأجله ─────────────────────────────────────────────────
 *
 * كان البناء `whatsapp.replace(/\D/g, "")` حرفياً، فرقمُ المالك المخزَّن
 * `01010000506` يخرج `wa.me/01010000506`. و**واتساب يشترط رقماً دولياً بلا صفر
 * بادئ**، فيردّ «الرقم غير صالح» — أي أن **الزر العائم في كل صفحة**، وقسم التواصل،
 * وصفحة متابعة الحجز، وصفحة العودة من الدفع، وأزرار الاستفسار في بطاقات العروض،
 * وصفحة الصيانة، كلها تفتح واتساب على رسالة خطأ. وهي القناة الأولى في سوقٍ
 * يراسل قبل أن يتصل.
 *
 * ── ولماذا لا يكفي أن تطلب الشاشة الصيغة الدولية ───────────────────────────
 *
 * لأنها **تطلبها فعلاً** منذ بنائها («الواتساب بصيغة دولية بدون + … لأنه يُستخدم
 * في رابط `wa.me`»)، والمخزَّن محليٌّ رغمها. فالتلميح ليس حارساً، والحارس مكانه
 * هنا: **ما يُكتب يُقبل، وما يخرج يكون صحيحاً**.
 *
 * ── القواعد ────────────────────────────────────────────────────────────────
 *
 * 1. `+` بادئة ⇒ الرقم دوليٌّ كما كتبه صاحبه، تُنزع الرموز ويُترك.
 * 2. صفرٌ بادئ ⇒ محليّ، فيُستبدل الصفر برمز الدولة.
 * 3. يبدأ برمز الدولة سلفاً ⇒ يُترك (لا يُضاعَف الرمز).
 * 4. أقصر من تسع خانات ⇒ `null`؛ ورابطٌ يفتح خطأً أسوأ من زرٍّ غائب — وهو الحكم
 *    نفسه الذي حكم به `socialHref` في `site-config.ts`.
 */
export function waNumber(whatsapp: string | null | undefined): string | null {
  const raw = (whatsapp ?? "").trim();
  if (raw === "") return null;

  const international = raw.startsWith("+");
  let digits = raw.replace(/\D/g, "");
  if (digits === "") return null;

  if (!international) {
    if (digits.startsWith("0")) digits = WA_DIALING_CODE + digits.slice(1);
    else if (!digits.startsWith(WA_DIALING_CODE)) digits = WA_DIALING_CODE + digits;
  }

  return digits.length >= 9 ? digits : null;
}

/**
 * الرقم بصيغة **E.164** (‏`+201010000506`) — أو `null` بالقواعد الأربع نفسها.
 *
 * ولا نسخة ثانية من المنطق هنا بقصد: هي `waNumber` حرفاً بحرف ثم `+` أمامها.
 * الفرق بين السطحين شكليٌّ لا منطقي — `wa.me` يشترط المسار بلا `+` (يقرؤه محرفَ
 * ترميز في العنوان)، وكل ما عداه يشترطها. فوضع القواعد في موضعين يعني أن تشدُّد
 * أحدهما يوماً (طول أدنى أدق، رمز دولة ثانٍ) لا يبلغ الآخر — وهو النمط ٨ نفسه
 * الذي وُجد هذا الملف ليمنعه.
 *
 * ── ولماذا اسمٌ بالصيغة لا بالمستهلك ────────────────────────────────────────
 * `waNumber` سُمّيت بمستهلكها لأنها تخدمه وحده بصيغةٍ شاذة لا اسم لها. وهذه
 * تخدم مستهلكَين لا يجمعهما شيء إلا المعيار (‏`tel:` وحقل `telephone` في
 * schema.org)، فتسميتها بأحدهما تُخفي أنها للآخر أيضاً.
 */
export function e164Number(phone: string | null | undefined): string | null {
  const digits = waNumber(phone);
  return digits === null ? null : `+${digits}`;
}

/**
 * الشكل الوطني المصري كما تُخرجه `normalize_phone` في القاعدة: `01XXXXXXXXX`.
 * تُقرأ هنا **للتفريع في العرض وحده** — لا للتطبيع.
 */
const EG_NATIONAL_PATTERN = /^01\d{9}$/;

/**
 * الرقم **كما فهمه النظام**، مصفوفاً ليُقرأ بالعين — `+20 10 1000 0506`.
 *
 * ── لمن يقرأ: هذه **مُنسِّقة عرض لا مُطبِّعة** ─────────────────────────────
 *
 * مُدخلها ناتج `public.normalize_phone` من القاعدة — وهي **المرجع الوحيد**
 * للتطبيع في هذا المشروع (‏`0026`، وعليها يقع كل مطابقة عميل عبر
 * `bookings.phone_norm`). فلا تُنادى بنصٍّ خام أبداً، ولا تُعيد اشتقاق شيء:
 * كل ما تفعله أن تختار الشكل الدولي وتضع فيه فواصل.
 *
 * ولماذا الشكل الدولي وقد كتبه العميل وطنياً؟ **لأن اختلاف الشكل هو الفائدة.**
 * الغرض أن يقرأ العميل رقمه بعينٍ جديدة قبل أن يؤكّده؛ ونصٌّ يطابق ما كتبه
 * حرفاً بحرف تقفز عليه العين ولا تراجع خانةً واحدة. والتجميع (رمز الدولة ‏+
 * بادئة الشبكة + أربعة + أربعة) يجعل الخانة المقلوبة مرئية.
 *
 * ⚠ **ولا تُبنى على `waNumber` إلا في الفرع المصري.** ما ليس مصرياً يخرج من
 * `normalize_phone` **دولياً بلا `+`** (بعد حذف بادئة `00`)، و`waNumber` تقرأ
 * غياب `+` وغياب الصفر البادئ على أنه رقمٌ محليٌّ عارٍ فتلصق `20` أمامه —
 * فيصير رقم لندن رقماً مصرياً. فالفرع الثاني يضع `+` وحدها ولا يمسّ الخانات.
 *
 * والإرجاع `null` لِما لا يصلح للعرض (فارغ · أقصر من تسع خانات)، والمنادي
 * يمتنع عن عرض سطر التأكيد كله — **صمتٌ خيرٌ من رقمٍ مبتور يؤكّده العميل**.
 */
export function formatNormalizedPhone(normalized: string | null | undefined): string | null {
  const digits = (normalized ?? "").trim();
  if (digits === "" || !/^\d+$/.test(digits)) return null;

  if (EG_NATIONAL_PATTERN.test(digits)) {
    // `e164Number` تتولّى استبدال الصفر البادئ برمز الدولة — لا نسخة ثانية منه
    const e164 = e164Number(digits);
    if (e164 === null) return null;
    // +20 | 1X | XXXX | XXXX
    const body = e164.slice(3);
    return `+${WA_DIALING_CODE} ${body.slice(0, 2)} ${body.slice(2, 6)} ${body.slice(6)}`;
  }

  if (digits.length < 9) return null;
  // أجنبيٌّ خرج دولياً من `normalize_phone` — تُضاف `+` ويُجمَّع بلا تخمين بلد
  return `+${digits.replace(/(\d{3})(?=\d)/g, "$1 ")}`;
}

/**
 * رابط محادثة واتساب كاملاً — أو `null` إن تعذّر بناء الرقم.
 *
 * ── لماذا الرابط نفسه هنا لا الرقم وحده ────────────────────────────────────
 * لأن الرقم وحده لم يمنع النسخ: `waNumber` كانت قائمة، ومع ذلك بقيت **أربع
 * شاشات** تبني `https://wa.me/${…}` بيدها بنزع الرموز، فورثت العيب الأصلي كاملاً
 * (بطاقة العميل في بوابة المتعهد، وتفاصيل الطلب، وملف المتعهد، وطلبات عروض
 * الأسعار). فما دام بناء العنوان مسموحاً في كل ملف، تكفي غفلةُ واحدٍ لإعادة
 * العيب. الآن العنوان يُبنى **هنا وحده**، وقاعدة `no-restricted-syntax` في
 * `eslint.config.mjs` تُسقط أي قالب `wa.me/${…}` خارج هذا الملف وأخيه
 * `components/site/links.ts`.
 *
 * والإرجاع `null` لا عنوانٌ مبتور: القاعدة الحية أثبتت أن ما يصل هذه الشاشات
 * ليس رقم المالك المضبوط بل ما كتبه العميل أو المتعهد — و**رابطٌ يفتح «الرقم غير
 * صالح» أسوأ من زرٍّ غائب**، فالمنادي يُخفي الزر بدل أن يَعِد بمحادثة لا تنعقد.
 */
export function waLink(whatsapp: string | null | undefined): string | null {
  const number = waNumber(whatsapp);
  return number === null ? null : `https://wa.me/${number}`;
}

/**
 * رابط اتصال هاتفي بالصيغة الدولية — أو `null` إن لم يبقَ رقمٌ يُتصل به.
 *
 * ── الحكم الذي يخصّ `tel:` وحده، ولماذا E.164 مكسبٌ لا نقض ─────────────────
 *
 * `tel:` **ليس** `wa.me`: الرقم المحلي `tel:01010000506` يطلب فعلاً من هاتف
 * زائرٍ في مصر، فالعطب ليس ظاهراً كرسالة «الرقم غير صالح». ولذلك لا يكفي أن
 * يُقال «طبّعناه للاتساق» — وجب وزن الحالتين:
 *
 *   • **الزائر المحلي** لا يخسر شيئاً. الصفر البادئ بادئةُ اشتراكٍ داخلية،
 *     و`+20` تؤدي المكالمة نفسها من الهاتف نفسه — وهو ما تفعله كل جهة اتصال
 *     محفوظة في أي هاتف. **والنص المعروض يبقى كما كتبه المالك** (`01010000506`)
 *     لأن الشاشات تعرض `contact.phone` خاماً وتضع المُطبَّع في `href` وحده،
 *     فلا يرى القارئ المحلي شكلاً غريباً عنه.
 *
 *   • **الزائر خارج مصر يكسب المكالمة كلها.** وهذا ليس فرضاً نظرياً في هذا
 *     المنتج بالذات: نقلٌ سياحي، وجمهوره الأول من يهبط بشريحة أجنبية أو متجوّلاً
 *     — والصفر البادئ عنده بادئةٌ لا تعني شيئاً خارج الشبكة المصرية، فالطلب يفشل
 *     صامتاً. أي أن الحالة العاملة تبقى عاملة، والفاشلة تعمل.
 *
 * ويزيدها RFC 3966 حسماً: `tel:` بلا معامل `phone-context` **يجب** أن يكون رقماً
 * عالمياً يبدأ بـ`+`؛ فالمحلّي العاري مخالفٌ للمواصفة لا مجرد أقلّ حظاً.
 *
 * أما `null` فيصيب حالةً واحدة — نصٌّ لا رقم فيه أصلاً — ومنادٍ يعرض الرقم
 * نصّاً بلا رابط خيرٌ من مرساةٍ تطلب فراغاً.
 */
export function telLink(phone: string | null | undefined): string | null {
  const number = e164Number(phone);
  if (number !== null) return `tel:${number}`;
  /**
   * ما رفضته القواعد الأربع (أقصر من تسع خانات) لا يُهدر: قد يكون تحويلةً
   * داخلية أو خطاً مختصراً، و`tel:` بها يطلب ما كتبه صاحبه فعلاً — بخلاف
   * `wa.me` التي تدّعي حساباً غير موجود. فالسقوط هنا إلى الأرقام كما كُتبت.
   */
  const bare = (phone ?? "").replace(/[^+\d]/g, "");
  return bare === "" || bare === "+" ? null : `tel:${bare}`;
}
