/**
 * عقد نظام السجلات (الدفعة ٤ — الملاحظة ١٥) — المرجع الأوحد.
 *
 * نصّ المالك في `docs/VISION.md` ملحق ٢ ملاحظة ١٥:
 * «لا سجلات (Logs) — المطلوب نظام سجلات متكامل وشامل يسجّل كل حدث **ويربط كل
 * شيء ببعضه**، فيمكن تتبّع حركات المستخدمين وكل إجراء أو تعديل والرجوع إلى أي
 * حدث في الماضي بالتفصيل.»
 *
 * ── القرار الأول: نوسّع `booking_events` ولا نخترع بجانبه ──────────────────
 *
 * المستودع **ليس** خالياً من التدقيق كما يبدو لأول نظرة: `public.booking_events`
 * (هجرة 0007) جدولُ تدقيقٍ عامل منذ المرحلة ٤، وفيه ثلاثة قرارات صحيحة تُنسخ
 * هنا حرفاً بحرف بدل إعادة اكتشافها:
 *
 *   (أ) **`actor uuid` بلا مفتاح أجنبي — بقصد.** تعليق 0007 صريح: «السجل تدقيقي
 *       ويجب أن يبقى بعد حذف المستخدم». ومفتاحٌ أجنبي بـ`on delete set null`
 *       (كما في `translations.updated_by` وحده) **يمحو الفاعل** يوم يُحذف حسابه
 *       — أي أن السجل يفقد بالضبط ما وُجد لأجله.
 *   (ب) **يُكتب بمُشغّل لا بنداء.** «فلا يمكن أن يتم انتقال بلا سطر في السجل
 *       مهما كان مسار التعديل». وهذا يحسم مسألة التزوير كذلك: صفٌّ يكتبه مُشغّل
 *       لا يستطيع مستدعٍ تخطّيه ولا انتحال فاعله، ولا يحتاج منحةً لأحد.
 *   (ج) **الفاعل يُشتق ولا يُمرَّر.** `public.current_actor()` (0007) تُرجع
 *       `auth.uid()` داخل معالج استثناء («الحجز أهم من تسجيل الفاعل»)، وهي
 *       **مسحوبة من `public` و`anon` و`authenticated`** ولا تُمنح لأحد.
 *
 * 🔒 **ولا نكرّر شكل `ledger_on_expense_insert`:** هو يقرأ
 * `coalesce(new.created_by, current_actor())` — أي أن **قيمةً يرسلها المستدعي
 * تفوز على الهوية الحقيقية**. في جدول مصروفات ذلك مقبول بحكم RLS فوقه؛ في سجلّ
 * تدقيق يكون بابَ تزوير التاريخ نفسه. فالفاعل هنا من `current_actor()` **وحدها**
 * ولا عمود يقبله من الخارج.
 *
 * ── القرار الثاني: ما يُحفظ من القيم — وهذا أخطر ما في الملاحظة ─────────────
 *
 * مسح مسارات الكتابة كشف أن مُشغّلاً ساذجاً بـ`to_jsonb(NEW)` كان سيكتب في
 * **جدول واحد**: مفاتيح بوابات الدفع (`payment_providers`)، وتوكنات القياس
 * (`site_settings.integrations`)، وأسماء العملاء وهواتفهم (`bookings`). فيصير
 * السجلّ أغنى هدفٍ في القاعدة كلها، وخطأُ منحةٍ واحد يسلّمه لكل متعهد.
 *
 * فالقاعدة: **الحدث يُسجَّل كاملاً، والقيمة الحساسة تُسجَّل بأنها تغيّرت ولا
 * تُنسخ.** أي أن السطر يقول «فلان غيّر مفتاح Paymob في هذا التوقيت» ولا يحمل
 * المفتاح لا قديمه ولا جديده. لا يضيع بذلك شيء من غرض التدقيق: المدقّق يريد
 * **من ومتى وماذا مسّ**، لا نسخةً ثانية من السرّ.
 *
 * ── القرار الثالث: D-48 يقسم النظام قسمين، ولا مفرّ من ذلك ─────────────────
 *
 * كل نداء PostgREST معاملة واحدة، فالاستثناء يُرجِع كل ما كُتب فيها **بما فيه
 * سطر السجل**. وعليه:
 *
 *   • **التغيير المُنفَّذ** يُسجَّل بمُشغّل داخل المعاملة نفسها — فيثبت معه
 *     ويُلغى معه. وهذا **صحيح تماماً**: تغييرٌ أُلغي لم يقع، وسطرٌ يقول إنه وقع
 *     كذبة.
 *   • **المحاولة المرفوضة** (‏٦١ رفضاً بـ`forbidden`، و`debt-limit`،
 *     و`margin-floor`، و`already-assigned`، و`immutable-row`…) **لا يمكن أن
 *     يسجّلها مُشغّل إطلاقاً** — ترمي فتُرجِع سطرها معها. وهي بالضبط ما يريده
 *     التدقيق الأمني.
 *
 * والحل ليس اختراعاً: `find_booking_by_reference` في 0027 حلّها بالقلب —
 * «لا نتيجة ⇒ **صفر صفوف بلا استثناء** حتى تبقى المحاولة محسوبة». فالمحاولات
 * المرفوضة تُسجَّل من **معاملة ثانية** يفتحها الخادم بعد التقاط الخطأ، عبر
 * `record_audit_attempt()`. ومن يضع نداءها داخل `try` مع العملية نفسها يكون قد
 * أعاد إنتاج D-48 بيده.
 */

