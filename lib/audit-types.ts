/**
 * سطر واحد في `public.audit_log`.
 *
 * **«يربط كل شيء ببعضه»** (نصّ الملاحظة) يقع عبر عمودَي ربط مُلحقَين بكل صف:
 * `bookingId` و`subcontractorId`. وهما تكرارٌ متعمَّد لبيانات موجودة في الصف
 * المُعدَّل — سببه أن السؤال الحقيقي للمالك ليس «ماذا جرى على جدول الحجوزات؟»
 * بل **«ماذا جرى لهذا الحجز؟»**: الدفعة والإيصال والبث والقبول والتسوية، كلها
 * في جداول مختلفة وتُقرأ باستعلام واحد مفهرس.
 */
export type AuditEntry = {
  id: number;
  occurredAt: string;
  actor: string | null;
  actorKind: AuditActorKind;
  /** اسم الجدول — `bookings` · `payments` · `site_settings` … */
  entity: string;
  entityId: string | null;
  /** لقطة نصية تبقى بعد حذف الصف — مرجع الحجز، اسم الشركة، مفتاح الإعداد */
  entityLabel: string | null;
  action: AuditAction;
  /**
   * `{ عمود: { from, to } }` للتحديث. والعمود الحساس يظهر
   * `{ عمود: { redacted: true } }` — تغيّر مسجَّل بلا نسخ قيمته (القرار ٢).
   */
  changes: Record<string, unknown> | null;
  /** الصف كاملاً **عند الحذف وحده** — وإلا ضاع ما حُذف بلا أثر */
  snapshot: Record<string, unknown> | null;
  note: string | null;
  bookingId: string | null;
  subcontractorId: string | null;
};

/**
 * محاولة مرفوضة — سطر في `audit_log` كذلك، لكن `action` فيه `'reject'`… **لا.**
 *
 * ⚠ قرارٌ يستحق التوضيح: المحاولة المرفوضة **لا تدخل `audit_log`**، بل جدولها
 * `audit_attempts` المنفصل. والسبب أن خلطهما يكسر أهم خاصية في الأول: `audit_log`
 * يُكتب **بمُشغّل داخل معاملة التغيير** فيستحيل تزويره أو تخطّيه؛ بينما
 * `audit_attempts` يُكتب **بنداء من الخادم بعد فشل المعاملة**، أي بثقةٍ أضعف
 * بنيوياً. وضعُ السطرين في جدول واحد يجعل كل قارئ يفترض في الأضعف ضمانةَ الأقوى.
 */
export type AuditAttempt = {
  id: number;
  occurredAt: string;
  actor: string | null;
  actorKind: AuditActorKind;
  /** اسم العملية كما يعرفها الخادم — `manual_assign` · `accept_offer` … */
  operation: string;
  /** تلميح الرفض من القاعدة — `forbidden` · `debt-limit` · `margin-floor` … */
  reason: string;
  entity: string | null;
  entityId: string | null;
  detail: string | null;
};

