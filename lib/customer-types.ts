/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  عقد حسابات العملاء — المرحلة ١٢ب                                        ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * العميل يسجّل دخولاً، فيرى حجوزاته الماضية ويحجز من جديد بلا إعادة إدخال، ثم
 * يُبنى الولاء على هذا الأساس. هذا هو المطلوب. وهذا الملف يكتب **الحدود** التي
 * يُبنى داخلها، لأن ثلاثة منها قِيست على القاعدة الحيّة قبل كتابة سطر واحد،
 * وواحدٌ منها كان سيُسرِّب المنتج كله.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §١ — القاعدة الحاكمة: **العميل لا يحصل على سياسة `SELECT` على `bookings`**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * ── القياس، لا التقدير ──────────────────────────────────────────────────────
 *
 * أُنشئت في معاملة تُلغى سياسةٌ ساذجة واحدة — النوع الذي تكتبه أي جلسة تبني
 * «صفحة حجوزاتي» بحسن نيّة:
 *
 *     create policy … on public.bookings for select to authenticated
 *     using (phone_norm = <هاتف العميل>)
 *
 * فكانت الحصيلة المقيسة **يوم 2026-08-14**:
 *
 * ⚠ والأرقام أدناه **لقطةٌ مؤرَّخة لا ثابت**: `pnpm demo:seed` يهدم بيانات العرض
 * ويعيد بناءها، فمن أعاد القياس غداً وجد أعداداً أخرى — وقد قِيست ٢٣٦ ثم ٨٩ في
 * اليوم التالي أثناء دورة زرع. **والشاهد ليس المقدار بل النسبة**: سياسةٌ واحدة
 * تفتح **أربعة أسطح**، ثلاثةٌ منها لا يمرّ عليها من يراجع «ميزة العميل» — وذلك
 * لا يتغيّر بتغيّر عدد الصفوف.
 *
 * | السطح | ما انكشف |
 * |---|---|
 * | `bookings` | ٣٤٠ صفاً، **٢٩٩ منها تحمل `subcontractor_cost` و`margin_amount` و`subcontractor_id`** |
 * | `v_booking_profit` | ٣٤٠ صفاً — ربح كل حجز على حدة |
 * | `v_stats_orders` | ١٨٢ صفاً |
 * | `v_stats_customers` | ١٣٧ صفاً |
 *
 * أي أن **سياسةً واحدة تفتح أربعة أسطح**، ثلاثةٌ منها لا يمرّ عليها من يراجع
 * «ميزة العميل» أصلاً.
 *
 * ── ولماذا لا يكفي «سنختار الأعمدة في الاستعلام» ────────────────────────────
 *
 * لأن المنح على `bookings` لـ`authenticated` قائم على **الأعمدة الـ٢٣ كلها**
 * (‏`SELECT` و`UPDATE`)، و**Postgres لا يملك RLS على مستوى العمود**: الـRLS
 * يرشّح **الصفوف** والمنح يرشّح **الأعمدة**. فما دام المنح مفتوحاً، فاختيارُ
 * الأعمدة في كود التطبيق تجميلٌ لا حراسة — والعميل يفتح PostgREST بتوكنه
 * ويطلب `select=*` فيأتيه هامشنا في كل صف.
 *
 * ── والأسطح الأربعة تنقلب معاً لأنها ورثةٌ لا مستقلّة ───────────────────────
 *
 * الاطلاعات الاثنا عشر كلها `security_invoker=true` — وهو **الصواب** وسبب أن
 * الوضع اليوم سليم: المتعهد (وهو مستخدم `authenticated` بالقاعدة الأم) يقرأ
 * اليوم **صفر صفوف** من `bookings` و`v_booking_profit` و`v_stats_orders`،
 * قِيس ولم يُقدَّر. لكن `security_invoker` سيفٌ ذو حدّين: ما دامت الاطلاعات
 * ترث سياسات `bookings`، فتوسيع تلك السياسات يوسّعها كلها في اللحظة نفسها،
 * **بلا سطر يتغيّر فيها ولا مراجعة تمرّ عليها**.
 *
 * ── فالطريق المرسوم ─────────────────────────────────────────────────────────
 *
 * 🔒 **لا سياسة `SELECT` جديدة على `bookings`. أبداً.** يقرأ العميل حجوزاته من
 * دالة `security definer` تُرجع **الإسقاط الآمن وحده** — تماماً كما يقرأ
 * المتعهد رحلاته من `portal_trips()` وكما يقرأ الزائر حجزه من
 * `get_booking_by_token()`. النمط قائمٌ في هذا المستودع منذ المرحلة ٥، مُختبَر،
 * ومحروسٌ بفحوص ذاتية تمنع تسرّب التكلفة والهامش. و١٢ب تسلكه لا تخترع غيره.
 *
 * والفارق العملي أن **التسريب يصير مستحيلاً بالبناء لا ممنوعاً بالانضباط**:
 * الدالة تُرجع الأعمدة التي كُتبت فيها، فما لم يُكتب لا يخرج — ولا يوجد
 * `select=*` يلتفّ عليها.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٢ — ثغرة التسجيل: `handle_new_user` تنسخ هاتفاً **لم يتحقق منه أحد**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * الدالة الحيّة (من `pg_get_functiondef` — D-58) تفعل هذا عند كل تسجيل:
 *
 *     insert into public.profiles (id, full_name, phone)
 *     values (new.id, new.raw_user_meta_data ->> 'full_name',
 *                     new.raw_user_meta_data ->> 'phone')
 *
 * و`raw_user_meta_data` **حمولةٌ يرسلها العميل في نداء التسجيل** — يكتب فيها ما
 * شاء. فهي اليوم بلا أثر لأن لا أحد يقرأ `profiles.phone`. لكن ١٢ب تُبنى بالضبط
 * على المطابقة بالهاتف («أرِ العميلَ حجوزاته») — فتصير الحمولة المزوَّرة
 * **مفتاحاً لحجوزات غيره**: يسجّل بأي بريد، يكتب في `phone` رقم عميلٍ يعرفه،
 * فيرى رحلاته وعناوينه وما دفعه.
 *
 * 🔒 فالربط **لا يكون بالهاتف المكتوب في التسجيل**، بل بهاتفٍ **أثبت العميل
 * ملكيته** — رمز يصله عليه ويؤكده. وحتى ذلك الحين، هذا الحقل يُعامَل «ما ادّعاه
 * المستخدم» لا «هاتف العميل». وتطبيع الهاتف (الدفعة ١) شرطُ صحة المطابقة لا
 * شرط أمانها — الأول يمنع الخطأ والثاني يمنع الانتحال، ولا يغني أحدهما.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٣ — `profiles.role` افتراضه `'customer'`، وهذا **مقصود ومحروس**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * قِيس على القاعدة: `column_default = 'customer'::text` منذ `0001`. أي أن كل من
 * يسجّل يصير عميلاً — وهو الصواب: لا ترقية بالسهو إلى إدارة أو تعهّد. والهجرة
 * `0025` أُنجزت تحديداً لتسبق هذا الفتح، فلا يُبنى عليه شيء قبلها.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٤ — تدقيق المنح الإلزامي: **أُجري، وحصيلته أنظف مما افترضته الخارطة**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * الخارطة تشترط أن تبدأ ١٢ب «بمراجعة كل منح قائم لا ببناء شاشة»، لأن كل سياسة
 * RLS وكل `grant … to authenticated` في **٢٥** هجرة كُتبت على القاعدة الأم
 * (**D-20**: كل `authenticated` متعهدٌ أو موظف)، وبعد ١٢ب تصير تعني **أي زائر
 * ملأ نموذجاً**. أُجري التدقيق بإنشاء عميلٍ افتراضي بدور `customer` داخل معاملة
 * تُلغى، ثم **مناداة كل شيء فعلاً** — لا قراءة سياسات.
 *
 * ── (أ) الجداول والاطلاعات: ٨ كيانات من ٥٩ ─────────────────────────────────
 *
 * ما يقرأه العميل المسجَّل اليوم: `sections` (٩٣) و`pages` (١٧) و`site_settings`
 * (١٠) و`tariffs` (٤) و`vehicle_classes` (٤) و`locales` (٢) و`pricing_settings`
 * (١) — وكلها **يقرأها الزائر المجهول أصلاً**، فالموقع العام مبنيّ عليها —
 * و**صفَّه هو وحده** من `profiles` (١ من ١٠). وصفرٌ من الاطلاعات الاثني عشر
 * كلها، وصفرٌ من `bookings` والمالية والإحصاءات.
 *
 * 🔎 **وهذا يصحّح تخوّفاً مكتوباً في الخارطة**: `grant select on v_stats_customers
 * to authenticated` (‏`0022_analytics.sql`) بدا أنه سيجعل «عميلاً مسجَّلاً يقرأ
 * إحصائيات عملاء الموقع». وهو **لا يفعل**، لأن الاطّلاع `security_invoker=true`
 * فيرث سياسات `bookings` التي تشترط `is_admin()`. المنح واسع والحارس أسفل منه.
 *
 * ── (ب) الدوال: ٧٧ دالة `security definer`، والحصيلة «لا شيء جديد» ──────────
 *
 * وهذه هي التي تستحق القياس فعلاً: **`security definer` لا ترث RLS المنادي**،
 * فالحارس فيها داخليٌّ أو معدوم. نوديت واحدةً واحدة بدور متعهد وبدور عميل:
 *
 * 🟢 **ما ينجح للعميل المسجَّل ولم يكن ينجح للمتعهد: لا شيء.** ١٢ب لا تفتح دالة
 * واحدة جديدة. والمالية والتدقيق والبث كلها ترفض برسالة صريحة
 * («المؤشرات المالية متاحة للإدارة فقط»)، ومنها `partner_statement` بمعرّف
 * **متعهد آخر** — أي أن عزل «متعهد ضد متعهد» (**D-19**) صامدٌ بالقياس.
 *
 * وما ينجح للاثنين ثلاثةَ عشرَ، كلها محتوى عام يناديه الزائر المجهول أصلاً
 * (`localized_page` · `localized_settings` · `t` · `enabled_locales` ·
 * `public_extras` · `price_extras` · `receipt_upload_allowed` …)، وواحدة كاتبة
 * راجعتُها بعينها: `record_audit_attempt` تكتب في `audit_attempts` — وهي
 * **مصمَّمة لذلك**: الزائر بلا هوية يخرج بصمت، والفاعل يُسجَّل، والسقف ٦٠
 * محاولة في الساعة يُعدّ على صفوف ملتزمة، والحقول تُقصّ. فالإغراق محدود والتزوير
 * منسوبٌ إلى صاحبه.
 *
 * ⚠ **ودرسٌ من طريقة التدقيق نفسها**: أول تمريرة بحثت عن حارس بنمط نصّي في أجسام
 * الدوال، فأعلنت **٤١ دالة «بلا حارس»** — وكلها محروسة، لكن بفحص دور مكتوبٍ
 * بصيغة لم يعرفها النمط. أي أن الكاشف أنتج ٤١ إنذاراً كاذباً، **ولو كان الخلل
 * معكوساً لأنتج طمأنينة كاذبة**. النداء الحيّ هو الحقيقة، لا مطابقة النصوص.
 *
 * ── (ج) فما الذي يبقى خطراً إذاً؟ ──────────────────────────────────────────
 *
 * §١ و§٢ وحدهما. لا يأتي الخطر من المنوح اليوم، بل مما **سيُكتب غداً**: سياسة
 * `SELECT` واحدة على `bookings`، أو مطابقةٌ بهاتفٍ لم يُتحقق منه.
 */

/**
 * ══════════════════════════════════════════════════════════════════════════
 *  §٥ — كيف يُربط حجزٌ سابق بحساب: **بما هو مبنيٌّ ومُصلَّب، لا بجديد**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * البديهي أن تُطابَق الحجوزات بهاتف الحساب. و§٢ يمنعه: الهاتف يأتي من حمولة
 * التسجيل. والبديل البديهي الثاني — تحقّقٌ برمز SMS — يستلزم **مزوّد رسائل غير
 * مضبوط** (‏`OPEN_TASKS` تذكر Resend للبريد ولا شيء للرسائل)، أي قرار مالكٍ
 * وتكلفةٌ شهرية يعلّقان مرحلةً كاملة.
 *
 * 🔎 **والمخرج أن المشروع يملك إثبات الملكية أصلاً**: صفحة `/track` تعمل منذ
 * الدفعة ٢ بـ`find_booking_by_reference(p_reference, p_phone, p_client_key)` —
 * ومَن يملك **رقم الحجز وهاتفه معاً** هو صاحبه. والدالة مُصلَّبة بما لا يُعاد
 * بناؤه بسهولة: تطبيعُ المرجع يقبل `TR-ABC123` و`tr abc123` سواءً، وتطبيعُ
 * الهاتف **داخلها** لأن `normalize_phone` لا تُمنح للزائر بحال، وسقفٌ ثمانيَ
 * محاولات لكل ربع ساعة — سخيٌّ للإنسان وقاتلٌ لتعداد ٣١⁶ — **وترتيبُ خطواته
 * هو الميزة**: العدّ قبل البحث، ومسار «لا نتيجة» يرجع صفر صفوف **ولا يرمي**،
 * وإلا لأرجعت المعاملةُ صفَّ العدّاد معها فبقي المهاجم بلا خانق (**D-48**).
 *
 * فالربط يُفوَّض إليها ولا يستنسخها (**القاعدة ١٢**). ومكسبان في قرار واحد:
 * تسقط تبعية مزوّد الرسائل، ويسقط خطر §٢ من المسار كله — إذ لا يُقرأ
 * `profiles.phone` أصلاً في المطابقة.
 *
 * ── ومدخلان لا مدخل ────────────────────────────────────────────────────────
 *
 * 1. **`link_booking_by_reference`** — «أضِف حجزاً سابقاً»: يكتبه العميل بنفسه
 *    بمرجعه وهاتفه. مسارٌ صريح، لكل حجزٍ على حدة، ويقبل السقف نفسه.
 * 2. **`link_booking_by_token`** — بعد إتمام حجزٍ جديد ومعه جلسة عميل: الخادم
 *    يملك التوكن الذي أصدره لتوّه، والحيازةُ إثبات. **ولا سقف عليه** لأن لا شيء
 *    يُعدّ: التوكن سلسلة عشوائية طويلة، ومن يملكه يرى الصفحة كاملةً أصلاً —
 *    فالربط **لا يكشف حرفاً جديداً**، وإنما يضيف سطراً إلى قائمة صاحبه.
 *
 * ── ⚠ والمدخلان ليسا متكافئين، وقولي إنهما كذلك كان خطأً ──────────────────
 *
 * كُتب أعلاه أن الحيازة إثبات. وهي إثباتُ **وصول** لا إثباتُ **ملكية** — والفرق
 * لا يظهر ما دام الربط سطراً في قائمة، ويظهر في اللحظة التي يُقرأ فيها من ذلك
 * السطر **هاتفٌ أو اسم**. وروابط الحجوزات **تُعاد إرسالها**: يبعثها العميل إلى
 * زوجته أو سائقه أو مجموعة عمل. فمن أُرسل إليه رابط، ثم ربطه بحسابه، يرث في
 * `BookingPrefill` اسمَ صاحب الحجز وهاتفه — أي أن **§٢ يُفتح من بابٍ ثانٍ بعد
 * أن أُغلق الأول**، وقد وعد هذا العقد نفسه بأن حقل الهاتف «المُثبَت وحده».
 *
 * 🔒 **فالتمييز يُخزَّن مع الصف لا يُستنتَج بعده**: `customer_bookings.link_source`
 * إمّا `'reference'` — ومعناه أن صاحب الحساب **أثبت** الهاتف عبر
 * `find_booking_by_reference` — أو `'token'` أي حيازةٌ وحدها. و**`BookingPrefill`
 * لا يُملأ إلا من ربطٍ مصدره `'reference'`**؛ وما جاء بالتوكن يُعرض في القائمة
 * ولا يُشتقّ منه هوية.
 *
 * والحدّ سببه أن **الضرر مؤجَّل لا معدوم**: لا مِلء تلقائي مبنيّ اليوم، فالخلل
 * نظريٌّ الآن ويصير حقيقياً بأول سطرٍ يقرأ هاتفاً من حجزٍ مربوط. ولذلك يُكتب
 * التمييز **قبل** أن يوجد قارئه — إضافةُ عمودٍ اليوم أهون من مطاردة القراءات غداً.
 *
 * ⚠ **والربط لا ينزع**: `customer_bookings` مفتاحها المركّب `(profile, booking)`،
 * فربط شخصٍ حجزاً لا يزيله من قائمة أحد. الحجز كضيف يبقى عاملاً كما هو، وصفحة
 * التوكن تبقى المرجع — الحساب **طبقةُ راحة فوقهما، لا بوابةٌ دونهما** (وهو نصّ
 * الرؤية: رحلة العميل مرسومة كاملةً بلا حساب).
 */

/**
 * رموز رفض ربط حجزٍ بحساب.
 *
 * ⚠ **وطريقا الوصول مختلفان بقصد**: يرفع الغلافان أكثرها بـ`using hint`، أما
 * `not-found` من مسار **المرجع** فيصل **صفرَ صفوف بلا استثناء** — لأن الرفع
 * هناك يُرجع معاملةَ الدالة ومعها صفُّ العدّاد الذي كُتب لتوّه، فيبقى التعداد
 * بلا خانق (**D-48**). فمن يقرأ هذه القائمة ويبني عليها معالجة أخطاء يجب أن
 * يعامل «صفر صفوف من `link_booking_by_reference`» رمزَ `not-found` كاملاً.
 *
 * ⚠ **و`forbidden` ليس منها**: ترفعه الدالتان حين لا جلسة أصلاً، وهو حارس
 * مصادقة على سطحٍ خلف تسجيل الدخول لا رفضَ ربط. وأُبقي خارج الاتحاد كي لا
 * تختلط رسالةُ «راجع بياناتك» برسالة «سجّل دخولك» في نفس الخريطة.
 */
export type LinkRefusal =
  | "invalid-input"
  | "rate-limited"
  /**
   * ⚠ **لا يفرّق** بين «مرجع لا وجود له» و«مرجع صحيح بهاتف خاطئ» — والتفريق
   * يجعل النموذج **مُثبِتاً لوجود الحجز** لمن يملك المرجع وحده. وهو الرمز نفسه
   * الذي ترفعه `/track` للسبب نفسه.
   */
  | "not-found"
  /** مربوطٌ بهذا الحساب سلفاً — نجاحٌ في نظر العميل لا خطأ، فتُعرض كذلك */
  | "already-linked";

/**
 * الإسقاط الآمن لحجز كما يراه صاحبه في «حجوزاتي».
 *
 * 🔒 **كل حقل هنا قرارٌ بالإضافة لا بالحذف**: ما ليس مكتوباً في هذا النوع لا
 * تُرجعه الدالة أصلاً (‏§١). ولذلك لا `subcontractorId` ولا `subcontractorCost`
 * ولا `margin*` ولا `priceSource` — وليست محجوبةً في العرض بل **غير موجودة في
 * الحمولة**، وهو الفرق الذي أصلحته `0043` في حمولة العميل بالدفعة ٥.
 *
 * ولا `publicToken` كذلك: التوكن مفتاح صفحة عامة بلا كلمة سرّ، ووضعُه في حمولة
 * قائمةٍ يعني أن أي تسريب لسجلّ واحد يسلّم مفاتيح كل حجوزات العميل. الانتقال إلى
 * صفحة الحجز يمرّ بالخادم الذي يُصدر التوكن للصفحة المطلوبة وحدها.
 */
export type MyBookingRow = {
  reference: string;
  status: string;
  /**
   * ⚠ **غير قابل للفراغ** — والعمود `NOT NULL` في `bookings` والقيد مُنفَّذ فعلاً
   * (‏`update … set class_title = null` يُرفض)، و`my_bookings()` تختاره خاماً
   * عبر وصلٍ داخلي. كان معلَناً `string | null` فيفرض على كل بطاقة حجزٍ فرعاً
   * ميتاً لا بديل له — إذ لا `classSlug` في هذه الحمولة يُرجَع إليه.
   *
   * والفرق مقصود عن الثلاثة أدناه (`originLabel`/`destLabel`/`pickupAt`): تلك
   * مشتقّةٌ من `trip` وهو `jsonb`، فمفتاحٌ غائب يُخرج `null` فعلاً — قِيس بحذف
   * المفاتيح داخل معاملة تُلغى. أي أن قابلية الفراغ هنا **تتبع مصدر الحقل**، لا
   * تحوّطاً موحّداً.
   */
  classTitle: string;
  /** ما يدفعه العميل — وهو الرقم الوحيد من أرقام الحجز الذي يخصّه */
  total: number;
  currency: string;
  amountDue: number;
  amountRemaining: number;
  originLabel: string | null;
  destLabel: string | null;
  pickupAt: string | null;
  passengers: number;
  createdAt: string;
};

/**
 * ما يُملأ تلقائياً في نموذج حجزٍ جديد لعميلٍ عائد — «بلا إعادة إدخال».
 *
 * ⚠ ولا يشمل وجهةً ولا سعراً: التسعير يخرج من `quote_price` في القاعدة عند كل
 * طلب (**D-05**)، وأي قيمة مُخزَّنة من حجزٍ سابق تصير سعراً قديماً يُعرض على
 * أنه عرضٌ قائم.
 */
export type BookingPrefill = {
  customerName: string | null;
  /**
   * الهاتف المُثبَت وحده — لا ما كُتب في التسجيل (‏§٢)، **ولا ما جاء من حجزٍ
   * رُبط بالتوكن** (‏§٥): مصدره الوحيد المشروع صفُّ ربطٍ `link_source='reference'`،
   * أي حجزٌ أثبت صاحبُ الحساب هاتفَه بنفسه.
   */
  customerPhone: string | null;
  customerWhatsapp: string | null;
};

/**
 * كيف رُبط الحجز بالحساب — ويُقرأ قبل اشتقاق أي هوية منه (‏§٥).
 *
 * `'reference'` إثباتُ ملكية (مرجعٌ وهاتف مرّا بالدالة المُصلَّبة)، و`'token'`
 * إثباتُ **وصولٍ** وحده. والثاني يكفي لعرض الحجز في القائمة ولا يكفي لملء نموذج.
 */
export type LinkSource = "reference" | "token";

