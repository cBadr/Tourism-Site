/**
 * ولماذا خمسٌ لا واحدة: علاجُ كلٍّ منها مختلف، وجملةٌ واحدة («تعذّر عرضها
 * الآن») تُقال للغياب وللرفض وللانقطاع معاً هي بعينها ما أُصلح في بطاقة
 * السائقين. **ولا مربّعَ صامتٌ في هذه الشبكة.**
 */
export type VehiclePhotoState =
  | { kind: "url"; url: string }
  /** لا ملف أصلاً — والرفع اختياري */
  | { kind: "none" }
  /** المسار المخزَّن لا يطابق النمط الملزم — عطلُ بياناتٍ لا صلاحية */
  | { kind: "bad_path" }
  /** التخزين ردّ رفضاً: إمّا لا وجود له، وإمّا لا تشمله صلاحيتك */
  | { kind: "unavailable" }
  /** لم يصل الردّ أصلاً — التخزين غير قابلٍ للاتصال الآن */
  | { kind: "unreachable" };

/** مركبةٌ كما تُرسم في الشبكة — ولا مسارَ خام يعبر إلى JSX، الرابطُ فقط */
