/**
 * صفٌّ لكل فئة — **بما فيها الفئة التي لا مركبة له فيها**.
 *
 * 🔴 والصفرُ يُقال ولا يُحذف سطرُه: المشرف يحتاج أن يعرف **ما لا يملكه**
 * الشريك بقدر ما يملك. وسطرٌ غائبٌ يُقرأ «لم يُرسم» لا «لا يملك».
 */
export type FleetClassRow = {
  classSlug: string;
  /** عنوان الفئة كما في `vehicle_classes`، أو الـslug إن كانت الفئة محذوفة */
  title: string;
  /** السعة المعلَنة للعميل — قرارُ مالك، لا تُشتق من مقاعد الشريك */
  capacity: number | null;
  /** هل الفئة نفسها مفعّلة على المنصة؟ مركبةٌ في فئةٍ مطفأة لا تُسعَّر */
  classActive: boolean;
  total: number;
  active: number;
  withPhoto: number;
  seatsMin: number | null;
  seatsMax: number | null;
  /**
   * كم مركبةً تخالف مقاعدُها سعةَ فئتها المعلَنة.
   *
   * ⚠ **يُعرض ولا يُصحَّح**: السعة قرارُ مالكٍ (يرفعها ويخفضها من اللوحة)،
   * والمقاعد إقرارُ شريكٍ عن سيارته. فالتباين معلومةٌ للمشرف لا خطأٌ يُبتلع.
   */
  seatsMismatch: number;
};

