const MAPS_DIR_URL = "https://www.google.com/maps/dir/";

function coord(point: MapPoint): string {
  return `${point.lat.toFixed(6)},${point.lng.toFixed(6)}`;
}

/**
 * مسار الرحلة كاملاً: من نقطة الانطلاق إلى نقطة الوصول.
 * جمهوره: العميل بعد التأكيد، والمتعهد بعد الإسناد (رابطاً ثانوياً).
 */
export function tripDirectionsUrl(origin: MapPoint, destination: MapPoint): string {
  const url = new URL(MAPS_DIR_URL);
  url.searchParams.set("api", "1");
  url.searchParams.set("origin", coord(origin));
  url.searchParams.set("destination", coord(destination));
  url.searchParams.set("travelmode", "driving");
  return url.toString();
}

/**
 * الوصول إلى نقطة الالتقاط **من موضع السائق الآن** — بلا `origin` عمداً.
 *
 * جمهوره: المتعهد بعد الإسناد، **وهو الرابط الأوّل له لا الثاني**. فعلُه الفعلي
 * ليس «تأمّل المسار» بل «صِل إلى العميل»؛ ونقطةُ انطلاق الرحلة هي وجهتُه هو.
 * ووضعُ `origin` هنا كان سيرسم له طريقاً من مكانٍ ليس مكانه.
 */
export function pickupDirectionsUrl(pickup: MapPoint): string {
  const url = new URL(MAPS_DIR_URL);
  url.searchParams.set("api", "1");
  url.searchParams.set("destination", coord(pickup));
  url.searchParams.set("travelmode", "driving");
  return url.toString();
}
