import { cookies } from "next/headers";

/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  م‑٩ — عقد اختيار الثيم: ثلاث حالات، لا اثنتان                           ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * 🔴 **`system` حالةٌ ثالثة حقيقية، وليست «الداكن مبدئياً».**
 *
 * الفرق ليس تسميةً: زائرٌ لم يختر شيئاً ونظامه فاتح يجب أن يرى الموقع فاتحاً،
 * **وإن بدّل نظامه وهو في الصفحة انقلبت الصفحة معه بلا إعادة تحميل**. ولو
 * خُزّنت الحالة الافتراضية «داكن» لَما تحقّق أيٌّ من الأمرين، ولَصار المبدّل
 * طريقاً باتجاه واحد: من يختار مرةً لا يستطيع العودة إلى «اتبع نظامي».
 *
 * ── ولماذا كوكي لا `localStorage` ─────────────────────────────────────────
 *
 * لأن الوميض يُحسم على **الخادم** لا في المتصفح (الشرح الكامل في
 * `app/(site)/layout.tsx`): الكوكي يصل مع الطلب، فتخرج الصفحة من الخادم بثيمها
 * الصحيح في أول بايت. و`localStorage` لا يُقرأ إلا بعد وصول HTML، فيقتضي
 * سكربتاً حاجزاً في `<head>` يعيد الطلاء — وهو الحلّ الشائع، وهو أضعف: يفشل
 * بلا جافاسكربت، ويُدخل سطراً حاجزاً في المسار الحرج لكل صفحة.
 */

/** الحالات الثلاث كما تُخزَّن وكما تُقرأ */
export const THEME_CHOICES = ["system", "light", "dark"] as const;
export type ThemeChoice = (typeof THEME_CHOICES)[number];

/**
 * اسم الكوكي. البادئة `site.` تفصله عن كوكيز Supabase وnext-intl في نفس النطاق.
 *
 * ⚠ **ولا يُضاف إلى أي مفتاح تخزين مؤقت (`cache tag`) ولا يُقرأ في مسار مُخبَّأ
 * ثابتاً**: قراءة الكوكي تجعل الصفحة ديناميكية بحكم Next، وهذا مقصود هنا لأن
 * غلاف الموقع يقرؤها — لكن **لا تُقرأ داخل كتلةٍ أو مكوّنٍ عميق**، وإلا صارت
 * كل صفحةٍ فيه ديناميكية بلا أن يعرف كاتبها لماذا.
 */
export const THEME_COOKIE = "site.theme";

/** سنةٌ كاملة — الاختيار تفضيلُ قراءةٍ لا جلسة، ولا معنى لانتهائه بإغلاق المتصفح */
export const THEME_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

/**
 * قيمةٌ واصلةٌ من المتصفح ⇒ حالةٌ من الثلاث. وما ليس منها **`system`** لا خطأ:
 * الكوكي يكتبه أي أحد، وقيمةٌ مشوّهة يجب أن تُعيد الزائر إلى «اتبع نظامك» لا أن
 * تُسقط الصفحة ولا أن تفرض عليه ثيماً لم يختره.
 */
export function normalizeThemeChoice(value: string | null | undefined): ThemeChoice {
  return (THEME_CHOICES as readonly string[]).includes(value ?? "")
    ? (value as ThemeChoice)
    : "system";
}

/** اختيار الزائر من الكوكي — يستدعيها غلاف الموقع وحده */
export async function getThemeChoice(): Promise<ThemeChoice> {
  const store = await cookies();
  return normalizeThemeChoice(store.get(THEME_COOKIE)?.value);
}

/**
 * قيمة `color-scheme` المقابلة للاختيار.
 *
 * وهي **ليست تجميلاً**: أدوات المتصفح التي يرسمها بنفسه — منتقي التاريخ والساعة،
 * وقائمة `select`، وأشرطة التمرير، وأرضية الإكمال التلقائي — لا تسمع لأيٍّ من
 * الرموز السبعة عشر وتتبع هذه الخاصية وحدها (المبرر الكامل في `globals.css` §٢).
 *
 * و`"light dark"` في حالة `system` هي المفتاح الذي تعمل به `light-dark()` في
 * `globals.css`: تُعلن أن العنصر يقبل العائلتين، فيختار المتصفحُ بحسب تفضيل
 * الجهاز — وهذا هو موضع القرار كله في الحالة الافتراضية، بلا استعلام وسائط
 * مكرَّر وبلا سطر جافاسكربت.
 */
export function colorSchemeFor(choice: ThemeChoice): string {
  return choice === "system" ? "light dark" : choice;
}
