/**
 * عقد الطباعة والمشاركة والتصدير (الدفعة ٤ — الملاحظة ٦) — المرجع الأوحد.
 *
 * نصّ المالك في `docs/VISION.md` ملحق ٢ ملاحظة ٦:
 * «الطباعة والمشاركة — طباعة تفاصيل الرحلة ومشاركتها ونشرها على التواصل
 * الاجتماعي في الواجهة العامة، وطباعة التقارير وتفاصيل الرحلات وحسابات
 * المتعهدين في اللوحة.»
 *
 * ── 🔒 القرار الأول، وهو أمني بحت: ما الذي يُنشَر؟ ─────────────────────────
 *
 * **رابط صفحة الرحلة `/booking/[token]` هو بيانات الاعتماد نفسها.** الدالة
 * `get_booking_by_token` تأذن بحيازة النص وحده، وتُرجع اسم العميل وهاتفه
 * وواتسابه وإحداثيات الالتقاء والوصول وملاحظاته وسجل إيصالاته. وزرُّ «انشر على
 * فيسبوك» فوق هذه الصفحة ينشر مفتاحاً حيّاً: فاحصات المعاينة تجلب الرابط،
 * وترويسة `referer` تحمله إلى الموقع التالي، وسجلات مختصرات الروابط تحفظه.
 * والصفحة نفسها تقول للعميل «هو مفتاحك الوحيد لهذه الصفحة».
 *
 * **وحُسم مع المالك (2026-08-14):**
 *
 *   • **النشر العام** ⇒ لصفحات التسويق وحدها: المسارات والخدمات والرئيسية.
 *     وهي المبنية أصلاً لتُشارَك وتجلب زواراً، ورابطها عام مفهرَس بلا سرّ.
 *   • **صفحة الرحلة** ⇒ **طباعة** و**نسخ الرابط** و**إرساله إلى واتساب صاحبه
 *     نفسه** — نيّة خاصة موجَّهة، لا نشر عام. ولا بطاقة Open Graph لها إطلاقاً
 *     (الصفحة `noindex, nofollow, nocache` أصلاً ولا تمرّ بـ`buildPageMetadata`).
 *
 * فالملاحظة تُنفَّذ كاملة — «المشاركة» و«النشر» كلاهما موجود — لكن كلاً منهما
 * على السطح الذي يحتمله.
 *
 * ── 🔒 القرار الثاني: التصدير يقرأ ولا يحسب ───────────────────────────────
 *
 * D-05 يسري على الملف كما يسري على الشاشة: كل رقم في أي CSV **يصل محسوباً من
 * Postgres**. ولا مجموع في TypeScript ولو بدا بريئاً — فملفٌ مجموعُه يخالف
 * الشاشة أسوأ من ملفٍ لا يوجد، لأنه يُطبَع ويُرسَل ويُحتجّ به.
 *
 * ولذلك تُبنى التصديرات الأربعة على أسطح **جاهزة الشكل** لا على استعلامات
 * جديدة: `partner_statement()` تُرجع الرصيد الجاري محسوباً، و`ledger_entries`
 * و`expenses` و`bookings` صفوفٌ تُقرأ كما هي.
 *
 * ── 🔒 القرار الثالث: السقف يُعلَن ولا يُخفى ──────────────────────────────
 *
 * كل شاشة قائمة في اللوحة لها سقف صفوف (‏١٠٠ للطلبات، ٢٠٠ للدفتر والمصروفات،
 * ٥٠٠ للكشف). وملفٌ يصدّر أول مئة صف من ألف **بلا أن يقول** هو أخطر شكل من
 * أشكال الرقم الكاذب: يبدو كاملاً ويُبنى عليه قرار.
 *
 * فلكل تصدير سقفه المعلَن، **ويكتب في آخر سطر من الملف** ما إذا كان السقف قد
 * بُلغ. (والصف الأخير سطر تعليق لا بيانات، فلا يفسد قراءة الجدول.)
 */

