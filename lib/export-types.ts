/**
 * CSV عربي صحيح ليس CSV عادياً بترجمة عناوين. أربعة أشياء تُفسده صامتة:
 *
 * **(١) بلا BOM** — إكسل على ويندوز يقرأ UTF-8 على أنه ترميز محلي، فيخرج
 * العربي كله رموزاً. البادئة `﻿` تحلّها.
 *
 * **(٢) الأرقام العربية الهندية** — `formatAmount` و`toArabicDigits` في هذا
 * المستودع تُخرج `١٬٢٣٤٫٥` بفاصلة U+066C وسالب U+2212. جميلة على الشاشة،
 * و**نصٌّ لا رقم** في إكسل: لا تُجمع ولا تُرتَّب. فكل مُنسِّق في المستودع
 * **يُتجاوَز** هنا، وتُكتب الأرقام لاتينية خاماً بفاصلة عشرية `.` وسالب `-`.
 *
 * **(٣) حقن الصيغ** — خانة تبدأ بـ`=` أو `+` أو `-` أو `@` تنفّذها إكسل
 * كصيغة. وملاحظات التشغيل نصّ حرّ يكتبه بشر. فتُسبَق هذه الخانات بعلامة
 * اقتباس مفردة.
 *
 * **(٤) اسم ملف عربي** — يُكسر في ترويسة `Content-Disposition` البسيطة.
 * فيُكتب اسم لاتيني آمن، ومعه `filename*=UTF-8''…` بترميز RFC 5987 للاسم
 * العربي، فيقرأ كل متصفح ما يفهمه.
 *
 * والتواريخ: `YYYY-MM-DD HH:mm` **بتوقيت القاهرة** — الصيغة التي ترتّبها إكسل
 * صحيحاً، والمنطقة التي يحسب بها المشروع كل يوم.
 */
export const CSV_BOM = "﻿";
export const CSV_EOL = "\r\n";
export const CSV_MIME = "text/csv; charset=utf-8";

/**
 * الخانات التي تبدأ بأحدها تُسبَق باقتباس مفرد قبل الكتابة.
 *
 * ⚠ **وللقاعدة استثناء بنيوي وقعت فيه صياغةٌ أولى لهذا العقد، وأمسكه التنفيذ
 * قبل الشحن:** `-` في القائمة، فتطبيقُها حرفياً يجعل `csvEscape("-360.50")`
 * تُخرج `'-360.50` — أي أن **كل مبلغ سالب يصل إكسل نصّاً لا رقماً**، فلا
 * يُجمع ولا يُرتَّب. وعمود الرصيد في كشف حساب المتعهد سالبٌ لخمسةٍ من ستة
 * متعهدين في قاعدة بدر اليوم — أي أن الملف كان سيفقد الغرض الذي بُني له.
 *
 * فالحارس يستثني **الرقم المكتمل وحده**: خانة تطابق `/^-?\d+(\.\d+)?$/` لا
 * تُسبَق أبداً. والاستثناء **بنيوي لا احتمالي**: `-2+3+cmd|'/c calc'!A0`
 * و`-360.50x` لا تطابقان النمط فتبقيان محيَّدتين.
 */
export const CSV_FORMULA_PREFIXES = ["=", "+", "-", "@", "\t", "\r"] as const;

/** النمط الذي يُعفي خانةً من حارس الصيغ — رقم مكتمل لا يبدأ بشيء آخر */
export const CSV_NUMERIC_LITERAL = /^-?\d+(\.\d+)?$/;

