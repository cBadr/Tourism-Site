/**
 * 🔒 **الملف سطحٌ جديد، والسطح الجديد يُسأل عنه السؤال نفسه: من يقرؤه؟**
 *
 * وملفٌ يخرج من اللوحة يُرسَل بالبريد ويُفتَح على جهاز آخر ويُعاد توجيهه —
 * أي أنه **يتسرّب أسهل من شاشة محروسة بجلسة**. ولذلك تُسقَط هذه الأعمدة من
 * التصدير حتى وهي مرئية للمشرف على الشاشة:
 *
 *   • `public_token` — رابط متابعة الحجز بلا كلمة سر. ملفٌ فيه ألف توكن يسلّم
 *     ألف حجز لمن يفتحه. **وهذا أخطرها.**
 *   • `receipt_path` و`attachment_path` — مسارات دلو خاص لا تُفتح إلا برابط
 *     موقَّع؛ وجودها في ملف يغري بمحاولة الوصول ولا يفيد قارئاً.
 *   • `customer_phone` و`customer_whatsapp` في تصدير الحجوزات — التصدير
 *     للمراجعة التشغيلية والمالية، والهاتف ليس منها. (والاسم يبقى: بلا اسم لا
 *     يُعرف الحجز.)
 *
 * وما **يبقى** مقصود بالقدر نفسه: `subcontractor_cost` و`margin_amount` في
 * تصدير الحجوزات — لأن قارئه المالك وحده، وهما لبّ المراجعة المالية. ولا
 * يُصدَّر أيٌّ منهما في أي ملف قد يصل متعهداً.
 */
