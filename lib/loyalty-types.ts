/**
 * ╔══════════════════════════════════════════════════════════════════════════╗
 * ║  عقد الولاء — المرحلة ١٢ب، الشقّ الثاني (وبه تُقفل المرحلة ١٢)            ║
 * ╚══════════════════════════════════════════════════════════════════════════╝
 *
 * نقاطٌ تُكسب على الرحلات المكتملة، وتُستبدل خصماً على رحلةٍ تالية.
 *
 * كُتب هذا الملف بعد **ثلاثة تصاميم مستقلة** بزوايا متعمَّدة الاختلاف — دفترٌ لا
 * يُمحى، وأصغرُ ما يعمل، ومن المهاجم إلى الداخل — ثم توليفٍ وقياسٍ مستقلٍّ لكل
 * ادّعاءٍ حاسم على القاعدة الحيّة. وما دون ذلك من تفصيل تنفيذي يُترك للهجرة؛
 * هنا **القرارات وحدها ومبرراتها**، لأن نقضها بالسهو أغلى من كتابتها.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §١ — 🔴 العطب الذي يجب أن يُقرأ قبل أي شيء: **الأرضية لا تحتمل طبقةً ثانية**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * الاستبدال خصمٌ ثانٍ على السعر. والبديهي أن يُنادى `apply_discount` ثم تُطرح
 * النقاط من ناتجه. **وهذا يخترق أرضية الهامش** (‏**D-16**) — مقيسٌ بقراءة الجسم
 * الحيّ لا بملف الهجرة (**D-58**):
 *
 *     v_mintotal := greatest(v_cost + v_floor, coalesce(v_minprice, 0));
 *     v_max      := floor(v_total - v_mintotal);
 *
 * الأرضية تُحسب من **الإجمالي الداخل**، و`v_max` هو المساحة كلها. فطرحُ النقاط
 * بعدها ينزل بالسعر تحت `v_mintotal` — أي تحت تكلفة المتعهد زائد أدنى هامش.
 *
 * ⚠ **وأخطر ما فيه أنه لا يُمسَك بفحص**: `apply_discount` تُرجع `applied = true`
 * وقيمةً سليمةً تماماً، وكل اختبارات المرحلة ١٢أ تبقى **خضراء**، بينما
 * `bookings.total` النهائي تحت الأرضية. عطبٌ صامتٌ في المال — وهو أسوأ الأنواع.
 *
 * 🔒 **فالعلاج بنيويّ لا انتباهيّ، وهو تفويضٌ لا استنساخ (القاعدة ١٢):**
 *
 * 1. تُستخرج معادلة الأرضية إلى دالةٍ واحدة `discount_floor_room(...)` —
 *    **جسمها منقولٌ من `pg_get_functiondef` الحيّ**، لا من ملف `0024`.
 * 2. تُعاد كتابة `apply_discount` لتناديها، وحدّ تغييرها سطران.
 * 3. `redeem_points` تنادي **الدالة نفسها**، وتطرح ما أخذه الكوبون سلفاً.
 * 4. **سقفٌ واحد للطبقتين مجتمعتين** — لا سقفان يُجمعان.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٢ — موضع الاستبدال في التسعير: طبقةٌ ثالثة، بعد الكوبون وقبل الخدمات
 * ══════════════════════════════════════════════════════════════════════════
 *
 *     ride_total   (الأرضية ← معامل العودة ← الانتظار ← الذروة)   D-11
 *       − خصم الكوبون                                            apply_discount
 *       − استبدال النقاط                                          redeem_points  ★
 *       = ride_after
 *       + extras_total                                            D-54
 *       = bookings.total
 *
 * **بعد الكوبون** لأن النقاط **مالٌ يملكه العميل سلفاً**، والكوبون تنزيلٌ من
 * المنصة. فتُستهلك النقاط على ما **بقي** بعد تنزيلات المنصة — وإلا أنفق العميل
 * رصيده على مبلغٍ كان سيُحسم عنه مجاناً، أي أخذنا منه قيمةً بلا مقابل.
 *
 * **وقبل الخدمات** التزاماً بـ**D-54** المحسومة في الدفعة ٣، ولسببٍ اقتصادي:
 * الخدمة الإضافية بندٌ **تكلفته علينا** (كرسي أطفال، مرشد سياحي)، فشراؤها بنقاطٍ
 * لا تكلفة لها على العميل خسارةٌ صافية لا تنزيلُ ربح.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٣ — 🔒 مَن يملك الرصيد: **الهاتف المُثبَت، والحساب نافذةٌ عليه**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * أهم قرارٍ في الملف، وأكثر ما يُخطئ فيه التصميم البديهي («الرصيد على الحساب»).
 *
 * الرصيد يُجمَّع على `bookings.phone_norm` — العمود المولَّد المخزَّن من الدفعة ١ —
 * ويقرؤه الحساب عبر هواتفه **المُثبَتة** وحدها:
 *
 *     select distinct b.phone_norm
 *       from customer_bookings cb join bookings b on b.id = cb.booking_id
 *      where cb.profile_id = auth.uid()
 *        and cb.link_source = 'reference'     ← إثباتُ ملكية لا حيازة
 *
 * وهذا يُسقط أربعة أخطارٍ **بالبناء لا بسياسةٍ تُكتب**:
 *
 * | ما يسقط | كيف |
 * |---|---|
 * | وراثة النقاط برابطٍ مُعاد إرساله | الربط بالتوكن **لا يفتح رصيداً**: يرى الرحلة ولا يمسّ نقاطها (‏`customer-types.ts` §٥) |
 * | مزرعة الحسابات والإحالة الذاتية | عشرة حسابات على هاتفٍ واحد ترى **الرصيد نفسه** لا عشرة أرصدة — فالمزرعة بلا عائد |
 * | ثغرة `handle_new_user` (‏§٢ هناك) | **لا تدخل المسار أصلاً**: الهاتف من `bookings` لا من `profiles.phone`، ولا يُقرأ الأخير في سطرٍ واحد هنا |
 * | تبعية مزوّد الرسائل | الإثبات مبنيٌّ سلفاً: `find_booking_by_reference` بخانق ٨/ربع ساعة وبمسار «لا نتيجة» لا يرمي (**D-48**) |
 *
 * ومكسبٌ عملي: ربطٌ واحد مُثبَت يفتح رصيد **كل** حجوزات ذلك الهاتف — فصاحب
 * عشرين رحلة لا يحتاج عشرين نداءً على خانقٍ سعته ثمانية.
 *
 * ⚠ **وهذا المكسب نفسه هو ما جعل الثغرة حرجة**: أمسكت مراجعةُ هذه الدفعة أن
 * `get_booking_by_token` كانت تُخرج المرجع والهاتف معاً إلى `anon`، فينال حاملُ
 * رابطٍ مُعاد إرساله `link_source = 'reference'` بنداءٍ واحد — أي **رصيد الهاتف
 * كله** لا رحلةً واحدة. أُغلقت في `0049` بتقنيع الحقلين، والتفصيل في
 * `customer-types.ts` §٥.
 *
 * 📌 **والقاعدة المستخلصة تحكم كل ما يُبنى بعدها**: هذا العقد يقف على أن
 * `'reference'` إثباتٌ حقيقي — فأيُّ سطحٍ جديد يُخرج هاتف عميلٍ بجوار مرجعه
 * **ينقض الولاء كله من حيث لا يمسّ سطراً منه**. تُفحص هذه العلاقة عند كل توسيع
 * لحمولةٍ عامة، لا عند تعديل الولاء وحده.
 *
 * ⚠ **وثمنه يُكتب لا يُخفى**: من غيّر رقمه فقد رصيده القديم حتى يربط حجزاً بالرقم
 * القديم. وهو ثمنٌ مقبول لأن البديل — الرصيد على الحساب — يفتح المزرعة والوراثة
 * معاً؛ ومسار الدعم اليدوي يبقى ممكناً بدمجٍ يُسجَّل في الدفتر كأي حركة.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٤ — 🔒 النقطة تُسكّ على **الحجز** لا على الحساب
 * ══════════════════════════════════════════════════════════════════════════
 *
 * سجلّ الكسب مفتاحه `booking_id` **فريداً** بفهرس فريد جزئي:
 *
 *     unique (booking_id) where direction = 'earn' and reverses_entry_id is null
 *
 * رحلةٌ واحدة ⇒ صفُّ كسبٍ واحد، مهما تعدّدت الحسابات التي ربطتها ومهما أُعيد
 * الربط. والحجز هو الكيان الصحيح لأنه وحده يملك حالةً، وإجمالاً مجمَّداً،
 * ومُشغّلَ اكتمالٍ قائماً — فالكسب **مُشغّلٌ على انتقال الاكتمال**، لا دالةَ تطبيق
 * يناديها الكود ولا مهمةً مجدولة تمرّ على الماضي.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٥ — دفترٌ مُلحَق بلا عمود رصيد، وصفٌّ واحد يُقفَل
 * ══════════════════════════════════════════════════════════════════════════
 *
 * `loyalty_entries` مرآةُ `ledger_entries` بنيةً وانضباطاً: لا `update` ولا
 * `delete`، والتصحيح **قيدٌ عاكس** يشير إلى أصله (`reverses_entry_id`) — فتاريخ
 * الرصيد قابلٌ للتفسير بعد سنة، وهو ما يفرّق نظام ولاءٍ عن عدّاد.
 *
 * ومعه `loyalty_accounts(phone_norm)` بعمود رصيدٍ مادّي — **لا نقضاً للدفتر بل
 * صفّاً قابلاً للقفل** (`select … for update`): الاستبدال يقرأ ويكتب في معاملةٍ
 * واحدة، والقفل يجعل الإنفاق المزدوج المتزامن مستحيلاً بدل أن يكون نادراً.
 * والرصيد المادّي **مشتقٌّ يُطابَق دورياً** بمجموع الدفتر، وأي فرقٍ عطبٌ يُرفع.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  §٦ — ما لا يُبنى في هذه الدفعة، بسببٍ مكتوب
 * ══════════════════════════════════════════════════════════════════════════
 *
 * - **لا انتهاء صلاحية للنقاط.** التزامٌ مالي مفتوح، نعم — لكن الانتهاء يحتاج
 *   إخطاراً قبل موعده، ولا قناة تبلغ العميل اليوم (‏`RESEND_API_KEY` بندٌ مفتوح).
 *   ونظام يُسقط نقاطاً بلا إنذار يُفقد الثقة أكثر مما يوفّر.
 * - **لا نقل بين الحسابات ولا إهداء.** كل نقلٍ طريقُ غسلٍ للنقاط المسكوكة.
 * - **لا كسب على الخدمات الإضافية** — تكلفتها علينا (‏§٢).
 * - **لا كوبون ونقاط على حجزٍ واحد** إن ضاقت المساحة عنهما: السقف واحد (‏§١)،
 *   والأولوية للكوبون لأنه معلَنٌ قبل الحجز.
 */

/** إعدادات الولاء — صفٌّ واحد، على شكل `discount_settings` حرفياً */
export type LoyaltySettings = {
  /**
   * ⚠ **`false` في البذرة**، كنظام الخصومات: لا نظام ولاء يبدأ بلا قرار بشري.
   * ونظامٌ مطفأ يعني «لا نقاط تُسكّ ولا تُستبدل» — لا «تُسكّ ولا تظهر».
   */
  enabled: boolean;
  /** كم نقطة لكل جنيه من `ride_total` بعد الخصم وقبل الخدمات */
  pointsPerCurrency: number;
  /** قيمة النقطة الواحدة بالجنيه عند الاستبدال */
  currencyPerPoint: number;
  /** أقل رصيد يُسمح باستبداله — يمنع حركاتٍ بقروش لا معنى لها */
  minRedeemPoints: number;
  /** أقصى نسبة من `ride_after` تُدفع بالنقاط — والسقف الحقيقي أرضيةُ §١ */
  maxRedeemPercent: number;
};

/** اتجاه الحركة في الدفتر */
export type LoyaltyDirection = "earn" | "redeem" | "reverse" | "adjust";

/** حركة واحدة كما يراها المالك في اللوحة */
export type LoyaltyEntryView = {
  id: string;
  direction: LoyaltyDirection;
  /** موجبٌ للكسب، سالبٌ للاستبدال — والإشارة في القيمة لا في حقلٍ ثانٍ */
  points: number;
  bookingReference: string | null;
  occurredAt: string;
  note: string | null;
};

/**
 * رصيد العميل كما يراه صاحبه في «حجوزاتي».
 *
 * 🔒 ولا `phoneNorm` فيه: الرصيد يُجمَّع عليه في القاعدة، ولا حاجة بالعميل إلى
 * رؤية شكل تطبيعنا لرقمه — وإخراجه يجعل نافذةً على الهوية بلا داعٍ.
 */
export type MyLoyaltyView = {
  points: number;
  /** ما تساويه بالجنيه اليوم — تُحسب في القاعدة (**D-05**) ولا تُضرب في الواجهة */
  worth: number;
  currency: string;
  /**
   * `null` حين لا رصيد **مُثبَت** — والفرق عن صفرٍ مقصود: الأول «لم تربط حجزاً
   * بإثبات بعد» ويُعرض بدعوةٍ للربط، والثاني «رصيدك صفر» ويُعرض كما هو (‏§٣).
   */
  provenPhones: number | null;
};

