/**
 * **القرار (م‑١٠):** مرساة البند **معرّفٌ ثابت مستقل عن نصّه**، بمصدرين
 * مرتّبين لا ثالث لهما:
 *
 *   ١) `content.anchor` إن كان موجوداً ويطابق `ANCHOR_PATTERN` — يكتبه المالك
 *      مرةً (`cancellation`) فيصير الرابط مقروءاً: `/terms#cancellation`.
 *   ٢) وإلا **معرّف الصفّ نفسه**: `c-<sections.id>` — موجودٌ دائماً، تسكّه
 *      القاعدة، ولا يشتقّ من حرفٍ واحد من المحتوى.
 *
 * فلا يوجد بندٌ بلا مرساة إطلاقاً، ولا مرساةَ تتغيّر بتحرير نصّ.
 *
 * **🔴 الطريق الذي لم يُؤخذ، وعاقبته حرفياً:** أن تُشتقّ المرساة من العنوان
 * العربي (‏`slugify(title)`). وهو أجمل ما يمكن كتابته وأخطر ما يمكن شحنه:
 *
 *   • **تصحيحُ خطأٍ إملائي في العنوان يبطل كل رابطٍ أُرسل.** والمالك يصحّح
 *     العناوين — هذا عملُه. فتصير قاعدة الاستعمال: «لا تلمس العنوان بعد أن
 *     ترسل الرابط»، وهي قاعدةٌ لا يعلمها أحد ولا تقولها أي شاشة.
 *   • **والكسر صامتٌ تماماً**: `#الإلغاء` الذي لم يعد موجوداً لا يُخرج ٤٠٤ ولا
 *     خطأً — المتصفح يفتح الصفحة من أولها. فالعميل الذي أُرسل له «§٤» يقرأ
 *     المقدمة ويظن أن البند غير موجود، **ولا سطر في أي سجل**. وهو النمط ٣ في
 *     `LESSONS.md` بعينه.
 *   • **وينكسر مرةً ثانية باللغة**: العنوان المشتقّ يختلف بين `/terms` و
 *     `/en/terms`، فالرابط الواحد لا يصلح للغتين — بينما المعرّف اللاتيني
 *     الثابت يصلح لهما معاً لأنه **خارج فهرس الترجمة** (§١).
 *
 * **وثمن الطريق المأخوذ، مكتوباً بلا تجميل:** مرساةٌ لم يكتبها المالك تكون
 * `c-<uuid>` — رابطٌ طويلٌ قبيح. وهو ثمنٌ مقبول لأنه **يُنسخ ولا يُكتب** (زرّ
 * الرابط بجوار كل بند)، ولأن علاجه بيد المالك في حقلٍ واحد. وثمنٌ ثانٍ أصغر:
 * كتلةٌ أُنشئت في المسودة قد تكتسب معرّفاً نهائياً عند أول نشر، فالمرساة
 * الافتراضية تستقرّ بعد النشرة الأولى — ولذلك يقول نصّ المساعدة في اللوحة:
 * **اكتب مرساةً بيدك قبل أن ترسل الرابط.**
 */
export const ANCHOR_PATTERN = /^[a-z][a-z0-9-]{0,39}$/;

/** بادئة المرساة الافتراضية — مصدرٌ واحد تقرؤه العارضة والفهرس معاً */
export const ANCHOR_FALLBACK_PREFIX = "c-" as const;

/**
 * مرساة البند كما تُصيَّر فعلاً. **تُنادى من العارضة ومن الفهرس معاً** فلا
 * يختلف ما يُكتب في `id` عمّا يُكتب في رابط الفهرس (نفس مبرر `blockRenders`
 * في العقد §١٣: حكمُ الشاشة هو حكمُ الصفحة).
 */
export function resolveAnchor(sectionId: string, raw: unknown): string {
  return typeof raw === "string" && ANCHOR_PATTERN.test(raw)
    ? raw
    : `${ANCHOR_FALLBACK_PREFIX}${sectionId}`;
}

/**
 * هل يجوز أن يحمل هذا القسم هذا الحقل غير النصّي؟ — تُنادى في الحفظ وفي
 * المعاينة معاً، فلا يختلف حكم الشاشة عن حكم الصفحة (نفس مبرر `blockRenders`
 * في العقد §١٣).
 */
export function blockDeclaresNonText(
  decl: NonTextFieldDecl,
  field: string,
  level: "block" | "item"
): boolean {
  const list = level === "item" ? decl.nonTextItemFields : decl.nonTextFields;
  return list !== null && (list as readonly string[]).includes(field);
}

