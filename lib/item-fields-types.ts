/**
 * عقد الحقول غير النصّية داخل الكتل (م‑٧) — المرجع الأوحد لصور العناصر
 * وأيقوناتها. يُقرأ **قبل** أول سطر SQL وقبل أول مكوّن.
 *
 * يُقرأ معه ولا يُغني عنه: `lib/page-builder-types.ts` (§٤ العنونة · §٥ `style` ·
 * §٦ الكتالوج · §١٠ البلاغة الكاملة) · `lib/content-types.ts` ·
 * `supabase/migrations/0059_i18n_stable_item_keys.sql` (طبقة العنونة الحيّة) ·
 * **D-24** و**D-48** و**D-58**، والقاعدتان الذهبيتان **١٢** (فوِّض ولا تستنسخ)
 * و**١٩** (احكم بالنداء الحيّ لا بمطابقة النصّ).
 *
 * ── لماذا وُجد هذا الملف ────────────────────────────────────────────────────
 *
 * التصميم يعطي كل بطاقة مسار صورةً وكل ضمانةٍ أيقونة، والقيد غير القابل
 * للتفاوض يقول إن كل ما يُرى يُحرَّر من اللوحة. والعقد القائم يمنع الاثنين:
 * صورةُ العنصر تحتاج مفتاحاً غير نصّي **داخل عنصر قائمة**، وقد بقي مغلقاً في
 * م‑٢ بمبرر مكتوب («‏`src` داخل عنصر قائمة شكلٌ لم يُقنَّن في العقد»).
 *
 * وهذا الملف يفتحه — لا بنقض المبرر بل بتقنين الشكل.
 *
 * ── ما قِيس فعلاً على القاعدة الحيّة (2026-08-16، داخل معاملة `read only`
 *    انتهت بـ`rollback`) ────────────────────────────────────────────────────
 *
 * ١) 🔴 **المقدّمة التي بُني عليها القرار السابق غير صحيحة، والقياس يهدمها.**
 *    `NON_TEXT_CONTENT_FIELDS` **لا يقرؤه فهرس الترجمة إطلاقاً**. مستهلكه
 *    الوحيد في القاعدة هو `block_registry_check` بصيغة
 *    `v_non_text constant text[] := array['src']`، ووظيفته هناك سطرٌ واحد:
 *    السماح بأن يُذكر `src` في `required_fields` وهو ليس في `text_fields`.
 *    **ولا أثر له على ما يدخل الفهرس ولا على ما يخرج منه.**
 *
 * ٢) **الفهرس يتجاوز بالاسم، وبقائمة من عنصرين اثنين، على المستويين معاً.**
 *    المقيس من `pg_get_functiondef`: `i18n_corpus_rows` و`i18n_apply` كلتاهما
 *    تنادي `public.i18n_reserved_content_key(key)` **مرتين**: مرةً على مفتاح
 *    المستوى الأعلى (`e.key`) ومرةً على مفتاح حقلٍ داخل العنصر (`ie.key`).
 *    وجسم الدالة المنادَاة بحرفه:
 *
 *        select p_key is not null and p_key in ('_k', 'style')
 *
 *    ⇒ **آليةُ التجاوز على مستوى العنصر قائمةٌ وموصولة سلفاً**، وينقصها
 *    الأسماء وحدها. وهذا يقلب المرحلة كلها: لا تحتاج جراحةً في دالتين
 *    كبيرتين، بل **قائمةَ أسماء في ورقةٍ طرفية**.
 *
 * ٣) 🔴 **والتسميم الذي خشيناه على مستوى العنصر واقعٌ اليوم على المستوى
 *    الأعلى.** ثلاثة صفوف حيّة في الفهرس الآن، مقروءةً بأعيانها:
 *
 *        <heroId>.src     ⇐ "/img/hero-chauffeur.avif"
 *        <heroId>.poster  ⇐ "/img/hero-video-poster.avif"
 *        <heroId>.video   ⇐ "/video/hero-loop.mp4"
 *
 *    كتبتها `0064` بحسن نيّة: `text_fields` لا تذكرها، لكن الفهرس **لا يقرأ
 *    `block_registry` أصلاً** — يقرأ كل مفتاحٍ قيمتُه نصّ. والأسوأ أن
 *    `i18n_apply` تستبدل بالاسم كذلك، فترجمةُ `src` **تُطبَّق فعلاً**؛
 *    و`safeMediaSrc` لا تنقذ: «‎/img/سائق.avif» مسارٌ داخلي سليم يمرّ من
 *    الحارس ويُصيَّر صورةً مكسورة.
 *
 * ٤) **وهذه أرخص لحظة ممكنة للإصلاح:** `select count(*) from translations`
 *    = **صفر**. فلا مفتاحٍ منشور يُسحَب، ولا ترجمةَ إنسانٍ تُسقَط — وهو
 *    بالضبط الثمن الذي يحذّر منه العقد §١ («المفتاح الذي نُشر لا يُسحب»).
 *    وتأجيلُ هذا الإصلاح إلى ما بعد أول ترجمة يضاعف كلفته.
 *
 * ٥) **حالة الفهرس الآن — الأساس الذي يُقاس عليه الإغلاق (§٧):**
 *    الإجمالي **٦٤٢** صفاً · `section` **٥٥٣** (منها **٣١٤** بصيغة
 *    `items.<_k>.<field>` و**٢٣٩** بصيغة `<sectionId>.<field>`) · `page` ٦٩ ·
 *    `vehicle` ٨ · `service` ٦ · `settings` ٦.
 *    و`block_registry` **١٥** صفاً في **٩** أعمدة، و`sections` **١٣٥** صفاً.
 */

