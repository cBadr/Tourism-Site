/**
 * **القرار:** يُضاف عمودان `text[]` يقابلان القائمتين النصّيتين تقابلاً تاماً:
 *
 *     text_fields       ⇄ non_text_fields        (المستوى الأعلى)
 *     item_fields       ⇄ non_text_item_fields   (داخل عنصر `items`)
 *
 * والأربع **متقاطعةٌ صفراً**: الاسم إمّا نثرٌ يُترجَم وإمّا لا، ولا ثالث.
 * و`null` في العمودين الجديدين تعني «لا حقل غير نصّي» (لا `{}` — الغياب يعني
 * الافتراضي كما في العقد §٥ والقاعدة الذهبية ١٥).
 *
 * **ولماذا عمودان لا واحد؟** لأن الفرق بين المستويين هو الفرق بين عنوانَي
 * ترجمةٍ مختلفين في العقد §٤، وقد أثبت `0064` أن دمجهما ذهنياً هو ما أدخل
 * `poster` و`video` الفهرس: كُتبا حقلين عُليين بلا قائمةٍ تصفهما، فلم يرَهما
 * حارسٌ واحد.
 *
 * **ووظيفة العمودين — وهذا هو محور القرار:** ليست ترشيح الفهرس (ذاك بالاسم،
 * §١)، بل ثلاثة أشياء لا يقدر عليها الاسم وحده:
 *
 *   ١) **المحرر**: أي عنصر واجهة يُعرض لهذا الحقل — منتقي وسائط أم قائمة
 *      أيقونات أم صندوق نصّ. والمقيس اليوم أن المنشئ يكتشف الحقول غير النصّية
 *      **من `requiredFields`** (‏`components/admin/page-builder/block-fields.tsx:66-70`)
 *      ⇒ **حقلٌ غير نصّي اختياري لا يظهر له إدخالٌ أصلاً**، وهو سبب أن وسائط
 *      البطل (‏`poster`/`video`) غير قابلة للتحرير من المنشئ اليوم رغم وجودها
 *      في القاعدة. العمودان يُنهيان هذا الاكتشاف بالاستنتاج.
 *   ٢) **التحقق**: `required_fields` يصير مقروءاً على اتحاد القوائم الأربع
 *      بدل حيلة `v_non_text` — فيسقط العيب القائم الذي يسمح لكتلةٍ **بلا حقل
 *      `src` إطلاقاً** أن تعلنه إلزامياً.
 *   ٣) **التعاقد**: الكتلة تصف نفسها كاملةً في صفٍّ واحد، فلا يبقى حقلٌ حيّ
 *      لا يذكره السجل (وهي حالة `hero.src` اليوم بالضبط).
 *
 * 🔒 **والتعاشق الذي يجعل الانحراف غير قابل للكتابة:**
 * `block_registry_check` يرفض أي اسمٍ في العمودين الجديدين ليس في
 * `NON_TEXT_FIELD_NAMES`. فلا يستطيع كاتب كتلةٍ أن يعلن حقلاً «غير نصّي»
 * والفهرس ما زال يفهرسه — ولا العكس. الاتفاق **بالبناء** لا بالانضباط، وهو
 * نفس مذهب العقد §٦: «الشكل غير القانوني لا يُكتب».
 *
 * **عاقبة النقض (ترك العمودين وإبقاء الاكتشاف من `required_fields`):**
 * كل حقل صورةٍ اختياري في أي كتلة يبقى بلا محرر — أي أن الصور تصير قابلة
 * للتحرير من محرر SQL وحده، وهو نقضٌ حرفي للقيد غير القابل للتفاوض.
 */
export type NonTextFieldDecl = {
  /** حقول عليا غير نصّية — `null` = لا شيء */
  nonTextFields: readonly NonTextFieldName[] | null;
  /** حقول غير نصّية داخل العنصر — `null` = لا شيء، ويلزمها `itemFields` */
  nonTextItemFields: readonly NonTextFieldName[] | null;
};

