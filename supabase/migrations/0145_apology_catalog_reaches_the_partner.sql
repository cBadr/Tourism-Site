-- 0145 — كتالوجُ الاعتذار يصل المتعهد: `portal_apology_reasons()`
--
-- ══════════════════════════════════════════════════════════════════════════
--  العيب — حقٌّ وقّع عليه المتعهد ولا سبيل إليه
-- ══════════════════════════════════════════════════════════════════════════
--
-- البند ٥ من اتفاقية المتعهدين (‏`0113`، الإصدار ١، وقَبِله حمزة الغمري في
-- 2026-08-18) يمنح المتعهد الانسحابَ عن رحلةٍ قَبِلها بإبلاغ المنصة مع بيان
-- السبب. و`withdraw_from_trip` (‏`0119`/`0121`) تنفّذ ذلك وتنجح بنداءٍ مباشر.
--
-- **والحلقةُ المقطوعة كانت الكتالوج لا الفعل:** سياساتُ `SELECT` على
-- `failure_reasons` كلُّها `is_admin()` وحدها، و`loadApologyOptions` تقرأ
-- الجدولَ **بجلسة المتعهد** ⇒ صفرُ صفوف ⇒ `apology.ready = false` ⇒ زرُّ
-- «اعتذر عن الرحلة» **لا يُرسم أبداً**. فمن اضطُرّ للانسحاب يترك الرحلة تفشل
-- في موعدها — **وهو المسارُ الذي يُخصم فيه** (‏`mark_booking_failed`) بدل
-- المسار الذي لا يُخصم فيه اليوم.
--
-- ⇒ العلاجُ **دالةُ قراءةٍ `security definer`** لا فتحُ RLS على الجدول.
--   والفرقُ جوهريّ: الجدول يحمل `default_action` و`default_deduct_amount`
--   و`applies_to` و`initiator` — تصنيفٌ تشغيليٌّ للإدارة، والمتعهدُ لا شأن له
--   إلا بما يخصّ **اعتذاره هو**. وهذا تطبيقُ اتفاقية ٧: «الأمان بنيويّ لا
--   انضباطيّ — ما لا يوجد في نوع الإرجاع لا يُسرَّب بخطأ في الواجهة».
--
-- ══════════════════════════════════════════════════════════════════════════
--  ماذا يخرج وماذا يُحجَب — وكلُّ حقلٍ بمبرّره
-- ══════════════════════════════════════════════════════════════════════════
--
--   الحقل                    | القرار | المبرر
--   -------------------------|--------|-------------------------------------
--   `slug`                   | يخرج   | مفتاحُ الاختيار الذي تعيده الشاشة إلى
--                            |        | `withdraw_from_trip` — بلا وسيطٍ آخر
--   `label`                  | يخرج   | ما يقرؤه إنسان، وهو نصُّ الكتالوج نفسه
--   `may_deduct`             | يخرج   | 🔴 انظر أدناه — التزامٌ تعاقدي
--   `default_deduct_amount`  | يُحجَب  | مبلغٌ **مقترح** يُسقَّف بمستحق الرحلة
--                            |        | ولا يُنفَّذ إلا بقرارٍ إداريٍّ بمبرَّرٍ
--                            |        | مكتوب (‏`0130`). وعرضُه رقماً يَعِد بما
--                            |        | لا تنفّذه القاعدة (النمط ٢ في LESSONS)،
--                            |        | وهو `null` في كل صفوف المالك اليوم.
--   `applies_to`/`initiator` | يُحجَب  | تصنيفُ الكتالوج الداخلي — الدالةُ تصفّي
--                            |        | به سلفاً، فإخراجُه يكشف بنيةَ التصنيف
--                            |        | (ومنها وجودُ أسبابٍ تخصّ المنصة) بلا فائدة
--   `id`                     | يُحجَب  | مفتاحٌ داخلي؛ `slug` هو الواجهة
--   `active`                 | يُحجَب  | المعطَّل لا يوجد أصلاً في هذه النتيجة
--   `created_at`/`updated_at`| يُحجَب  | زمنُ إدارةٍ لا يخصّ المتعهد
--
-- ── 🔴 ولماذا `may_deduct` يخرج، ونصُّ الشاشة كان يحجبه بقصد ───────────────
--
-- ترويسةُ `app/portal/requests/data.ts` كانت تحجب الإجراءَ المالي بحجّةٍ
-- صحيحةٍ في نفسها: «من يرى (هذا السبب إجراؤه خصم) يختار الأرخص لا الأصدق».
-- **لكن البند ٥ يقول نصّاً**: «ولكل سبب أثرٌ مالي **معلوم مسبقاً**: لا شيء،
-- أو أداءُ المستحق كاملاً، أو خصم» — ويُفصح في السطر التالي عن أحدها بعينه
-- («والانسحاب لظرف قاهر … لا يترتب عليه خصم»). فالإفصاحُ **التزامٌ وقّع عليه
-- الطرفان**، لا خياراً تصميمياً. واختيارٌ أعمى بين سببٍ بثمنٍ وسببٍ بلا ثمن
-- ليس اختياراً.
--
-- والتوفيقُ بين الالتزام والحجّة على ثلاث درجات:
--   (١) يخرج **الاتجاه** (‏«قد يترتب عليه خصم») **ولا يخرج المبلغ** — فما
--       يمنع الكذبَ في السبب هو خفاءُ الفارق الكمّي، لا خفاءُ وجود أثرٍ أصلاً.
--   (٢) و`may_deduct` **مشتقٌّ من الحالة الحيّة** لا من الكتالوج وحده:
--       `default_action = 'deduct'` **و** `apology_deduction_enabled` من
--       `trip_closure_config()` — وهو المفتاح الذي تفحصه
--       `apply_withdrawal_deduction` نفسها قبل أن تخصم. فما دام المفتاح مطفأً
--       (وهو مطفأٌ اليوم) فلا سببَ يُخصم عليه، و`may_deduct` **false للجميع**
--       بحقّ. ⇒ لا رقمان لقاعدةٍ واحدة (النمط ٨)، ولا تحذيرٌ من عقوبةٍ لا تقع.
--   (٣) وما يقيّد اللعبَ بالسبب باقٍ كما هو: الخصمُ قرارُ إنسانٍ بمبرَّرٍ
--       مكتوب، وسقفُه مستحقُّ الرحلة، وله بابُ تظلّم، و«الانسحابُ المتكرر بلا
--       سببٍ مقبول» إخلالٌ جسيم في البند ١٥.
--
-- ══════════════════════════════════════════════════════════════════════════
--  ⚠ تعارضٌ مقيسٌ بين نصّ البند ٥ وكتالوج القاعدة — **لا يُعالَج هنا**
-- ══════════════════════════════════════════════════════════════════════════
--
-- البند يعدّ ستةَ أسباب، ولا تقبل `withdraw_from_trip` من المتعهد إلا اثنين
-- منها (‏`vehicle-breakdown` و`force-majeure`). وثلاثةُ أسبابٍ يقبلها الكودُ
-- **لا يذكرها البند** — ومنها **السببان الوحيدان اللذان يُخصم عليهما**
-- (`partner-double-booking` و`partner-no-reason`). والجدولُ الكامل في تقرير
-- الجلسة وفي ترويسة القسم (ع) من `completion_apology_tests.sql`.
--
-- 🔒 **ولا يُلمس نصُّ الاتفاقية هنا**: نصُّها قرارُ بدر، ونشرُ إصدارٍ ثانٍ
--    يُلزم حمزةَ بإعادة القبول ويوقف عنه العروض حتى يقبل (البند ١٦). فالقرار
--    له وحده، والقياسُ مسجَّلٌ ينتظره.
-- ============================================================================

create or replace function public.portal_apology_reasons()
returns table(
  slug       text,
  label      text,
  may_deduct boolean
)
language sql
stable
security definer
set search_path = ''
as $function$
  select r.slug,
         r.label,
         -- الاتجاه لا المبلغ، ومن الحالة الحيّة لا من الكتالوج وحده: المفتاح
         -- المطفأ يعني أن `apply_withdrawal_deduction` ترفض كل خصمٍ اعتذار.
         (r.default_action = 'deduct' and c.apology_deduction_enabled) as may_deduct
  from public.failure_reasons r
  cross join public.trip_closure_config() c
  -- 🔒 الحارس في الجسم (D-20): `authenticated` ليست متعهداً بحكم الدور
  where public.current_subcontractor_id() is not null
    and r.active
    -- ومرآةُ ما تفرضه `withdraw_from_trip` حرفاً بحرف — فلا يُعرض خيارٌ تردّه
    -- القاعدة عند الضغط (النمط ٢ في LESSONS)
    and r.applies_to in ('apology', 'both')
    and r.initiator <> 'platform'
  order by r.sort, r.slug;
$function$;

comment on function public.portal_apology_reasons() is
  'أسبابُ الاعتذار كما يراها المتعهد: slug وlabel واتجاهُ الأثر المالي (may_deduct) مشتقاً من مفتاح اللوحة الحيّ — بلا مبلغٍ ولا تصنيفٍ داخلي. تُغني عن فتح RLS على failure_reasons، وحارسُها current_subcontractor_id() في الجسم لا في السياسة.';

-- (القاعدة ١٦) — `revoke` صريح ثم أضيق منحة
revoke all on function public.portal_apology_reasons() from public, anon;
grant execute on function public.portal_apology_reasons() to authenticated, service_role;
