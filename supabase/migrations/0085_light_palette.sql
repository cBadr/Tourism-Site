-- 0085 — لوحة الثيم الفاتح تُبذَر في `site_settings` (م‑٩)
--
-- ── ما تفعله، ولا تفعل غيره ────────────────────────────────────────────────
--
-- تضيف مفتاحاً واحداً إلى صفّ `brand`: ‏`colorsLight` — سبعة عشر لوناً بنفس
-- مفاتيح `colors` حرفاً، بقيمٍ مضبوطةٍ للأرضية الفاتحة. **ولا تلمس `colors`
-- ولا `name` ولا `tagline` ولا `logoUrl`**.
--
-- ── لماذا لوحةٌ ثانيةٌ كاملة ولا يكفي «اقلب العائلة» ────────────────────────
--
-- لأن الطبقة الدلالية كانت تعرف كيف تنقلب منذ `0063`: كتلة `.dark` تسند الرموز
-- إلى عائلة `ink*` و`:root` إلى `sand*`. أي أن **الوضع الفاتح كان قائماً
-- وشغّالاً** — عليه تعمل `/admin` و`/portal` اليوم. فالناقص لم يكن آليةً بل
-- **قيماً**: ألوان الإشارة في اللوحة الواحدة اختيرت لتُقرأ فوق الحبر، ومقياسها
-- فوق الرمل يقول الباقي:
--
--     كهرمان التصميم  #D89A3E  فوق  #F4F0E7  =  2.14 : 1     (الحد 4.5)
--     نيل التصميم     #2E9184  فوق  #F4F0E7  =  3.36 : 1
--     خطر التصميم     #D64545  فوق  #F4F0E7  =  3.85 : 1
--
-- وثلاثتها مكتوبةٌ نصّاً في المستودع (`text-primary` في `components/site/
-- services.tsx` مثالاً)، فكانت ستصير غير مقروءة لحظة انقلاب الأرضية. ولا
-- يُصلَح ذلك بشفافيةٍ ولا بوزن خطّ — يُصلَح بقيمةٍ أخرى، وهذا هو المفتاح.
--
-- ── و🔴 ثلاثة مفاتيح تنقض نظيرها عمداً، وسبب كلٍّ منها في النتيجة لا في الذوق ─
--
--   primaryForeground : #1A1206 (داكن) → #FFF8EC (فاتح)
--       سلسلة: كهرمان الفاتح أُعمِق حتى يُقرأ نصّاً فوق الرمل، فصار أرضيةً
--       داكنة، فلزمه نصٌّ فاتح. المقيس بعده: 5.60:1.
--
--   primaryHi : أفتح من primary → **أغمق** منه
--       دورُه واحد (تمرير وتركيز)، وبلوغه على الداكن بالإضاءة وعلى الفاتح
--       بالإعتام. و#EDB45B فوق الرمل = 1.64:1 — أي أن نقل الاتجاه كما هو كان
--       يُلغي أثر التمرير بصرياً.
--
--   accentSoft : #1B4A45 (نيل داكن) → #D6E9E5 (تِنت فاتح)
--       دورُه «أرضية شارةٍ من لون المعلومة»، وشارةٌ داكنة وسط صفحةٍ فاتحة بقعةٌ
--       لا شارة. ونصّ الشارة فوق التِنت = 5.04:1.
--
-- ⚠ ورتب `ink*` هنا **مرفوعةٌ درجةً** عن رتب اللوحة الداكنة (#12201D مقابل
-- #08100F): الحبر شبه الأسود جميلٌ حين يملأ الشاشة، وثقبٌ أسود حين يكون شريط
-- دعوةٍ وسط صفحةٍ فاتحة. والنص فوقه ما زال 15.01:1 — فالتلطيف لم يُشترَ بقراءة.
--
-- ── وشرط عدم الاستبدال: نفس قاعدة `0061` و`0063` ────────────────────────────
--
-- `not (value ? 'colorsLight')` — الهجرة تبذر **مرّةً واحدة**. فإن كان المالك
-- قد ضبط لوحته الفاتحة من `/admin/settings` فإعادةُ تنفيذ الملف لا تمحوها.
-- ============================================================================

update public.site_settings
set value = jsonb_set(
  value,
  '{colorsLight}',
  '{
     "primary":            "#8A5A14",
     "primaryForeground":  "#FFF8EC",
     "primaryHi":          "#6E4610",
     "accent":             "#136B60",
     "accentSoft":         "#D6E9E5",
     "ink":                "#12201D",
     "ink1":               "#1A2B27",
     "ink2":               "#213531",
     "inkLine":            "#31453F",
     "sand":               "#F5F1E8",
     "sand2":              "#FFFFFF",
     "sandLine":           "#DED5C3",
     "onInk":              "#F4F2EC",
     "onInkMut":           "#AFC0BA",
     "onSand":             "#161F1C",
     "onSandMut":          "#4E5C57",
     "danger":             "#B32218"
   }'::jsonb,
  true
)
where key = 'brand'
  and not (value ? 'colorsLight');

