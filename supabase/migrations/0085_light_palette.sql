insert into public.site_settings (key, value)
select 'brand', '{"colorsLight": {
     "primary":"#8A5A14","primaryForeground":"#FFF8EC","primaryHi":"#6E4610",
     "accent":"#136B60","accentSoft":"#D6E9E5",
