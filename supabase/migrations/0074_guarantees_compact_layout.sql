-- ============================================================================
-- 0074 — «ست ضمانات مكتوبة» تصير صفوفاً مضغوطة: ‏١٦٥٧ ⇐ ‏٩٠٥ بكسل على الجوال،
--        و**ستُّ الضمانات تبقى مقروءةً كلها** بدل أن تُخبَّأ خلف سحبة
--
-- ── الطلب، والجواب الذي يخالفه في الوسيلة لا في الغاية ─────────────────────
--
-- بدر، بعد أن رأى السكة تعمل في الأسطول والمسارات والخدمات:
-- «تمام، نقدر نعمل نفس الطلب على (ست ضمانات مكتوبة) و هي نفس الشكوى.»
--
-- والشكوى نفسها فعلاً — الارتفاع. **أما الوسيلة فلا تنتقل، والقياس هو الحجّة:**
--
--   | الشكل | الارتفاع عند ٣٧٥ | كم ضمانةً تُرى بلا حركة؟ |
--   |---|---|---|
--   | بطاقات (القائم) | ١٦٥٧ بكسل | واحدة تقريباً لكل شاشة — خمس شاشات تمرير |
--   | **سكة أفقية**   | **٦٢٥ بكسل** | **واحدة**، وخمسٌ خلف سحبةٍ أفقية |
--   | **صفوف مضغوطة** | **٩٠٥ بكسل** | **خمسٌ في شاشةٍ واحدة**، والسادسة تحتها |
--
-- فالسكة أقصر بـ٢٨٠ بكسل، **وثمنها أن خمساً من ستٍّ لا تُقرأ**.
--
-- ── ولماذا هذا فرقُ غرضٍ لا فرقُ ذوق ───────────────────────────────────────
--
-- السكة تصلح لما **يُقارَن ويُنتقى منه واحد**: مسارٌ من تسعة، فئةٌ من أربع،
-- خدمةٌ من ستّ — والزائر يسحب لأنه **يبحث عن واحدةٍ بعينها**. أما الضمانات
-- فتُقرأ **مجموعةً**: سؤال العميل «إيه اللي هاخده؟» وجوابه القائمة كلها. ومن
-- رأى ضمانةً واحدة لا يعرف أن تحتها خمساً، ولا سبب عنده ليسحب.
--
-- 🔒 **والتصميم نفسه يقول هذا ولا يُستنتج استنتاجاً:** `assets/css/style.css`
--    يعطي `.rail` لـ`#fleet` و`#routes` (وشريط الآراء)، **ويترك `#promise`
--    قائمةً رأسية عادية** (`.gua__list`: شارةٌ صغيرة ثم `<h3>` ثم `<p>`، بلا
--    صندوق). أي أن حزمة التصميم المعتمدة فرّقت بين القسمين بنفس هذه القسمة.
--
-- **والقرار يبقى لبدر:** الشكلان مبنيّان كلاهما (`rail` و`compact` رمزان في
-- `FEATURES_LAYOUT_TOKENS`)، وتبديلهما **قائمةٌ واحدة في المنشئ** لا نشرةُ كود.
-- وهذه الهجرة تشحن التوصية، لا تُغلق الباب.
--
-- ── وما لا تفعله هذه الهجرة ────────────────────────────────────────────────
--
-- 🔴 **لا تمسّ «الحجز في ثلاث خطوات».** الصفّان من نوع `features` ولا يفرّق
--    بينهما إلا هذا الرمز نفسه (`0073`)، فالبذرة مشروطةٌ بالعنوان **وبغياب
--    المفتاح** معاً، والفحص §(ب) يثبت أن صفّ الخطوات خرج منها كما دخل.
--
-- 🔒 ولا يتغيّر حرفٌ من نصّ المالك: العنوان والبنود الستة ونصوصها كما هي
--    بايتاً ببايت — يتغيّر **شكل** عرضها وحده.
--
-- ⚠ ولا كتالوج يُلمس: `styleKeys` تعيش في `lib/page-builder-types.ts` ولا عمود
--   لها في `block_registry` (المكتوب في `0073` حرفاً). فهذه بذرةُ محتوى.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) البذرة — إضافةٌ بـ`||` داخل `style` فلا يُمسّ `_v` ولا مقبضٌ ضبطه المالك
-- ----------------------------------------------------------------------------

update public.sections s
set content = jsonb_set(
      s.content,
      '{style}',
      coalesce(s.content->'style', '{}'::jsonb) || jsonb_build_object('featuresLayout', 'compact'),
      true
    )
from public.pages p
where p.id = s.page_id
  and p.kind = 'home'
  and s.type = 'features'
  and s.content->>'title' = 'ست ضمانات مكتوبة'
  and not (coalesce(s.content->'style', '{}'::jsonb) ? 'featuresLayout');

-- ----------------------------------------------------------------------------
-- (٢) الفحص الذاتي
-- ----------------------------------------------------------------------------

do $$
declare
  v_compact integer;
  v_steps   integer;
  v_stray   integer;
  v_broken  integer;
begin
  select count(*) into v_compact
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.kind = 'home' and s.type = 'features'
    and s.content->>'title' = 'ست ضمانات مكتوبة'
    and s.content->'style'->>'featuresLayout' = 'compact';

  -- (ب) 🔴 صفّ الخطوات لم يُمسّ — وهو الخطر الوحيد الحقيقي هنا: النوع واحد
  select count(*) into v_steps
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.kind = 'home' and s.type = 'features'
    and s.content->>'title' = 'الحجز في ثلاث خطوات'
    and s.content->'style'->>'featuresLayout' = 'steps';

  if v_steps <> 1 then
    raise exception '0074: صفّ «الحجز في ثلاث خطوات» لم يعد يحمل steps — البذرة تجاوزت شرطها';
  end if;

  -- (ج) ولا صفَّ ثالثاً اكتسب رمزاً من هذه الهجرة
  select count(*) into v_stray
  from public.sections s
  where s.type = 'features'
    and s.content->>'title' not in ('ست ضمانات مكتوبة', 'الحجز في ثلاث خطوات')
    and s.content->'style' ? 'featuresLayout';

  if v_stray <> 0 then
    raise exception '0074: % صفّ features آخر اكتسب رمز الشكل', v_stray;
  end if;

  -- (د) كل كتل features الظاهرة ما زالت تُصيَّر — نفس بوابة النشر لا نسخةً منها
  select count(*) into v_broken
  from public.sections s
  where s.type = 'features' and s.visible
    and not public.block_renders(s.type, coalesce(s.content, '{}'::jsonb));

  if v_broken <> 0 then
    raise exception '0074: % كتلة features ظاهرة ولا تُصيَّر بعد البذرة', v_broken;
  end if;

  if v_compact = 0 then
    raise notice 'ℹ 0074: لا صفَّ بعنوان «ست ضمانات مكتوبة» بلا رمز — لم يُبذَر شيء';
  else
    raise notice '✔ 0074: الضمانات compact · الخطوات steps · ولا صفَّ ثالثاً مُسّ';
  end if;
end;
$$;
