-- ============================================================================
-- 0063 — لوحة التصميم تُبذَر في `site_settings`، فيملكها المالك ويظهر بها الموقع
--
-- ── المشكلة التي تصلحها هذه الهجرة، مقيسةً لا موصوفة ────────────────────────
--
-- فتح المالك الموقع فقال: «ما زال التصميم القديم». وقياس الصفحة الحيّة أعطى
-- السبب في سطر واحد — سمة `<html>` كانت تحمل:
--
--     --primary: oklch(0.65 0.15 250)      ← **أزرق**
--
-- وطبقةُ الرموز في `app/globals.css` كانت **تشتقّ** لوحة التصميم كلها من هذا
-- اللون بصيغة `oklch(from var(--primary) L C h)`. فخرجت أرضية الموقع
-- `oklch(.956 .013 250)` — أبيضَ مُزرقاً، والتصميم رملٌ دافئ (#F4F0E7). ولم يكن
-- في CSS أي مخرج: القيمة تُحقن **سطرياً** على `<html>`، والسطري يسبق `:root`
-- دائماً. أي أن ثلاثة مفاتيح في هذا الصفّ كانت تمحو هوية التصميم كلها.
--
-- ── والتصحيح: القيم قيمُ التصميم، والمكان هو القاعدة ────────────────────────
--
-- تُنقل ألوان التصميم السبعة عشر **كما هي حرفاً**، وتعيش **هنا** لا في CSS.
-- فيجتمع الثلاثة الذي بدا متعارضاً:
--   • الموقع يشبه التصميم — لأن القيم قيمُه بلا اشتقاق ولا إعادة حساب.
--   • المالك يغيّرها من `/admin/settings` — لأنها صفٌّ لا سطرُ كود (شرطه الذي
--     لا يُتفاوض عليه).
--   • نسخة الـwhite-label تُعاد صبغتها بـ`update` على هذا الصفّ لا بتفريع
--     المستودع (المرحلة ١٤).
--
-- ── 🔴 ما تغيّر من بيانات المالك — مكتوبٌ كي يستطيع الرجوع ───────────────────
--
--   المفتاح                | قبل                          | بعد
--   -----------------------|------------------------------|----------
--   colors.primary         | oklch(0.65 0.15 250)   أزرق  | #D89A3E  (كهرمان التصميم)
--   colors.primaryForeground| oklch(0.985 0 0)   شبه أبيض | #1A1206  (حبر التصميم)
--   colors.accent          | oklch(0.8533 0.15 153.53) أخضر| #2E9184 (نيل التصميم)
--   + أربعة عشر مفتاحاً جديداً (الأرضيات والنصوص والخطر) لم تكن موجودة أصلاً.
--
-- و`name` و`tagline` و`logoUrl` **لا تُمسّ** — هي بيانات المالك ولا شأن للتصميم
-- بها. وللرجوع: `update public.site_settings set value = jsonb_set(value,
-- '{colors}', '{"primary":"oklch(0.65 0.15 250)","primaryForeground":
-- "oklch(0.985 0 0)","accent":"oklch(0.8533 0.15 153.53)"}'::jsonb)
-- where key = 'brand';`
--
-- ── لماذا الشرط `not (colors ? 'ink')` وليس `do update` مطلقاً ──────────────
--
-- الهجرة تصحّح **مرّة واحدة**: ما دامت اللوحة ثلاثة مفاتيح فهي الحالة المعطوبة
-- التي نصلحها. فإذا صارت سبعة عشر — سواء بهذه الهجرة أو بحفظةٍ من اللوحة — فقد
-- صار الصفّ اختيارَ المالك، وإعادةُ تنفيذ الملف يجب ألا تمحوه. وهذه هي قاعدة
-- `0061` نفسها («لا تمحُ ما بدّله المالك») مطبَّقةً على صفٍّ لا بدّ من تصحيحه.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) البذرة — تُدمج فوق `colors` ولا تلمس بقيّة مفاتيح `brand`
--
-- والقيم منقولة من كتلة `:root` في
-- `Tours-02/landing/assets/css/style.css` — وهي نفسها المكتوبة في
-- `DESIGN_PALETTE` في `lib/site-config.ts` وفي `:root` في `app/globals.css`.
-- الثلاثة تتطابق عمداً: القاعدة مصدرٌ حيّ، والملفّان احتياطيّان لا ينفرد أحدهما.
-- ----------------------------------------------------------------------------

update public.site_settings
set value = jsonb_set(
  value,
  '{colors}',
  '{
     "primary":            "#D89A3E",
     "primaryForeground":  "#1A1206",
     "primaryHi":          "#EDB45B",
     "accent":             "#2E9184",
     "accentSoft":         "#1B4A45",
     "ink":                "#08100F",
     "ink1":               "#0D1917",
     "ink2":               "#142522",
     "inkLine":            "#21322E",
     "sand":               "#F4F0E7",
     "sand2":              "#FFFFFF",
     "sandLine":           "#E0D8C8",
     "onInk":              "#F3F1EB",
     "onInkMut":           "#9FB2AC",
     "onSand":             "#16201D",
     "onSandMut":          "#55635E",
     "danger":             "#D64545"
   }'::jsonb,
  true
)
where key = 'brand'
  and not (coalesce(value -> 'colors', '{}'::jsonb) ? 'ink');

-- الصفّ قد لا يكون موجوداً أصلاً في قاعدة نظيفة — تُبذَر العلامة كاملةً حينها.
-- (‏`0002_seed_settings` يبذر `brand`، وهذا يحرس ترتيب التنفيذ لا أكثر.)
insert into public.site_settings (key, value) values
  ('brand', '{
     "name": "منصة النقل السياحي",
     "tagline": "خدمات نقل سياحي موثوقة في جميع أنحاء مصر",
     "logoUrl": null,
     "colors": {
       "primary": "#D89A3E", "primaryForeground": "#1A1206", "primaryHi": "#EDB45B",
       "accent": "#2E9184", "accentSoft": "#1B4A45",
       "ink": "#08100F", "ink1": "#0D1917", "ink2": "#142522", "inkLine": "#21322E",
       "sand": "#F4F0E7", "sand2": "#FFFFFF", "sandLine": "#E0D8C8",
       "onInk": "#F3F1EB", "onInkMut": "#9FB2AC", "onSand": "#16201D", "onSandMut": "#55635E",
       "danger": "#D64545"
     }
   }'::jsonb)
on conflict (key) do nothing;

-- ----------------------------------------------------------------------------
-- (٢) الفحص الذاتي — يحرس ما كان قائماً لا ما أضفناه (القاعدة الذهبية ١٠)
--
-- ثلاثة أحكام: اللوحة سبعة عشر مفتاحاً تماماً، وكلّها قيمُ ألوان لا نصٌّ حرّ
-- (الحقل يُحقن سمةً سطرية على `<html>`، فقيمةٌ فيها `;` تعبث بتنسيق كل صفحة)،
-- و**اسم العلامة لم يُمسّ** — وهو الحكم الذي يمسك خطأ الدمج لو أخطأ `jsonb_set`
-- المسار فاستبدل `brand` كلّه بدل `colors` وحدها.
-- ----------------------------------------------------------------------------

do $$
declare
  v_colors jsonb;
  v_name   text;
  v_n      integer;
  v_bad    text;
begin
  select value -> 'colors', value ->> 'name'
    into v_colors, v_name
  from public.site_settings
  where key = 'brand';

  if v_colors is null then
    raise exception '0063: لا صفّ brand في site_settings بعد الهجرة';
  end if;

  select count(*) into v_n from jsonb_object_keys(v_colors);
  if v_n <> 17 then
    raise exception '0063: اللوحة % مفتاحاً والمنتظر ١٧', v_n;
  end if;

  -- كل قيمة لونٌ صالح: خانات ست عشرية أو دالّة لون. والمجموعة هي نفسها التي
  -- يفرضها `safeColorValue` في `lib/site-config.ts` — فلا يمرّ من القاعدة ما
  -- سيرفضه الكود صامتاً فيسقط الرمز إلى الاحتياطي بلا أن يشكو أحد.
  select string_agg(key, ', ') into v_bad
  from jsonb_each_text(v_colors)
  where value !~ '^[A-Za-z0-9#%.,()/+\- ]{1,72}$';

  if v_bad is not null then
    raise exception '0063: قيم ألوان غير صالحة في: %', v_bad;
  end if;

  if coalesce(v_name, '') = '' then
    raise exception '0063: اسم العلامة ضاع — الدمج استبدل brand بدل colors';
  end if;

  raise notice '0063 OK — لوحة التصميم (١٧ لوناً) في القاعدة، واسم العلامة «%» سليم', v_name;
end $$;
