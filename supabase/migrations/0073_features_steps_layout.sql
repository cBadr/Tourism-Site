-- ============================================================================
-- 0073 — «الحجز في ثلاث خطوات» تصير خطواتٍ على مسار: رمزُ شكلٍ واحد في
--        `content.style`، وبلا حرفٍ واحد يُمسّ من نصّ المالك
--
-- ── الشكوى المقيسة ─────────────────────────────────────────────────────────
--
-- بدر، بعد أن فتح الموقع على هاتفه: «الحجز في ثلاث خطوات… أري أنها مختلفة
-- تماماً في الموقع حالياً عن الموجود في Tours-02».
--
-- والفرق مقيسٌ لا انطباعي. التصميم (`#how` في `index.html`) يعطي القسم أربعة
-- أشياء لا يحمل الموقعُ **واحداً** منها:
--
--   ١) رقمٌ في قرص لكل خطوة (`.step__dot > b.num`) — لا أيقونة
--   ٢) خطٌّ يربط الخطوات: رأسيٌّ على الجوال وموجةٌ أفقية على المكتب
--   ٣) سيارةٌ تسير على الخط فتبلغ نهايته — فيُقرأ اتجاه الإجراء
--   ٤) بلا بطاقة: النصّ عارٍ على أرضية القسم
--
-- وما في الموقع اليوم: ثلاث بطاقاتٍ متطابقة، أيقونة `CircleCheck` نفسها في
-- ثلاثتها، بلا رقمٍ وبلا رابطٍ بين خطوةٍ وتاليتها. أي أن الزائر يقرأ **قائمة
-- مزايا** لا **إجراءً متتابعاً** — وهو خطأُ معنى لا خطأُ ذوق.
--
-- ── ولماذا رمزٌ في `style` لا كتلةٌ جديدة اسمها `steps` ────────────────────
--
-- الرئيسية تحمل **صفَّي `features`** بالبنية نفسها حرفاً:
--   • sort=5 «الحجز في ثلاث خطوات» — ٣ عناصر
--   • sort=7 «ست ضمانات مكتوبة»   — ٦ عناصر
-- ويختلفان في **شكل العرض وحده**. فلو حُوِّلت العارضة كلها إلى مسارٍ مرقَّم
-- لصارت الضمانات الست «خطوات» يُقرأ ترتيبها إجراءً — وهو عطلٌ في المعنى.
--
-- وكتلةٌ جديدة كانت تكلّف: صفّاً في `block_registry`، وسطراً في
-- `page_builder_tests.sql`، **وترحيلَ الصفّ الحيّ من نوعٍ إلى نوع** — أي
-- `sections.id` جديداً ⇒ **فقدان كل ترجمات الكتلة**، لأن مفاتيح
-- `namespace='section'` كلها مبنيّة عليه (المكتوب في `lib/page-builder-types.ts`
-- §٧ حرفاً). والثمن كله لا يشتري حقلاً واحداً لا يحمله `features` اليوم:
-- الترقيم **موضعيّ** (`index + 1`) لا حقلاً يُكتب.
--
-- 🔒 **و`style` مفتاحٌ محجوزٌ بالاسم** في `i18n_reserved_content_key` منذ
--    `0058`: لا يدخل فهرس الترجمة ولا يستبدله `i18n_apply`. فلا صفَّ ترجمةٍ
--    واحداً لقيمةٍ مثل «steps»، ولا عمودَ جديد في السجل، ولا حارسَ يُمسّ.
--
-- ⚠ **ولا يتغيّر عدد صفوف الكتالوج ولا حقولها**: `styleKeys` تعيش في
--   `lib/page-builder-types.ts` وحدها ولا عمود لها في `block_registry` —
--   فهذه الهجرة **بذرةُ محتوىً لا تعديلُ كتالوج**.
--
-- ── والبذرة مشروطة بثلاثة شروط، كلٌّ منها يمنع ضرراً مختلفاً ────────────────
--
--   • `not (content->'style' ? 'featuresLayout')` — من ضبط الشكل من اللوحة لا
--     تُعاد بذرته فوقه (سابقة `0064` و`0071` حرفاً).
--   • **والعنوان ما زال هو العنوان** الذي بُني عليه القرار. فإن بدّله المالك
--     منذ كتابة هذه الهجرة لا يُبذَر شيء ويبقى الصفّ بطاقاتٍ كما هو — لأن
--     «هذا القسم إجراءٌ متتابع» حكمٌ على **هذا النصّ** لا على كل صفّ `features`.
--   • **وصفحة الرئيسية وحدها**: أي صفّ `features` في صفحةٍ أخرى لا يُمسّ.
--
-- 🔒 **وما يقرؤه الزائر من نصّ = ما كان يقرؤه قبلها بايتاً ببايت.** لا عنوان
--    يتغيّر ولا بند ولا ترتيب — يتغيّر **شكل** عرضها وحده.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) البذرة — إضافةٌ بـ`||` داخل `style` لا استبدالٌ للمفتاح، فلا يُمسّ `_v`
--     ولا أي مقبض تنسيقٍ ضبطه المالك على الصفّ نفسه.
-- ----------------------------------------------------------------------------

update public.sections s
set content = jsonb_set(
      s.content,
      '{style}',
      coalesce(s.content->'style', '{}'::jsonb) || jsonb_build_object('featuresLayout', 'steps'),
      true
    )
from public.pages p
where p.id = s.page_id
  and p.kind = 'home'
  and s.type = 'features'
  and s.content->>'title' = 'الحجز في ثلاث خطوات'
  and not (coalesce(s.content->'style', '{}'::jsonb) ? 'featuresLayout');

-- ----------------------------------------------------------------------------
-- (٢) الفحص الذاتي — الرمز وصل، وجارُه لم يُمسّ، والكتلة ما زالت تُصيَّر
-- ----------------------------------------------------------------------------

do $$
declare
  v_steps  integer;
  v_others integer;
  v_rows   integer;
begin
  -- (أ) صفّ الخطوات يحمل الرمز — أو لا وجود له أصلاً (عنوانٌ بدّله المالك)
  select count(*) into v_steps
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.kind = 'home' and s.type = 'features'
    and s.content->>'title' = 'الحجز في ثلاث خطوات'
    and s.content->'style'->>'featuresLayout' = 'steps';

  -- (ب) 🔴 **ولا صفَّ `features` آخر لمسه شيء.** «ست ضمانات مكتوبة» تبقى
  --     بطاقاتٍ — وهو الفرق الذي وُلد هذا الرمز لأجله.
  select count(*) into v_others
  from public.sections s
  where s.type = 'features'
    and s.content->>'title' is distinct from 'الحجز في ثلاث خطوات'
    and s.content->'style' ? 'featuresLayout';

  if v_others <> 0 then
    raise exception '0073: % صفّ features آخر اكتسب رمز الشكل — البذرة تجاوزت شرطها', v_others;
  end if;

  -- (ج) الكتلة تُصيَّر بمحتواها بعد البذرة — نفس بوابة النشر لا نسخةً منها
  select count(*) into v_rows
  from public.sections s
  where s.type = 'features' and s.visible
    and not public.block_renders(s.type, coalesce(s.content, '{}'::jsonb));

  if v_rows <> 0 then
    raise exception '0073: % كتلة features ظاهرة ولا تُصيَّر بعد البذرة', v_rows;
  end if;

  if v_steps = 0 then
    raise notice 'ℹ 0073: لا صفَّ بعنوان «الحجز في ثلاث خطوات» — لم يُبذَر شيء، والصفوف بحالها';
  else
    raise notice '✔ 0073: صفّ الخطوات يحمل featuresLayout=steps، وبقية features بطاقات كما هي';
  end if;
end;
$$;
