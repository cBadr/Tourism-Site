-- ============================================================================
-- 0072 — تنويه الشعارات يستعيد خانته: حقلٌ مستقلّ لا يشارك النثر التسويقي مكانه
--
-- ── العطل المقيس ───────────────────────────────────────────────────────────
--
-- `0061` أنشأت كتلة `logo-strip` بحقلين نصّيين `{title, note}`، وكتبت بجانب
-- الصفّ سبب وجود الثاني حرفياً: «و`note` شرط استعمالٍ لا زخرف — وصفٌ للمركبات
-- لا اعتماد ولا علاقة تجارية». و`0062` بذرت فيه الجملة نفسها. ثم — بينهما وبين
-- اليوم — **كُتب فوقه نثرٌ تسويقي**، والصفّ الحيّ عند كتابة هذه الهجرة:
--
--     note = 'نقوم بتوفير كافة الموديلات المطلوبة بسائقين محترفين …'
--
-- فاختفى التنويه من الصفحة الحيّة **بلا خطأ ولا سجلّ ولا فحصٍ يمسكه**: الحقل
-- ممتلئ، والكتلة تُصيَّر، والبوابة خضراء. وما ضاع ليس جملةً بل **إقرارٌ بأن
-- الشعارات تصف طرازات المركبات المتاحة عبر المتعهدين، لا رعايةً ولا شراكةً مع
-- الشركات المصنِّعة** — وهو ما يُسأل عنه صاحب الموقع لا كاتب النصّ.
--
-- ── والعلاج ليس إعادة الجملة إلى مكانها ────────────────────────────────────
--
-- إعادتها تمحو نثر المالك، **وتترك العطل قائماً**: الخانة واحدة، فالتحرير
-- التالي يمحو التنويه مرةً أخرى بنفس الطريقة الصامتة. فالخانة تُقسَم:
--
--     note        ← نثرٌ تحريري يملكه المالك: يُكتب ويُفرَّغ ويختفي بالفراغ
--     disclaimer  ← شرط الاستعمال: **يُعاد صياغته ولا يُفرَّغ**
--
-- و«لا يُفرَّغ» تُنفَّذ في العارضة لا هنا (`components/sections/logo-strip.tsx`):
-- الفارغ يعود إلى النصّ الافتراضي بدل أن يُخفي السطر. فالمالك يملك **الصياغة**
-- ولا يملك **الحذف** — وهذا بعينه معنى «شرطٌ لا زخرف» الذي كتبته `0061`.
--
-- ── ولا يُبذَر شيء في `sections` ───────────────────────────────────────────
--
-- صفّ الرئيسية **لا يُمسّ**: العارضة تعرض الافتراضي حين يغيب المفتاح، والمنشئ
-- يعرض الحقل فارغاً قابلاً للكتابة لأن الشاشة تشتقّ حقولها من `text_fields` لا
-- من مفاتيح الصفّ. فالتنويه يظهر ويُحرَّر بلا كتابةٍ واحدة على محتوى المالك.
--
-- ⚠ عدد صفوف الكتالوج يبقى ١٩، و`block_registry_check` لا تُلمس: `disclaimer`
--   اسمٌ بسيط قابل للعنونة، وجملةٌ يقولها إنسان — فيدخل فهرس الترجمة كأي نثر.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) السجل — والترتيب جزءٌ من العقد: التنويه بعد الملاحظة، كما يُقرآن أسفل
--     الشريط، وكما يقارنهما `page_builder_tests.sql` §(أ) مرتّبين.
-- ----------------------------------------------------------------------------

update public.block_registry
set text_fields = array['title', 'note', 'disclaimer']
where type = 'logo-strip';

comment on table public.block_registry is
  'كتالوج كتل منشئ الصفحات — مرآة BLOCK_CATALOGUE في lib/page-builder-types.ts. '
  'و«logo-strip.disclaimer» شرط استعمالٍ لا نثر: العارضة تعيد نصّه الافتراضي '
  'عند الفراغ، فالمالك يملك صياغته ولا يملك حذفه.';

-- ----------------------------------------------------------------------------
-- (٢) الفحص الذاتي — الشكل، والحارس البنيوي، وأن أحداً لم يُمسّ صفوف المحتوى
-- ----------------------------------------------------------------------------

do $$
declare
  v_fields text[];
  v_reason text;
  v_rows   integer;
begin
  select text_fields into v_fields from public.block_registry where type = 'logo-strip';
  if v_fields is distinct from array['title', 'note', 'disclaimer'] then
    raise exception '0072: حقول logo-strip النصّية لم تصل إلى شكل العقد — %', v_fields;
  end if;

  select public.block_registry_check(type, role, placement, accepts_children, max_children,
                                     text_fields, item_fields, required_fields,
                                     non_text_fields, non_text_item_fields)
    into v_reason
  from public.block_registry where type = 'logo-strip';
  if v_reason is not null then
    raise exception '0072: الحارس البنيوي رفض صفّ logo-strip بعد التوسيع — %', v_reason;
  end if;

  select count(*) into v_rows from public.block_registry;
  if v_rows <> 19 then
    raise exception '0072: الكتالوج صار % كتلة لا ١٩', v_rows;
  end if;

  -- والكتلة ما زالت تُصيَّر بمحتواها الحيّ كما هو — بلا بذرةٍ ولا كتابة
  if exists (
    select 1 from public.sections s
    where s.type = 'logo-strip' and s.visible
      and not public.block_renders(s.type, coalesce(s.content, '{}'::jsonb))
  ) then
    raise exception '0072: كتلة logo-strip ظاهرة ولا تُصيَّر بعد التوسيع';
  end if;

  raise notice '✔ 0072: logo-strip = {title, note, disclaimer} — وصفوف المحتوى بلا مساس';
end;
$$;
