-- ============================================================================
-- 0096 — نصُّ الرابط يصف وجهته: اسمُ العلامة يخرج من تسميات التذييل الثماني
--
-- ══════════════════════════════════════════════════════════════════════════
--  🔴 ما قِيس على الصفحة الحيّة (‏`curl` على `/` ثم عدُّ النصّ المُصيَّر)
-- ══════════════════════════════════════════════════════════════════════════
--
-- اسمُ العلامة يظهر **١٢ مرة** في نصّ كل صفحة من صفحات الموقع، وموضعُ ١١ منها
-- ليس المحتوى بل **قشرة الموقع**:
--
--   • الترويسة  ١ (‏الشعار — صحيح ومطلوب)
--   • المتن     ١ (‏`<h1>` — صحيح ومطلوب، وهو ما تقصده قاعدة «مرةً في h1»)
--   • التذييل  ١٠ ⇐ **ومنها ٨ في نصوص روابط عمود «مسارات شائعة»**
--
-- و`components/site/footer.tsx:231-233` يضع `label: page.title` حرفاً، وثمانيةٌ
-- من تسميات المسارات التسع تبدأ بـ«ايجار ليموزين». فالنتيجة **نصُّ رابطٍ مكرَّر
-- على مستوى الموقع كله**: ٨ روابط × ٢٣ صفحة، تبدأ كلها بنفس الثلاثة عشر حرفاً.
--
-- 🔴 **وهذا بعينه ما تسمّيه سياسات جوجل للسبام حشوَ كلماتٍ مفتاحية** — إشارةٌ
--    سالبة لا موجبة. وهو في الوقت نفسه **عيبُ إتاحةٍ وتصميم**: من يتنقّل بقارئ
--    شاشة يسمع «ايجار ليموزين من…» ثماني مرات قبل أن يبلغ ما يفرّق بينها، ومن
--    ينظر إلى العمود على شاشة ٣٧٥ يرى ثمانية أسطر متطابقة البدايات.
--
-- ══════════════════════════════════════════════════════════════════════════
--  ما تفعله — والحدُّ الذي لا تتجاوزه
-- ══════════════════════════════════════════════════════════════════════════
--
-- `pages.title` **تسميةُ تنقّلٍ** (‏التذييل · الشريط العلوي عبر `0094` · قائمة
-- `/admin/content`)، فتصير وصفاً للوجهة وحدها: «من القاهرة إلى الإسكندرية».
--
-- 🔒 **و`page-hero.title` لا يُمسّ**: هو `<h1>` الصفحة، واسمُ العلامة فيه **مرةً
--    واحدة** هو الموضع المشروع الذي تقصده القاعدة. فالصفحة لا تفقد ذكراً واحداً
--    من المواضع التي تبني الهوية — تفقد **تكراراً في نصّ رابطٍ** لا يبني شيئاً.
--
-- ⚠ **و`meta.title` غير متأثر:** التسعة كلها تحمل وصفاً خاصاً بها، و
--   `generateMetadata` في `app/(site)/routes/[slug]` يقرأ `meta.title` أولاً —
--   فسقوطُه إلى `pages.title` فرضٌ لا يقع على صفحةٍ من هذه التسع.
--
-- ⚠ **ولا مفتاح ترجمةٍ يتغيّر:** العنوان `page/<id>.title` مبنيٌّ على معرّف
--   الصفحة لا على نصّها (‏`0018`) — فالنصّ يُستبدل والعنوان في مكانه.
--
-- 📌 **وما بقي بيد بدر — وهو نصفُ العدد الباقي:** `brand.tagline` =
--    «ايجار ليموزين المطار و بين المحافظات و جولات سياحية» تُصيَّر في التذييل
--    **تحت** الشعار مباشرةً، فيُقرأ الاسم مرتين متلاصقتين. ومعها خطأُ تنسيق
--    («‏و بين» و«و جولات» — مسافةٌ بعد واو العطف). وهي `site_settings` لا صفَّ
--    محتوى (‏`SITE-CONTENT` ٨/٥).
-- ============================================================================

create temporary table _pagekeys_before_96 on commit drop as
select k from public.i18n_corpus_rows() where ns = 'page';

update public.pages
set title = btrim(replace(title, 'ايجار ليموزين ', ''))
where kind = 'corridor'
  and title like 'ايجار ليموزين %';

do $$
declare
  v_bad text;
  v_n   integer;
begin
  -- (١) صفر تسميةِ تنقّلٍ تحمل اسم العلامة — في كل الأنواع لا في المسارات وحدها
  select string_agg(slug, ', ') into v_bad
  from public.pages where title like '%ايجار ليموزين%';
  if v_bad is not null then
    raise exception '0096: تسميةُ تنقّلٍ ما زالت تحمل اسم العلامة — %', v_bad;
  end if;

  -- (٢) 🔒 والشاهد على ما **يجب أن يبقى**: `<h1>` كل مسار يحمل الاسم مرةً
  --     (‏وثمانيةٌ لا تسعة: `cairo-airport` عنوانها بلا اسمٍ أصلاً ومقصودةٌ كذلك)
  select count(*) into v_n
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.kind = 'corridor'
    and s.type = 'page-hero'
    and s.content ->> 'title' like 'ايجار ليموزين %';
  if v_n <> 8 then
    raise exception '0096: عنواناتُ h1 الحاملة لاسم العلامة % لا ٨ — الهجرة مسّت المتن', v_n;
  end if;

  -- (٣) وتسمياتُ التذييل مميَّزةٌ بعضها من بعض (‏نصُّ رابطٍ يصف وجهته)
  select string_agg(t.title, ' | ') into v_bad
  from (select title, count(*) n from public.pages where kind = 'corridor'
        group by title having count(*) > 1) t;
  if v_bad is not null then
    raise exception '0096: تسميتان متطابقتان في عمود المسارات — %', v_bad;
  end if;

  -- (٤) ولا تسميةَ فارغةٍ ولا أطولَ من ٣٥ حرفاً (‏عمودُ تذييلٍ على ٣٧٥ بكسل)
  select string_agg(slug || ':' || length(title), ', ') into v_bad
  from public.pages
  where kind = 'corridor' and (btrim(title) = '' or length(title) > 35);
  if v_bad is not null then
    raise exception '0096: تسميةٌ فارغة أو أطول من ٣٥ حرفاً — %', v_bad;
  end if;

  -- (٥) وكل مسارٍ ما زال يحمل `meta.title` خاصاً به، فلا سقوطَ إلى التسمية
  select string_agg(slug, ', ') into v_bad
  from public.pages
  where kind = 'corridor' and coalesce(btrim(meta ->> 'title'), '') = '';
  if v_bad is not null then
    raise exception '0096: مسارٌ بلا meta.title يسقط إلى تسمية التنقّل — %', v_bad;
  end if;

  -- (٦) وصفر مفتاح ترجمةٍ فُقد: العنوان معرّفُ الصفحة لا نصُّها
  select string_agg(a.k, ', ') into v_bad
  from (select k from _pagekeys_before_96
        except
        select k from public.i18n_corpus_rows() where ns = 'page') a;
  if v_bad is not null then
    raise exception '0096: مفتاحُ صفحةٍ فُقد بتغيير التسمية — %', v_bad;
  end if;

  raise notice '✔ 0096: تسميات التنقّل تصف وجهاتها · ٨ عناوين h1 ما زالت تحمل الاسم مرةً · صفر مفتاح مفقود';
end;
$$;
