-- ============================================================================
-- 0064 — وسائط البطل تصل إلى صفّ القسم، فتُطلب الأصول المحوَّلة فعلاً
--
-- ── المشكلة ────────────────────────────────────────────────────────────────
--
-- حوّلت م‑٣ تسع عشرة صورة إلى `public/img/*.avif` (‏٧٤٤ ك.ب مجموعها بعد وفرٍ
-- ٨٠–٨٩٪ مقيسٍ بـVMAF)، وبَنَت `components/motion/hero-video.tsx` كاملاً
-- بشروطه الأربعة. **ولم يشر إليها سطرٌ واحد.** قياسٌ على الصفحة الحيّة:
-- صفر `.avif` في HTML، وصفر استيراد لـ`HeroVideo` في المستودع كله. أي أن
-- الأصول شُحنت والمستهلك لم يُبنَ — فبقي البطل توهّجاً ملوّناً حيث يضع التصميم
-- صورة السائق.
--
-- ── ولماذا في صفّ القسم لا في العارضة ──────────────────────────────────────
--
-- القيد غير القابل للتفاوض: «التحكم في كامل الموقع من لوحة التحكم». ومسارٌ
-- محفور في JSX يعني أن نسخة الـwhite-label الثانية تُطلق بصورة الأولى في
-- كل صفحة (‏D-01). فالمسارات **بيانات**، والمالك يبدّلها من المنشئ.
--
-- والحقول الأربعة **غير نصّية** ولا تدخل فهرس الترجمة — إلا `imageAlt`، وهي
-- نصٌّ يُقرأ بقارئ الشاشة فيُترجم كأي نصّ. (‏`block_registry.text_fields` هو ما
-- يغذّي الفهرس، ولذلك تُضاف `imageAlt` وحدها إليه في §٢ أدناه.)
--
-- ⚠ **ولا تُلمس `block_registry_check`**: الدالة تفحص أسماء الحقول النصية
--    والإلزامية، ولا تعترض حقلاً **غير نصّي واختياري** في `content`. فلا حاجة
--    إلى توسيع `v_non_text`، ولا يتغيّر عدد الصفوف (١٥) الذي تحرسه `0061` §٣.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) صفّ البطل في الرئيسية — تُدمج الوسائط ولا يُمسّ نصٌّ قائم
--
-- `||` دمجٌ سطحي على المستوى الأعلى: يضيف المفاتيح الأربعة ويُبقي `headline`
-- و`sub` و`badge` و`scrollLabel` و`items` كما كتبها المالك حرفاً.
--
-- والشرط `not (content ? 'src')`: من بدّل الصورة من اللوحة لا تُعاد بذرته.
-- ----------------------------------------------------------------------------

update public.sections s
set content = s.content || jsonb_build_object(
  'src',      '/img/hero-chauffeur.avif',
  -- النصّ البديل منقولٌ من `index.html:189` في حزمة التصميم بلا اختصار: قارئ
  -- الشاشة يجب أن ينال ما يناله المبصر من المشهد، لا كلمة «صورة».
  'imageAlt', 'سائق بزيّ رسمي وقفازين يفتح باب سيارة سوداء فاخرة استعداداً لاستقبال راكب',
  'poster',   '/img/hero-video-poster.avif',
  'video',    '/video/hero-loop.mp4'
)
from public.pages p
where p.id = s.page_id
  and p.slug = 'home'
  and s.type = 'hero'
  and not (s.content ? 'src');

-- ----------------------------------------------------------------------------
-- (٢) `imageAlt` في سجل الكتل — كي يظهر حقلاً في المنشئ ويدخل فهرس الترجمة
--
-- والثلاثة الأخرى **لا تُضاف** إلى `text_fields` بقصد: مسارُ ملفٍّ ليس نصّاً
-- يُترجَم، وإدخاله الفهرس يضع «‎/img/hero-chauffeur.avif» في طابور المترجم —
-- وأسوأ من ذلك: مترجمٌ مجتهد قد «يعرّبه» فتختفي الصورة.
--
-- ⚠ والترتيب يوافق `BLOCK_CATALOGUE` في `lib/page-builder-types.ts` حرفاً،
--    لأن `supabase/tests/page_builder_tests.sql` يفحص التطابق ويسقط على الانحراف.
-- ----------------------------------------------------------------------------

update public.block_registry
set text_fields = array['badge', 'headline', 'sub', 'scrollLabel', 'imageAlt']
where type = 'hero';

-- ----------------------------------------------------------------------------
-- (٣) الفحص الذاتي
-- ----------------------------------------------------------------------------

do $$
declare
  v_content jsonb;
  v_bad     text;
begin
  select s.content into v_content
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.slug = 'home' and s.type = 'hero';

  if v_content is null then
    raise exception '0064: لا كتلة hero في الرئيسية';
  end if;

  if not (v_content ? 'src' and v_content ? 'poster' and v_content ? 'video') then
    raise exception '0064: وسائط البطل لم تُكتب — %', v_content;
  end if;

  -- النصّ القائم لم يُمحَ: الدمج `||` سطحي، وخطؤه الوحيد المتصوَّر هو استبدال
  -- الكائن كله. وغياب `headline` هو ما يكشف ذلك فوراً.
  if coalesce(v_content ->> 'headline', '') = '' then
    raise exception '0064: عنوان البطل ضاع — الدمج استبدل content بدل أن يضيف';
  end if;

  -- المسارات داخلية لا مطلقة: `safeMediaSrc` في الكود يرفض ما عداها، فلا
  -- يُبذَر في القاعدة ما سيُسقطه العرض صامتاً.
  select string_agg(key, ', ') into v_bad
  from jsonb_each_text(v_content)
  where key in ('src', 'poster', 'video')
    and (value !~ '^/[^/]' or value like '%:%');

  if v_bad is not null then
    raise exception '0064: مسارات غير داخلية في: %', v_bad;
  end if;

  raise notice '0064 OK — وسائط البطل في صفّ القسم، والنصّ سليم';
end $$;
