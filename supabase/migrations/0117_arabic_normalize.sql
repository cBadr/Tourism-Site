-- ============================================================================
-- 0117_arabic_normalize.sql
-- تطبيعُ العربية للبحث: «الإسكندرية» و«والاسكندرية» و«الاسكندريّة» شيءٌ واحد
-- ============================================================================
--
-- ── لماذا هذا الملف موجود ─────────────────────────────────────────────────
--
-- شكا المالك (2026-08-18) أن شاشة مراجعة الترجمة **بلا بحث**. والبحث في نصٍّ
-- عربيٍّ بلا تطبيعٍ يفشل صامتاً: يكتب ما يراه على الشاشة فلا يجد شيئاً، فيظن
-- أن الصف غير موجود ويكتبه من جديد.
--
-- 🔴 **والمقيس على هذه القاعدة نفسها، لا المفترض:**
--
--     select to_tsvector('arabic', 'الإسكندرية والاسكندرية');
--     ⇒ 'اسكندر':1 'والاسكندر':2
--
--   أي أن **مُجذِّر Postgres العربي يعطي المدينة الواحدة جذرين مختلفين** —
--   لأنه يجذّر ولا يطبّع: لا يوحّد الهمزات، ولا يفكّ بادئة الواو. فالاعتماد
--   عليه وحده يترك الشكوى قائمة. ⇒ التطبيع يسبق أي بحثٍ ولا يُستغنى عنه به.
--
-- ── لماذا في SQL لا في TypeScript وحدها ────────────────────────────────────
--
-- قرار المالك: «ابنِ دالة التطبيع الآن كأساس، وأجّل نظام البحث الأوسع». والأساس
-- إن سكن في مكوّن شاشةٍ واحدة لم يَعُد أساساً — يُنسخ في ثالثِ موضعٍ يحتاجه
-- (بحث الأماكن، بحث الحجوزات، بحث المحتوى) فتتفرّق النسخ. فموضعُه القاعدة:
-- كلُّ من يقرأ هذه القاعدة يراه، و`immutable` تجعله صالحاً **لفهرسٍ دالّي**
-- يوم يصير البحث على مليون صف بدل تسعمئة.
--
-- ── ولماذا بلا امتداد واحد ─────────────────────────────────────────────────
--
-- `pg_trgm` و`unaccent` و`fuzzystrmatch` متاحةٌ في هذا المشروع **وغير مثبَّتة**.
-- ولا واحدَ منها يلزم هنا:
--
--   • `unaccent` يزيل علاماتٍ لاتينية؛ وتشكيلُ العربية ليس منها — يُزال
--     بـ`regexp_replace` على مدىً محدَّد بالضبط، بلا قاموسٍ ولا امتداد.
--   • `pg_trgm` يخدم **التقاربَ** (`similarity`) والفهرسة، لا التطبيع.
--     ويبقى الباب مفتوحاً له: `arabic_search_key` مرشَّحٌ صريحٌ لفهرس
--     `gin (... gin_trgm_ops)` يوم يُبنى البحث الأوسع.
--   • `fuzzystrmatch` صُمِّم لأصواتٍ إنجليزية (soundex/metaphone) — لا معنى له
--     على العربية.
--
-- ⇒ فتثبيتُ امتدادٍ على قاعدة الإنتاج **لا يشتري شيئاً اليوم**، والتطبيع أدناه
--    نصٌّ خالص: `translate` و`regexp_replace` و`lower`، كلُّها في النواة.
--
-- ── ما تفعله الدوال الثلاث ─────────────────────────────────────────────────
--
--   normalize_arabic(t)     تطبيعُ حروفٍ محضٌ: همزات ← ا · ة ← ه · ى ← ي ·
--                           ؤ ← و · ئ ← ي · فارسيّة ک ی ← ك ي · حذف التشكيل
--                           والتطويل والمحارف الصفرية · أرقام عربية ← لاتينية ·
--                           تصغير اللاتينية · ضغط الفراغات.
--   arabic_strip_clitics(w) **كلمةٌ واحدة**: حذف بادئات «و» و«ال» و«بال/كال/
--                           لال/فال» بحرصٍ مشروحٍ أدناه.
--   arabic_search_key(t)    ما يُقارَن فعلاً: التطبيع + إسقاط الترقيم +
--                           تجريدُ كل كلمةٍ من بادئاتها.
--
-- ── 🔴 القرار الذي يمنع أن يفسد التجريدُ أسماءً ────────────────────────────
--
-- المجرِّدات الساذجة تحذف «ل» و«ب» و«ك» أينما وقعت في أول الكلمة، فتصير
-- **«لبنان» ⇐ «بنان» ⇐ «نان»**. وهنا لا تُحذف هذه الأربعة **إلا متبوعةً بـ«ال»**
-- («بالقاهرة» ⇐ «القاهرة» ⇐ «قاهره»): موضعٌ لا لبس فيه. و«لبنان» تخرج كما
-- دخلت. أما «و» فتُحذف وحدها لأنها العطف الغالب («والإسكندرية»).
--
-- وحدٌّ أدنى للباقي في كل حالة، فلا تتحول كلمةٌ قصيرة إلى حرفين بلا معنى.
--
-- ⚠ **والبادئة التي لم تُجرَّد لا تكسر البحث** — المطابقة بالاحتواء، والبادئة
--   في **أول** الكلمة: «لرحلة» تحتوي «رحله». التجريد يلزم للاتجاه المعاكس
--   وحده: أن يكتب هو البادئة ولا تكون في النص.
--
-- ── التوأم في الواجهة ──────────────────────────────────────────────────────
--
-- 🔴 `app/admin/languages/_components/arabic-search.ts` **نسخةٌ حرفيةٌ من هذه
--    القواعد بـTypeScript**، لأن الشاشة تبحث في صفوفٍ محمَّلةٍ سلفاً في ذاكرة
--    الخادم فلا تحتمل رحلةً إلى القاعدة لكل صف. ومن غيّر واحدةً غيّر الأخرى.
--    والمجموعة `supabase/tests/arabic_normalize_tests.sql` تثبّت الحالات
--    نفسها المكتوبة في ترويسة ذلك الملف — فمن كسر الاتفاق كسر المجموعة.
--
-- ── لا صفَّ بياناتٍ يُلمس ──────────────────────────────────────────────────
--
-- هذه الهجرة **دوالٌّ فقط**: لا جدول، ولا عمود، ولا `update`، ولا سياسة. تُطبَّق
-- على قاعدةٍ حيّة فلا يتغيّر فيها صفٌّ واحد.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (١) التطبيع الحرفي
-- ----------------------------------------------------------------------------
--
-- الترتيب مقصود: تُحذف العلاماتُ أولاً (كي تلتحم الكلمة المشكولة والممطوطة)، ثم
-- تُصغَّر اللاتينية، ثم تُبدَّل الحروف، ثم تُضغط الفراغات.
--
-- مدى العلامات المحذوفة — **مكتوبٌ بـ`\uXXXX` لا بمحارف ملصوقة**:
--   \u064b-\u065f  التشكيل (فتحة ... سكون) وعلاماتٌ ملحقة
--   \u0670         الألف الخنجرية
--   \u06d6-\u06ed  علامات الوقف والتجويد
--   \u0640         التطويل
--   \u200b-\u200f  المحارف الصفرية وعلامات الاتجاه
--   \u202a-\u202e  إحاطة الاتجاه
--   \u2066-\u2069  العزل الاتجاهي
--   \ufeff         علامة ترتيب البايتات
--
-- ⚠ **ولا يُلصق محرفٌ غير مرئيٍّ في هذا الملف.** (`languages-ui.tsx` حمل يوماً
--   بايت `NUL` فصار `grep` يتخطّاه كملفٍّ ثنائي، ولا أحد يرى ما لا يُطبع.)
create or replace function public.normalize_arabic(p_text text)
returns text
language sql
immutable
strict
parallel safe
as $$
  select btrim(
    regexp_replace(
      translate(
        lower(
          regexp_replace(
            p_text,
            '[\u064b-\u065f\u0670\u06d6-\u06ed\u0640\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]',
            '',
            'g')),
        'أإآٱؤئةىکی٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹',
        'ااااويهيكي01234567890123456789'),
      '[\s\u00a0]+',
      ' ',
      'g'));
$$;

comment on function public.normalize_arabic(text) is
  'تطبيع نصٍّ عربي للمقارنة والبحث: توحيد الهمزات والتاء المربوطة والألف المقصورة، وحذف التشكيل والتطويل والمحارف الصفرية، وتوحيد الأرقام، وتصغير اللاتينية، وضغط الفراغات. حرفيٌّ محض — لا يحذف كلمةً ولا يجذّر.';

-- ----------------------------------------------------------------------------
-- (٢) تجريد بادئات كلمةٍ واحدة
-- ----------------------------------------------------------------------------
--
-- تُستدعى على كلمةٍ **مطبَّعةٍ سلفاً** (بلا تشكيل ولا همزات). والحلقة ثلاثُ
-- دوراتٍ على الأكثر: «وبالقاهرة» ⇐ «بالقاهرة» ⇐ «القاهرة» ⇐ «قاهره».
create or replace function public.arabic_strip_clitics(p_word text)
returns text
language plpgsql
immutable
strict
parallel safe
as $$
declare
  v_word text := p_word;
  i      integer;
begin
  for i in 1..3 loop
    if v_word ~ '^و' and length(v_word) >= 4 then
      -- واو العطف وحدها: «والاسكندريه» ⇐ «الاسكندريه»
      v_word := substr(v_word, 2);
    elsif v_word ~ '^[بكلف]ال' and length(v_word) >= 6 then
      -- ب/ك/ل/ف **متبوعةً بأل وحدها** — موضعٌ لا لبس فيه: «بالقاهره»
      v_word := substr(v_word, 2);
    elsif v_word ~ '^ال' and length(v_word) >= 5 then
      -- أداة التعريف: «القاهره» ⇐ «قاهره»
      v_word := substr(v_word, 3);
    else
      exit;
    end if;
  end loop;
  return v_word;
end;
$$;

comment on function public.arabic_strip_clitics(text) is
  'تجريد كلمةٍ عربيةٍ مطبَّعةٍ من بادئات «و» و«ال» و«بال/كال/لال/فال». ب/ك/ل/ف لا تُحذف إلا متبوعةً بأل حتى لا تصير «لبنان» «نان».';

-- ----------------------------------------------------------------------------
-- (٣) مفتاح البحث — ما يُقارَن فعلاً
-- ----------------------------------------------------------------------------
--
-- كلُّ ما ليس حرفاً عربياً (\u0600-\u06ff) ولا لاتينياً صغيراً ولا رقماً يصير
-- فاصلاً: فـ«انستا-باي» و«انستا باي» يصيران كلمتين في الحالتين، ويتكفّل مطابِقُ
-- الواجهة بحذف الفراغ بينهما («انستاباي» تجدهما).
create or replace function public.arabic_search_key(p_text text)
returns text
language sql
immutable
strict
parallel safe
as $$
  select coalesce(
    (select string_agg(public.arabic_strip_clitics(w.word), ' ' order by w.ord)
       from unnest(
              regexp_split_to_array(
                regexp_replace(
                  public.normalize_arabic(p_text),
                  '[^\u0600-\u06ffa-z0-9]+',
                  ' ',
                  'g'),
                ' ')
            ) with ordinality as w(word, ord)
      where w.word <> ''),
    '');
$$;

comment on function public.arabic_search_key(text) is
  'مفتاح المقارنة للبحث العربي: normalize_arabic ثم إسقاط الترقيم ثم تجريد بادئات كل كلمة. immutable — صالحٌ لفهرسٍ دالّي يوم يكبر البحث.';

-- ----------------------------------------------------------------------------
-- (٤) الصلاحيات — دوالُّ نصٍّ خالص لا تقرأ صفاً، والحدُّ الأدنى مع ذلك
-- ----------------------------------------------------------------------------
--
-- لا `anon`: لا مستهلكَ عاماً لها اليوم. ويوم يُبنى بحثٌ للزوّار تُمنح صراحةً
-- في هجرته هو، فيبقى سببُ المنح مقروناً بمن طلبه.
revoke all on function public.normalize_arabic(text)      from public, anon;
revoke all on function public.arabic_strip_clitics(text)  from public, anon;
revoke all on function public.arabic_search_key(text)     from public, anon;

grant execute on function public.normalize_arabic(text)     to authenticated, service_role;
grant execute on function public.arabic_strip_clitics(text) to authenticated, service_role;
grant execute on function public.arabic_search_key(text)    to authenticated, service_role;
