-- ---------------------------------------------------------------------------
-- (٨) حرّاسٌ تُفشل الهجرةَ نفسها — لا فحصٌ يُقرأ بعد الحقيقة
-- ---------------------------------------------------------------------------

do $$
declare
  v_count integer;
  v_bad   text;
begin
  -- (أ) كل كتلة تعبر بوابة النشر `block_renders` — وإلا صُيِّرت `null` صامتةً
  select string_agg(s.type || ':' || s.id::text, ', ')
    into v_bad
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.slug in ('terms','privacy','refund-policy','about','contact','faq')
    and s.visible
    and not public.block_renders(s.type, s.content);
  if v_bad is not null then
    raise exception 'كتل لا تُصيَّر بعد الهجرة: %', v_bad;
  end if;

  -- (ب) كتلة `once-per-page` لا تتكرر — وهو مانع النشر `duplicate-singleton`
  --     مقيساً هنا مباشرةً، لأن `page_publish_blockers` محروسةٌ بـ`is_admin()`
  --     («هذه القراءة للوحة وحدها») فلا تُنادى من هجرة.
  select string_agg(d.slug || ':' || d.type, ', ') into v_bad
  from (
    select p.slug, s.type
    from public.sections s
    join public.pages p on p.id = s.page_id
    join public.block_registry r on r.type = s.type
    where p.slug in ('terms','privacy','refund-policy','about','contact','faq')
      and r.placement = 'once-per-page'
    group by p.slug, s.type
    having count(*) > 1
  ) d;
  if v_bad is not null then
    raise exception 'كتلة once-per-page مكررة: %', v_bad;
  end if;

  -- (ج) مرساة كل بند فريدة داخل صفحتها — مرساتان متطابقتان تعنيان رابطاً يكذب
  select count(*) into v_count from (
    select s.page_id,
           case when coalesce(s.content->>'anchor','') ~ '^[a-z][a-z0-9-]{0,39}$'
                then s.content->>'anchor' else 'c-' || s.id::text end as anchor
    from public.sections s
    join public.pages p on p.id = s.page_id
    where p.slug in ('terms','privacy','refund-policy','about','contact','faq')
      and s.type = 'clause'
    group by 1, 2 having count(*) > 1
  ) dup;
  if v_count > 0 then
    raise exception 'مراسٍ مكررة داخل صفحة واحدة: % مجموعة', v_count;
  end if;

  -- (د) صفحة الأسئلة ما زالت تحمل ١٢ سؤالاً في كتلة `faq` **واحدة**
  select count(*) into v_count
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.slug = 'faq' and s.type = 'faq';
  if v_count <> 1 then
    raise exception 'صفحة الأسئلة يجب أن تحمل كتلة faq واحدة (عقدة FAQPage واحدة)، وُجد %', v_count;
  end if;

  select jsonb_array_length(s.content->'items') into v_count
  from public.sections s
  join public.pages p on p.id = s.page_id
  where p.slug = 'faq' and s.type = 'faq';
  if v_count <> 12 then
    raise exception 'عدد أسئلة صفحة الأسئلة يجب أن يبقى ١٢، وُجد %', v_count;
  end if;

  -- (هـ) 🔴 الأرقام الملزِمة في سياسة الاسترداد — شاهدٌ نصّي على أنها لم تتبدّل
  select count(*) into v_count
  from public.sections s
  join public.pages p on p.id = s.page_id
  cross join lateral jsonb_array_elements(s.content->'items') as item
  where p.slug = 'refund-policy' and s.type = 'table'
    and (item->>'c1', item->>'c2') in (
      ('مشاوير المدينة واستقبال المطارات',                '٢٤ ساعة على الأقل'),
      ('السفر بين المحافظات والجولات السياحية',           '٤٨ ساعة على الأقل'),
      ('المناسبات والمؤتمرات والأفواج',                   '٧٢ ساعة على الأقل'),
      ('من ٢٤ إلى ١٢ ساعة',                              '٢٥٪'),
      ('من ١٢ إلى ٤ ساعات',                              '٥٠٪'),
      ('من ٧٢ إلى ٤٨ ساعة',                              '٢٥٪'),
      ('من ٤٨ إلى ٢٤ ساعة',                              '٥٠٪'),
      ('التحويلات الفورية',                              'حتى ٣ أيام عمل'),
      ('الحوالات البنكية',                               'حتى ٧ أيام عمل')
    );
  if v_count <> 9 then
    raise exception 'أرقام سياسة الاسترداد المنقولة إلى الجداول = % من ٩', v_count;
  end if;

  -- (و) وأرقام الانتظار المجاني في الشروط — ١٥ · ٣٠ · ٦٠
  select count(*) into v_count
  from public.sections s
  join public.pages p on p.id = s.page_id
  cross join lateral jsonb_array_elements(s.content->'items') as item
  where p.slug = 'terms' and s.type = 'table'
    and item->>'c1' in ('المشاوير داخل المدينة','الرحلات بين المحافظات','استقبال المطارات')
    and (item->>'c2' like '١٥ دقيقة%' or item->>'c2' like '٣٠ دقيقة%' or item->>'c2' like '٦٠ دقيقة%');
  if v_count <> 3 then
    raise exception 'أرقام الانتظار المجاني في الشروط = % من ٣', v_count;
  end if;

  raise notice '0069 — الصفحات الست أُعيد بناؤها: كل الكتل تُصيَّر، صفر مانع نشر، والأرقام مطابقة.';
end $$;
