-- ============================================================================
-- 0086 — تعميق درجتَي الإشارة في اللوحة الفاتحة، بعد قياسٍ على الصفحة الحيّة
--
-- ── لماذا هجرةٌ ثانية بدل تصحيح `0085` ──────────────────────────────────────
--
-- `0085` **مُطبَّقة ومسجَّلة** في `schema_migrations`. وتعديل ملفها لا يُعيد
-- تشغيله، فيبقى الصفّ في القاعدة على القيم القديمة بينما يقول الملفّ غيرها —
-- وهو أسوأ من الخطأ نفسه: انحرافٌ صامت بين ما يُقرأ وما يُنفَّذ. والقاعدة
-- مكتوبة في `CLAUDE.md` («لا تُعدَّل هجرةٌ مطبَّقة») ولها هذا السبب بعينه.
--
-- ── وما الذي تغيّر، ولماذا لم يُمسَك في `0085` ──────────────────────────────
--
--   primary : #8A5A14 → #7A4E10
--   accent  : #136B60 → #0F5F55
--   primaryHi: #6E4610 → #5C3A0C   (ليبقى تحت `primary` بخطوةٍ مرئية)
--
-- القيمتان الأوليان **تعبران AA عاريتين**: الكهرمان 5.24:1 والنيل 5.65:1 فوق
-- الرمل. والجدول العاري هو ما قِيس في `0085`، وكان ناقصاً.
--
-- ثم مُسحت أربع عشرة صفحة **حيّة** بحاسبٍ يقرأ اللون المحسوب لكل عنصر نصّي
-- ويركّب كل شفافية فوق أرضيتها الفعلية، فظهر استعمالان يسقطان:
--
--   · شارة العنوان الفرعي — `bg-primary/10` مع `text-primary` = **4.37:1**.
--     والسبب بنيوي لا عرضي: التِنت يزحف بالأرضية **نحو** لون النص، فيقلّ
--     الفرق. أي أن لوناً يعبر فوق الرمل قد يسقط فوق تِنتٍ من نفسه.
--   · `text-primary/80` في فهرس `/terms` = **3.86:1**.
--
-- 🔴 **والدرس أعمّ من الرقمين**: لونٌ مضبوطٌ على حدّ AA بالضبط ليس مضبوطاً —
-- كل `‎/opacity‎` أو تِنتٍ فوقه يأكل الفارق. فيُترك هامشٌ فوق الحدّ لا يُلامَس.
-- والمقيس بعد التعميق: الشارة **5.51** والنصّ العاري **6.37**.
--
-- ── والشرط: لا يُمسّ ما بدّله المالك ────────────────────────────────────────
--
-- التحديث مشروطٌ بأن تكون القيمة **هي بالضبط** ما بذرته `0085`. فمالكٌ فتح
-- `/admin/settings` وضبط كهرمانه بيده بين الهجرتين يبقى اختياره كما هو — وهي
-- قاعدة `0061` و`0063` نفسها: الهجرة تصحّح بذرتها، لا اختيار المالك.
-- ============================================================================

update public.site_settings
set value = jsonb_set(value, '{colorsLight,primary}', '"#7A4E10"'::jsonb, true)
where key = 'brand'
  and value #>> '{colorsLight,primary}' = '#8A5A14';

update public.site_settings
set value = jsonb_set(value, '{colorsLight,primaryHi}', '"#5C3A0C"'::jsonb, true)
where key = 'brand'
  and value #>> '{colorsLight,primaryHi}' = '#6E4610';

update public.site_settings
set value = jsonb_set(value, '{colorsLight,accent}', '"#0F5F55"'::jsonb, true)
where key = 'brand'
  and value #>> '{colorsLight,accent}' = '#136B60';
