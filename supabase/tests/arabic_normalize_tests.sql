-- (أ) **العلاقة التي وُجدت الدوال من أجلها**: «الإسكندرية» و«الاسكندرية»
--     و«والاسكندرية» و«الاسْـكندريّة» شيءٌ واحد عند البحث. وهي علاقةٌ لا رقم —
--     تصمد مهما تغيّر محتوى الموقع.
