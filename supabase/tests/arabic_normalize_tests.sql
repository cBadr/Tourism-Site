-- ----------------------------------------------------------------------------
-- (٠) الشروط المسبقة — هجرة 0117 مطبَّقة؟
-- ----------------------------------------------------------------------------
do $$
declare
  v_missing text;
begin
  select string_agg(x.sig, '، ')
    into v_missing
  from (values
    ('public.normalize_arabic(text)'),
    ('public.arabic_strip_clitics(text)'),
    ('public.arabic_search_key(text)')
  ) as x(sig)
  where to_regprocedure(x.sig) is null;

  if v_missing is not null then
    raise exception 'دوالُّ التطبيع غير موجودة (%) — نفّذ pnpm db:migrate أولاً', v_missing;
  end if;

  raise notice '✔ (٠) الدوال الثلاث موجودة';
end;
$$;

-- ----------------------------------------------------------------------------
-- (أ) التطبيع الحرفي — ما يجب أن يتساوى بعد normalize_arabic
-- ----------------------------------------------------------------------------
do $$
declare
  r record;
  v_a text;
  v_b text;
begin
  for r in
    select *
    from (values
      -- الهمزات: الشكوى الأصلية
      ('الإسكندرية',            'الاسكندرية',   'همزة تحت الألف'),
      ('آمن',                   'امن',          'ألف ممدودة'),
      ('أحمد',                  'احمد',         'همزة فوق الألف'),
      -- التاء المربوطة والألف المقصورة
      ('رحلة',                  'رحله',         'تاء مربوطة'),
      ('مصطفى',                 'مصطفي',        'ألف مقصورة'),
      -- الهمزة على الواو والياء
      ('مؤسسة',                 'موسسه',        'همزة على الواو'),
      ('قائمة',                 'قايمه',        'همزة على الياء'),
      -- التشكيل والتطويل والمحارف الصفرية (تُبنى بـchr لا تُلصق)
      ('الاسْكَنْدَريّة',            'الاسكندريه',   'تشكيل'),
      ('الاس' || chr(1600) || chr(1600) || 'كندرية',
                                'الاسكندريه',   'تطويل'),
      ('الاسكندرية' || chr(8203), 'الاسكندريه', 'محرف صفري'),
      -- الأرقام واللاتينية والفراغات
      ('٢٠٢٥',                  '2025',         'أرقام عربية'),
      ('TEST',                  'test',         'تصغير اللاتينية'),
      ('رحلة' || chr(160) || chr(160) || 'خاصة',
                                'رحله خاصه',    'فراغ غير فاصل ومكرر'),
      -- الحروف الفارسية التي تشبه العربية
      ('کتاب',                  'كتاب',         'كاف فارسية'),
      ('یوم',                   'يوم',          'ياء فارسية')
    ) as t(a, b, why)
  loop
    v_a := public.normalize_arabic(r.a);
    v_b := public.normalize_arabic(r.b);
    if v_a is distinct from v_b then
      raise exception '(أ) «%» ≠ «%» بعد التطبيع (%) — الناتجان: «%» و«%»',
        r.a, r.b, r.why, v_a, v_b;
    end if;
  end loop;

  raise notice '✔ (أ) التطبيع الحرفي: الهمزات والتاء والألف المقصورة والتشكيل والتطويل والأرقام والفارسية';
end;
$$;

-- ----------------------------------------------------------------------------
-- (ب) تجريد البادئات — ما يجب أن يتساوى، **وما يجب ألا يُمسّ**
-- ----------------------------------------------------------------------------
do $$
declare
  r record;
  v_a text;
  v_b text;
begin
  -- (ب-١) ما يجب أن يتساوى بعد arabic_search_key
  for r in
    select *
    from (values
      ('والاسكندرية',  'الإسكندرية',  'واو العطف'),
      ('الإسكندرية',   'اسكندرية',    'أداة التعريف'),
      ('بالقاهرة',     'القاهرة',     'باء + أل'),
      ('وبالقاهرة',    'قاهرة',       'واو + باء + أل'),
      ('انستا-باي',    'انستا باي',   'الشرطة فاصل'),
      ('  رحلة  ',     'رحلة',        'فراغ محيط')
    ) as t(a, b, why)
  loop
    v_a := public.arabic_search_key(r.a);
    v_b := public.arabic_search_key(r.b);
    if v_a is distinct from v_b then
      raise exception '(ب-١) «%» ≠ «%» في مفتاح البحث (%) — «%» مقابل «%»',
        r.a, r.b, r.why, v_a, v_b;
    end if;
  end loop;

  -- (ب-٢) 🔴 الحدّ: اسمٌ يبدأ بحرفٍ يشبه البادئة **لا يُقصّ**
  --       لو حُذف شرط «متبوعةً بأل» صارت «لبنان» ⇐ «نان» وفشل هذا الفحص.
  for r in
    select *
    from (values
      ('لبنان',  'لبنان',  'لام أصلية لا بادئة'),
      ('بنات',   'بنات',   'باء أصلية'),
      ('كتاب',   'كتاب',   'كاف أصلية'),
      ('الله',   'الله',   'أقصر من الحدّ الأدنى'),
      ('ولد',    'ولد',    'واو أصلية في كلمةٍ قصيرة')
    ) as t(a, expected, why)
  loop
    v_a := public.arabic_search_key(r.a);
    if v_a is distinct from public.normalize_arabic(r.expected) then
      raise exception '(ب-٢) 🔴 «%» تغيّرت إلى «%» (%) — التجريد يأكل حروفاً أصلية',
        r.a, v_a, r.why;
    end if;
  end loop;

  raise notice '✔ (ب) البادئات: و/ال/بال تُجرَّد · ولبنان وبنات وكتاب والله تخرج كما دخلت';
end;
$$;

-- ----------------------------------------------------------------------------
-- (ج) الخصائص التي تجعل الدوال صالحةً لفهرسٍ دالّي لاحقاً
-- ----------------------------------------------------------------------------
do $$
declare
  r record;
begin
  for r in
    select p.proname, p.provolatile, p.proisstrict
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in ('normalize_arabic', 'arabic_strip_clitics', 'arabic_search_key')
  loop
    if r.provolatile <> 'i' then
      raise exception '(ج) % ليست immutable (%) — لا تصلح لفهرسٍ دالّي', r.proname, r.provolatile;
    end if;
    if not r.proisstrict then
      raise exception '(ج) % ليست strict — null يجب أن يعود null لا سلسلةً فارغة', r.proname;
    end if;
  end loop;

  if public.normalize_arabic(null) is not null then
    raise exception '(ج) normalize_arabic(null) ليست null';
  end if;
  if public.arabic_search_key('') <> '' then
    raise exception '(ج) arabic_search_key('''') يجب أن تكون سلسلةً فارغة لا null';
  end if;

  raise notice '✔ (ج) الثلاث immutable وstrict · null ⇒ null · '''' ⇒ ''''';
end;
$$;

-- ----------------------------------------------------------------------------
-- (د) 🔴 لماذا لا يكفي مُجذِّر Postgres العربي — يُقاس لا يُروى
-- ----------------------------------------------------------------------------
do $$
declare
  v_ts text;
begin
  if exists (select 1 from pg_ts_config where cfgname = 'arabic') then
    v_ts := to_tsvector('arabic', 'الإسكندرية والاسكندرية')::text;

    -- المدينة الواحدة تعطي جذرين ⇒ البحث بها يفشل بلا تطبيع
    if v_ts !~ 'اسكندر' or position(' ' in v_ts) = 0 then
      raise notice 'ℹ (د) مخرَج المجذّر تغيّر: % — أعِد قراءة مبرّر 0117', v_ts;
    end if;

    -- والتطبيع يوحّدهما فعلاً
    if public.arabic_search_key('الإسكندرية') <> public.arabic_search_key('والاسكندرية') then
      raise exception '(د) 🔴 التطبيع نفسه لم يوحّد المدينة — العلّة التي وُجد لها قائمة';
    end if;

    raise notice '✔ (د) المجذّر يعطي جذرين لمدينةٍ واحدة (%) — والتطبيع يوحّدهما', v_ts;
  else
    raise notice 'ℹ (د) تهيئة النص العربية غير موجودة — تُخطّى المقارنة مع المجذّر';
  end if;
end;
$$;

