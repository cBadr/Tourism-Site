--
-- لا صفَّ فيكسترة، ولا `set role`، ولا جدولاً مؤقتاً. كلُّ ما يقيسه ثلاثُ دوالٍّ
-- `immutable` على سلاسل نصٍّ حرفية. (والسبب مقيس: جولةُ `db:test` أبرقت يوماً
