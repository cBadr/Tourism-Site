-- (ب) **الحدّ الذي يمنع فساد الأسماء**: «لبنان» تبقى «لبنان». ولو حذف أحدٌ
--     شرطَ «متبوعةً بأل» من `arabic_strip_clitics` لصارت «نان» وفشلت (ب-١).
--
-- (ج) **العقد مع التوأم في الواجهة**: كل حالةٍ هنا مكتوبةٌ حرفياً في ترويسة
--     `app/admin/languages/_components/arabic-search.ts`. فمن غيّر SQL وحدها
--     كسر هذه المجموعة، ومن غيّر TypeScript وحدها ترك الاثنين يفترقان صامتاً
--     — ولذلك الحالات هنا **هي** قائمة المطابقة هناك، لا عيّنةٌ منها.
--
-- (د) 🔴 **لماذا لا يكفي مُجذِّر Postgres العربي** — يُقاس هنا لا يُروى:
--     `to_tsvector('arabic', …)` يعطي «الإسكندرية» و«والاسكندرية» **جذرين
--     مختلفين**. فمن اقترح غداً الاستغناء عن التطبيع بـ`tsvector` يرى الرقم.
--
-- المرجع: `0117_arabic_normalize.sql`.
